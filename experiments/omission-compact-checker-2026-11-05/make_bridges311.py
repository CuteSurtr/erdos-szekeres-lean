#!/usr/bin/env python3
"""Write CompactChecker/Bridge311Res.lean and CompactChecker/Bridge311Bal.lean (6 November 2026).

The bridges turn the root exclusion of each compact export (an `FFeas` statement over an
FCat catalog) into the exact arithmetic statement that the ES(8) <= 311 assembly consumes:

* residual: the body of `OmissionResidual32Bridge2650.Excludes2650Zero budget`
  (experiments/omission-residual32-bridge2650-2026-10-11/Residual32Bridge2650/Rows.lean:98);
* balanced: the body of `OmissionBalanced.ExcludesHoleBudget budget`
  (experiments/omission-global-assembly-2026-10-10/BalancedBudgets.lean:9).

Catalog identities are decided by the kernel in 128-row chunks: for every row, equal demand
and equal packed code in the reference catalog's base (big-integer comparisons, no Finset
normalization), then `rowCode_injective` gives equal supports. The 446 balanced cut rows have
no stored code, so their code is computed from the literal Finset.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "CompactChecker"

HEADER = "-- Generated by make_bridges311.py; do not edit by hand.\n"


def chunks(total, size=128):
    k = 0
    while k * size < total:
        yield k, k * size, min(size, total - k * size)
        k += 1


def combine(prop, total, prefix):
    """Proof of `∀ r : Fin total, prop r.val r.isLt` from the chunk theorems."""
    nchunks = (total + 127) // 128
    lines = [f"theorem {prefix}_all : ∀ r : Fin {total}, {prop} r.val r.isLt := by",
             "  intro ⟨r, hr⟩",
             f"  show {prop} r hr",
             f"  obtain ⟨k, hk, j, hj, rfl⟩ : ∃ k < {nchunks}, ∃ j < 128, r = 128 * k + j :=",
             "    ⟨r / 128, by omega, r % 128, Nat.mod_lt _ (by omega), by omega⟩",
             "  interval_cases k"]
    for k, start, _ in chunks(total):
        lines.append(f"  · exact {prop}.congr (by omega) ({prefix}{k} j (by omega))")
    return lines


COMMON = r"""
/-- Row codes determine supports for every base above one (as `rowCode_injective` in
`Residual32Bridge2650/Matches.lean`). -/
theorem rowCode_injective' {n b : ℕ} (hb : 1 < b) {s t : Finset (Fin n)}
    (h : rowCode b s = rowCode b t) : s = t := by
  have e : ∀ u : Finset (Fin n), rowCode b u = pack b (fun i => if i ∈ u then 1 else 0) := by
    intro u
    simp only [rowCode, pack, ite_mul, one_mul, zero_mul]
    rw [Finset.sum_ite_mem, Finset.univ_inter]
  rw [e, e] at h
  have hf := pack_injective_of_lt hb
    (fun i => by by_cases hi : i ∈ s <;> simp [hi] <;> omega)
    (fun i => by by_cases hi : i ∈ t <;> simp [hi] <;> omega) h
  ext i
  have hi := congrFun hf i
  by_cases hs : i ∈ s <;> by_cases ht : i ∈ t <;> simp_all

/-- A row of a well-formed FCat whose code (recomputed in any base `B > 1`) is the
`rowCode` of `s` has support `s`. -/
theorem fsupp_eq_of_codeR {c : FCat} {n base0 B : ℕ} (hwf : c.wf n base0 = true)
    (hB : 1 < B) (r : ℕ) (s : Finset (Fin n)) (h : codeR B (c.get r).1 = rowCode B s) :
    fsupp c n r = s := by
  apply rowCode_injective' hB
  rw [← codeL_get_eq_rowCode c hwf B r, ← codeR_eq]
  exact h
"""


def residual():
    lines = [HEADER.rstrip(),
             "import CompactChecker.Path",
             "import CompactChecker.Fcat2650",
             "import Residual32Bridge2650.Catalog",
             "",
             "/-!",
             "# Residual adapter for the compact ES(8) ≤ 311 recheck",
             "",
             "`residual_of_root` turns the root exclusion of the compact residual export (the zero",
             "branch of state 0, mask `pmask (zerosF 154) [(0, 2)]`, over `fcat2650`) into the body of",
             "`OmissionResidual32Bridge2650.Excludes2650Zero budget`, which `Final313/Final.lean` and",
             "`Final311/Final.lean` consume as `residual_excludes_2650_zero` with budget 32.",
             "",
             "`fcat2650` is generated from the same source (`source-2650.json.gz`, uncompressed SHA-256",
             "`e800d5f8…`) as `Residual32Bridge2650.Catalog`; the identity of every row is decided below.",
             "-/",
             "",
             "open ErdosSzekeres.OmissionCertificates",
             "open scoped BigOperators",
             "",
             "namespace CompactChecker.Bridge311Res",
             "",
             "set_option maxRecDepth 100000",
             "set_option maxHeartbeats 100000000",
             COMMON,
             "/-- Row `r` of `fcat2650` has the demand and the base-2^17 code of row `r` of the",
             "literal 2,650-row catalog. -/",
             "abbrev ResRow (r : ℕ) (h : r < 2650) : Prop :=",
             "  fcat2650.dem r = OmissionResidual32Bridge2650.demand ⟨r, h⟩ ∧",
             "    codeR OmissionResidual32Bridge2650.base (fcat2650.get r).1 =",
             "      OmissionResidual32Bridge2650.code ⟨r, h⟩",
             "",
             "theorem ResRow.congr {a b : ℕ} (e : a = b) {ha : a < 2650} {hb : b < 2650}",
             "    (h : ResRow a ha) : ResRow b hb := by",
             "  subst e",
             "  exact h",
             ""]
    for k, start, size in chunks(2650):
        lines += [f"theorem res{k} : ∀ j (hj : j < {size}), ResRow ({start} + j) (by omega) := by",
                  "  decide +kernel", ""]
    lines += combine("ResRow", 2650, "res")
    lines += ["",
              "theorem res_support (r : Fin 2650) :",
              "    fsupp fcat2650 154 r.val = OmissionResidual32Bridge2650.support2650 r :=",
              "  fsupp_eq_of_codeR fcat2650_wf (by decide) r.val _",
              "    ((res_all r).2.trans (OmissionResidual32Bridge2650.code_correct r))",
              "",
              "theorem res_demand (r : Fin 2650) :",
              "    fcat2650.dem r.val = OmissionResidual32Bridge2650.demand2650 r := (res_all r).1",
              "",
              "/-- The residual adapter: the root exclusion of the compact residual export gives the",
              "body of `OmissionResidual32Bridge2650.Excludes2650Zero budget`. -/",
              "theorem residual_of_root {budget : ℕ}",
              "    (h : ¬ ∃ holes : Fin 154 → ℕ,",
              "      FFeas fcat2650 2650 154 budget (pmask (zerosF 154) [(0, 2)]) holes) :",
              "    ¬ ∃ holes : Fin 154 → ℕ, (∀ i, holes i ≤ 1) ∧ holes 0 = 0 ∧",
              "      (∀ r, OmissionResidual32Bridge2650.demand2650 r ≤",
              "        ∑ i ∈ OmissionResidual32Bridge2650.support2650 r, holes i) ∧",
              "      (∑ i, holes i) ≤ budget := by",
              "  rintro ⟨holes, hb, h0, hr, hc⟩",
              "  refine h ⟨holes, hb, fun r => ?_, hc, fun i hi => ?_, fun i hi => ?_⟩",
              "  · rw [res_support r, res_demand r]",
              "    exact hr r",
              "  · rcases mem_mset_zero_occupied 1 i hi with h1 | h1 <;> omega",
              "  · rcases mem_mset_zero_occupied 2 i hi with h1 | h1",
              "    · have : i = 0 := Fin.ext h1.1",
              "      rw [this]",
              "      exact h0",
              "    · omega",
              "",
              "#print axioms res_support",
              "#print axioms residual_of_root",
              "",
              "end CompactChecker.Bridge311Res"]
    return "\n".join(lines) + "\n"


def balanced():
    lines = [HEADER.rstrip(),
             "import CompactChecker.Path",
             "import CompactChecker.Fcat62",
             "import BalancedProof.Catalog",
             "import BalancedCoverCutsV2",
             "",
             "/-!",
             "# Fcat bridge for the compact ES(8) ≤ 311 recheck (balanced side)",
             "",
             "`balanced_of_root` turns the root exclusion of the compact balanced export (mask",
             "`pmask (zerosF 252) []`, over `fcat62`, the 3,131 rows of `balanced-v2-source.json`)",
             "into the body of `OmissionBalanced.ExcludesHoleBudget budget`, which",
             "`Final311/Final.lean` consumes (through `OmissionBalancedCover63.exclusion_transfer`)",
             "with budget 63.",
             "",
             "Rows 0–2684 of `fcat62` are the 2,685 rows of `BalancedProof.Catalog`; rows 2685–3130 are",
             "the 446 cut rows of `BalancedCoverCutsV2`, which `BalancedCoverCutsV2.all_rows` derives from",
             "the first 2,685 for 0/1 hole vectors. Both identities are decided below.",
             "-/",
             "",
             "open ErdosSzekeres.OmissionCertificates",
             "open scoped BigOperators",
             "",
             "namespace CompactChecker.Bridge311Bal",
             "",
             "set_option maxRecDepth 100000",
             "set_option maxHeartbeats 100000000",
             COMMON,
             "/-- Row `r < 2685` of `fcat62` has the demand and the base-2^25 code of row `r` of",
             "`BalancedProof.Catalog`. -/",
             "abbrev BaseRow (r : ℕ) (h : r < 2685) : Prop :=",
             "  fcat62.dem r = OmissionBalanced.demand ⟨r, h⟩ ∧",
             "    codeR OmissionBalanced.base (fcat62.get r).1 = OmissionBalanced.code ⟨r, h⟩",
             "",
             "theorem BaseRow.congr {a b : ℕ} (e : a = b) {ha : a < 2685} {hb : b < 2685}",
             "    (h : BaseRow a ha) : BaseRow b hb := by",
             "  subst e",
             "  exact h",
             "",
             "/-- Row `2685 + j` of `fcat62` is cut row `j` of `BalancedCoverCutsV2`: same demand,",
             "same base-2^22 code (computed from the literal Finset on the right). -/",
             "abbrev CutRow (j : ℕ) (h : j < 446) : Prop :=",
             "  fcat62.dem (2685 + j) = BalancedCoverCutsV2.demand ⟨j, h⟩ ∧",
             "    codeR 4194304 (fcat62.get (2685 + j)).1 =",
             "      rowCode 4194304 (BalancedCoverCutsV2.support ⟨j, h⟩)",
             "",
             "theorem CutRow.congr {a b : ℕ} (e : a = b) {ha : a < 446} {hb : b < 446}",
             "    (h : CutRow a ha) : CutRow b hb := by",
             "  subst e",
             "  exact h",
             ""]
    for k, start, size in chunks(2685):
        lines += [f"theorem base{k} : ∀ j (hj : j < {size}), BaseRow ({start} + j) (by omega) := by",
                  "  decide +kernel", ""]
    for k, start, size in chunks(446):
        lines += [f"theorem cut{k} : ∀ j (hj : j < {size}), CutRow ({start} + j) (by omega) := by",
                  "  decide +kernel", ""]
    lines += combine("BaseRow", 2685, "base")
    lines += [""]
    lines += combine("CutRow", 446, "cut")
    lines += ["",
              "/-- Every row of `fcat62` holds for a 0/1 vector that satisfies the 2,685 rows of",
              "`BalancedProof.Catalog`. -/",
              "theorem fcat62_rows (holes : Fin 252 → ℕ) (hbool : ∀ i, holes i ≤ 1)",
              "    (hrows : ∀ r : Fin 2685, OmissionBalanced.demand r ≤",
              "      ∑ i ∈ OmissionBalanced.support r, holes i) :",
              "    ∀ r : Fin 3131, fcat62.dem r.val ≤ ∑ i ∈ fsupp fcat62 252 r.val, holes i := by",
              "  intro ⟨r, hr⟩",
              "  by_cases h : r < 2685",
              "  · obtain ⟨hd, hc⟩ := base_all ⟨r, h⟩",
              "    have hs := fsupp_eq_of_codeR fcat62_wf (by decide) r _",
              "      (hc.trans (OmissionBalanced.code_correct ⟨r, h⟩))",
              "    show fcat62.dem r ≤ ∑ i ∈ fsupp fcat62 252 r, holes i",
              "    rw [hs, hd]",
              "    exact hrows ⟨r, h⟩",
              "  · have hj : r - 2685 < 446 := by omega",
              "    obtain ⟨hd, hc⟩ := cut_all ⟨r - 2685, hj⟩",
              "    have e : 2685 + (r - 2685) = r := by omega",
              "    simp only [e] at hd hc",
              "    have hs := fsupp_eq_of_codeR fcat62_wf (by decide) r _ hc",
              "    show fcat62.dem r ≤ ∑ i ∈ fsupp fcat62 252 r, holes i",
              "    rw [hs, hd]",
              "    exact BalancedCoverCutsV2.all_rows holes hbool hrows ⟨r - 2685, hj⟩",
              "",
              "/-- The Fcat bridge: the root exclusion of the compact balanced export gives the body",
              "of `OmissionBalanced.ExcludesHoleBudget budget`. -/",
              "theorem balanced_of_root {budget : ℕ}",
              "    (h : ¬ ∃ holes : Fin 252 → ℕ, FFeas fcat62 3131 252 budget (pmask (zerosF 252) []) holes) :",
              "    ¬ ∃ holes : Fin 252 → ℕ, (∀ i, holes i ≤ 1) ∧",
              "      (∀ r, OmissionBalanced.demand r ≤ ∑ i ∈ OmissionBalanced.support r, holes i) ∧",
              "      (∑ i, holes i) ≤ budget := by",
              "  rintro ⟨holes, hb, hr, hc⟩",
              "  refine h ⟨holes, hb, fcat62_rows holes hb hr, hc, fun i hi => ?_, fun i hi => ?_⟩",
              "  · rw [mset_zeros 252 1 (by decide)] at hi",
              "    exact absurd hi (Finset.notMem_empty i)",
              "  · rw [mset_zeros 252 2 (by decide)] at hi",
              "    exact absurd hi (Finset.notMem_empty i)",
              "",
              "#print axioms fcat62_rows",
              "#print axioms balanced_of_root",
              "",
              "end CompactChecker.Bridge311Bal"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (OUT / "Bridge311Res.lean").write_text(residual())
