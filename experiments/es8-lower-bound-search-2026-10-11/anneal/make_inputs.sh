#!/bin/bash
# Regenerate the committed input point sets into $OUT and compare them with the
# committed copies: w5-w8 (witness(n)), v8_1-v8_3 (randomised-offset variants)
# and the starting sets init_w8p_1-4 and init_w6p (witness + one point).
# RECONSTRUCTED: the original commands for v8_*, init_w8p_* and init_w6p were
# not retained. The seeds below were recovered during packaging: they
# reproduce v8_*.txt, out/addpoint_w8_inits.log and the four init_w8p files
# byte for byte, and the added point of init_w6p.txt (its original number of
# tries was not recorded; seed 2 gives the same point for 1,000 to 40,000 tries).
# init_w7p and init_v8p_* are generated by batch2_coreB.sh / batch2_coreA.sh.
. "$(dirname "$0")/common.sh"
set -e
for n in 5 6 7 8; do python3 gen_witness.py $n > "$OUT/w$n.txt"; cmp "$OUT/w$n.txt" w$n.txt; done
for v in 1 2 3; do python3 gen_variant.py 8 $v > "$OUT/v8_$v.txt"; cmp "$OUT/v8_$v.txt" v8_$v.txt; done
: > "$OUT/addpoint_w8_inits.log"
for s in 1 2 3 4; do
  "$CGON" addpoint 8 4000 1$s < w8.txt | tee -a "$OUT/addpoint_w8_inits.log" > "$OUT/addpoint_w8p_$s.txt"
  P=$(sed -E 's/.*at \((-?[0-9]+),(-?[0-9]+)\).*/\1 \2/' "$OUT/addpoint_w8p_$s.txt")
  (cat w8.txt; echo "$P") > "$OUT/init_w8p_$s.txt"
  cmp "$OUT/init_w8p_$s.txt" init_w8p_$s.txt
done
cmp "$OUT/addpoint_w8_inits.log" out/addpoint_w8_inits.log
"$CGON" addpoint 6 4000 2 < w6.txt > "$OUT/addpoint_w6p.txt"
P=$(sed -E 's/.*at \((-?[0-9]+),(-?[0-9]+)\).*/\1 \2/' "$OUT/addpoint_w6p.txt")
(cat w6.txt; echo "$P") > "$OUT/init_w6p.txt"
cmp "$OUT/init_w6p.txt" init_w6p.txt
echo "make_inputs: w5-w8, v8_1-v8_3, init_w8p_1-4 and init_w6p reproduced byte for byte"
