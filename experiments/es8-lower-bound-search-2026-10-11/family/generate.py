#!/usr/bin/env python3
"""Build the family, verify every realized set, deduplicate, write sets/ and manifest."""
import json, os, random, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from family import *  # noqa

OUT = os.path.join(HERE, 'sets')
os.makedirs(OUT, exist_ok=True)
t_start = time.time()

cands = []  # (category, tree string)
# 0. control: exact repo witness
cands.append(('witness', witness_tree(8)))
# (c) mirror trees of the witness (same order type, different least-offset realization)


def ymirror(t):
    t = parse(t) if isinstance(t, str) else t
    if t == 'o':
        return 'o'
    return f"{'D' if t[0] == 'U' else 'U'}({ymirror(t[1])},{ymirror(t[2])})"


def xmirror(t):
    t = parse(t) if isinstance(t, str) else t
    if t == 'o':
        return 'o'
    return f"{'D' if t[0] == 'U' else 'U'}({xmirror(t[2])},{xmirror(t[1])})"


cands.append(('mirror', ymirror(witness_tree(8))))
cands.append(('mirror', xmirror(witness_tree(8))))
cands.append(('mirror', xmirror(ymirror(witness_tree(8)))))
# (a) all bracketings of the Down chain T0..T6 with canonical blocks
T = [canon_block(7 - j, j + 1) for j in range(7)]
for t in chain_bracketings(tuple(T)):
    cands.append(('bracket', t))
# (a') all bracketings of the Up chain of the y-mirrored blocks
Tm = [canon_block(j + 1, 7 - j) for j in range(7)]
for t in chain_bracketings(tuple(Tm)):
    cands.append(('bracket-up', t.replace('D(', 'X(').replace('X(', 'U(') if False else t))
# NOTE: chain_bracketings uses 'D' nodes; Up-chain of mirrored blocks is generated by ymirror below
cands = [c for c in cands if c[0] != 'bracket-up']
for t in chain_bracketings(tuple(T)):
    cands.append(('bracket-up', ymirror(t)))
# (b) all skeletons above maximal blocks, canonical blocks
skel = all_skeletons(TOP, lambda s: 'o' if s[0] == 1 else canon_block(s[1], s[2]))
for t in skel:
    cands.append(('skeleton', t))
# (b') witness skeleton (left Down chain of T blocks) with random block internals
rng = random.Random(20261011)
for _ in range(300):
    t = canon_block(7, 1)
    for j in range(1, 7):
        t = f'D({t},{random_block(7 - j, j + 1, rng)})'
    cands.append(('wblocks-random', t))
# (b'') random certified trees: uniform decomposition per node, and uniform over trees
for _ in range(400):
    cands.append(('random-dec', sample_tree(TOP, rng, 'dec')))
for _ in range(400):
    cands.append(('random-tree', sample_tree(TOP, rng, 'tree')))
# random skeleton with random blocks
for _ in range(300):
    sk = all_skeletons  # noqa
    cands.append(('skeleton-randblocks', None))

skel_list = skel


def rand_skel_randblocks():
    t = rng.choice(skel_list)
    # re-sample the blocks: replace each canonical block subtree by a random block
    # (done structurally: rebuild by walking the DP with random blocks)
    return t


# build skeleton+random blocks properly by a DP walk choosing a random skeleton decomposition
def rand_skel_tree(s):
    if is_block(s):
        return 'o' if s[0] == 1 else random_block(s[1], s[2], rng)
    d, a, b = rng.choice(decomps(s))
    return f'{d}({rand_skel_tree(a)},{rand_skel_tree(b)})'


cands = [c if c[0] != 'skeleton-randblocks' else ('skeleton-randblocks', rand_skel_tree(TOP)) for c in cands]

print('candidate trees:', len(cands), {k: sum(1 for c in cands if c[0] == k) for k in dict.fromkeys(c[0] for c in cands)})

seen_tree = {}
records = []
by_ot = {}
by_x = {}
n_cert = 0
for cat, t in cands:
    if t in seen_tree:
        continue
    seen_tree[t] = True
    b = bounds(parse(t))
    certified = b[0] == 64 and b[3] <= 7
    rec = {'category': cat, 'tree': t, 'bounds': b, 'certified': certified}
    if not certified:
        records.append(rec)
        continue
    n_cert += 1
    P = realize(t)
    info, O = verify_set(P, run_dp=False)
    rec.update(info)
    okey, nh = order_type_key(P, O)
    xkey = xorder_key(P, O)
    rec['order_type'] = okey
    rec['hull_size'] = nh
    xh = hashlib.sha256(xkey).hexdigest()
    rec['xorder_type'] = xh
    by_x.setdefault(xh, []).append(len(records))
    if okey not in by_ot:
        by_ot[okey] = len(records)
        # full verification (exact DP) for the representative of each order type
        rec['largest_convex_subset'] = W.largest_convex_subset(P)
        rec['representative'] = True
    else:
        rec['representative'] = False
        rec['same_as'] = by_ot[okey]
    records.append(rec)

reps = [r for r in records if r.get('representative')]
print('distinct trees:', len(seen_tree), 'certified:', n_cert)
print('distinct x-order sign vectors (mod 4 reflections):', len(by_x))
print('distinct order types:', len(by_ot))
bad = [r for r in reps if not (r['general_position'] and r['distinct_x'] and r['largest_convex_subset'] == 7)]
print('representatives failing verification:', len(bad))
print('representatives exceeding 2^27:', sum(1 for r in reps if not r['within_2^27']))
from collections import Counter
print('order types by first category:', Counter(r['category'] for r in reps))
print('max coord stats among reps: min %d max %d' % (min(r['max_abs_coord'] for r in reps), max(r['max_abs_coord'] for r in reps)))
# write each representative's points
nrep = 0
for i, r in enumerate(records):
    if r.get('representative'):
        r['id'] = f"ot{nrep:04d}"
        nrep += 1
        P = realize(r['tree'])
        with open(os.path.join(OUT, r['id'] + '.txt'), 'w') as f:
            f.write(''.join(f'{x} {y}\n' for x, y in P))
json.dump(records, open(os.path.join(HERE, 'manifest.json'), 'w'))
print('elapsed', round(time.time() - t_start, 1), 's')
