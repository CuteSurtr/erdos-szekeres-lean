#!/usr/bin/env python3
"""Write LeanLB/Data/<Name>.lean from a point-set file of the repository (standard library only).

Rows are copied verbatim (comments and blank lines dropped) as `List (List Int)`. The checker list is
the lattice image of the rows, translated to non-negative coordinates; the translation (s0, s1) is
printed in the file and the link between the two lists is re-checked in Lean by `decide +kernel`.
Usage: gen_data.py [--check]   (with --check, only compare the generated text with the files on disk)
"""
import hashlib, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
R = os.path.dirname(PKG)  # .../results

SETS = [
    # name, source (relative to results/), lattice kind
    ("C4N52", "ES8SYM/sets/c4_52pts_13layers.pts", "m4"),
    ("C6N60", "SIX60/sets/c6_60pts_D.pts", "m6"),
    ("C2N64", "ES8SYM/sets/c2_64points_k8.txt", "xy"),
    ("MirN46", "ES8SYM/sets/mirror_46points_k8.txt", "xy"),
    ("C3N61", "ES8SYM/sets4/c3_61pts_centre.txt", "m3"),
    ("C5N56", "ES8SYM/sets3/c5_56pts_11layers_centre.pts", "m5"),
    ("C7N64", "ES8SYM/sets/c7_64pts_small.pts", "m7"),
]

def rows(path):
    out = []
    for line in open(path):
        t = line.split('#')[0].split()
        if t:
            out.append([int(x) for x in t])
    return out

def g(w, j):
    return w[j] if j < len(w) else 0

def lat(kind, w):
    if kind == "m6":
        return (g(w,0) - g(w,2) - g(w,3) + g(w,5), g(w,1) + g(w,2) - g(w,4) - g(w,5))
    if kind == "m4":
        return (g(w,0) - g(w,2), g(w,1) - g(w,3))
    if kind == "m3":
        return (g(w,0) - g(w,2), g(w,1) - g(w,2))
    if kind == "xy":
        return (g(w,0), g(w,1))
    raise ValueError(kind)

def lat5(w):
    return ((2*g(w,0) - g(w,2) - g(w,3), g(w,1) + g(w,4) - g(w,2) - g(w,3), 0), (g(w,1) - g(w,4), g(w,2) - g(w,3), 0))

def lat7(w):
    X = (2*g(w,0) - 2*(g(w,2) + g(w,5)) + (g(w,3) + g(w,4)), (g(w,1) + g(w,6)) - (g(w,3) + g(w,4)),
         (g(w,2) + g(w,5)) - (g(w,3) + g(w,4)))
    Y = ((g(w,1) - g(w,6)) - (g(w,3) - g(w,4)), g(w,2) - g(w,5), g(w,3) - g(w,4))
    return (X, Y)

# Rational bounds lo/D < t < (lo+1)/D (must equal lo5/D5 in LeanLB/G/Five.lean, lo7/D7 in Seven.lean)
# and the scale exponent K of the approximations.
FIELD = {"m5": dict(lo=747157246399165135975324, Dbits=80, K=40),
         "m7": dict(lo=23002713614911870667, Dbits=64, K=24)}

def lowupp(r, lo, D):
    c1 = (r[1]*lo*D, r[1]*(lo+1)*D); c2 = (r[2]*lo*lo, r[2]*(lo+1)*(lo+1))
    return D*D*r[0] + min(c1) + min(c2), D*D*r[0] + max(c1) + max(c2)

def approx(r, lo, D, sc):
    L, H = lowupp(r, lo, D)
    n = (sc*L) // (D*D)
    for c in (n, n+1, n-1, n+2):
        if (c-1)*D*D <= sc*L and sc*H <= (c+1)*D*D:
            return c
    raise ValueError("precision too low")

def tup(t):
    return "(" + ", ".join(tup(x) if isinstance(x, tuple) else str(x) for x in t) + ")"

def render_field(name, src, kind):
    path = os.path.join(R, src)
    sha = hashlib.sha256(open(path, 'rb').read()).hexdigest()
    W = rows(path)
    lo = name[0].lower() + name[1:]
    F = FIELD[kind]; D = 2**F["Dbits"]; sc = 2**F["K"]
    pts = [lat5(w) if kind == "m5" else lat7(w) for w in W]
    A = [(approx(X, F["lo"], D, sc), approx(Y, F["lo"], D, sc)) for X, Y in pts]
    s0 = -min(a for a, _ in A); s1 = -min(b for _, b in A)
    N = [(a + s0, b + s1) for a, b in A]
    Mx = max(max(a, b) for a, b in N)
    fn = "lat5" if kind == "m5" else "lat7"
    out = []
    out.append("import LeanLB.Checker\n")
    out.append("/-! Generated by `scripts/gen_data.py`; do not edit.\n")
    out.append(f"Source: `results/{src}` ({len(W)} rows), SHA-256 `{sha}`.\n")
    out.append(f"`{lo}Rows` are the rows of the file, verbatim. `{lo}L` pairs the exact coordinates in `ℤ[t]`\n")
    out.append(f"(`LeanLB.G.{fn}` of the rows; re-checked by kernel evaluation) with integer approximations of\n")
    out.append(f"`2^{F['K']}·(X(t), Y(t))`, translated by `{lo}Shift` (certified by kernel evaluation of `certOK`). -/\n\n")
    out.append("namespace LeanLB\n\n")
    out.append(f"/-- The rows of `{os.path.basename(src)}`, verbatim. -/\n")
    out.append(f"def {lo}Rows : List (List Int) := [\n")
    out.append(",\n".join("  [" + ", ".join(str(x) for x in w) + "]" for w in W))
    out.append("]\n\n")
    out.append(f"/-- Scale `2^{F['K']}` of the approximations. -/\ndef {lo}Sc : Int := {sc}\n\n")
    out.append(f"/-- Translation of the approximations. -/\ndef {lo}Shift : Int × Int := ({s0}, {s1})\n\n")
    out.append(f"/-- Bound on the translated approximations. -/\ndef {lo}Mx : Nat := {Mx}\n\n")
    out.append(f"/-- Exact coordinates and approximations. -/\n")
    out.append(f"def {lo}L : List (((Int × Int × Int) × (Int × Int × Int)) × (Nat × Nat)) := [\n")
    out.append(",\n".join("  (" + tup(p) + ", " + tup(n) + ")" for p, n in zip(pts, N)))
    out.append("]\n\nend LeanLB\n")
    return "".join(out), sha, len(W)

def render(name, src, kind):
    if kind in ("m5", "m7"):
        return render_field(name, src, kind)
    path = os.path.join(R, src)
    sha = hashlib.sha256(open(path, 'rb').read()).hexdigest()
    W = rows(path)
    L = [lat(kind, w) for w in W]
    s0 = -min(x for x, _ in L)
    s1 = -min(y for _, y in L)
    N = [(x + s0, y + s1) for x, y in L]
    lo = name[0].lower() + name[1:]
    out = []
    out.append("import LeanLB.Checker\n")
    out.append("/-! Generated by `scripts/gen_data.py`; do not edit.\n")
    out.append(f"Source: `results/{src}` ({len(W)} rows), SHA-256 `{sha}`.\n")
    out.append(f"`{lo}Rows` are the rows of the file, verbatim. `{lo}Nat` are their lattice coordinates (kind `{kind}`)\n")
    out.append(f"translated by ({s0}, {s1}); `LeanLB.Main` re-checks this link by kernel evaluation. -/\n\n")
    out.append("namespace LeanLB\n\n")
    out.append(f"/-- The rows of `{os.path.basename(src)}`, verbatim. -/\n")
    out.append(f"def {lo}Rows : List (List Int) := [\n")
    out.append(",\n".join("  [" + ", ".join(str(x) for x in w) + "]" for w in W))
    out.append("]\n\n")
    out.append(f"/-- Translation used for `{lo}Nat`. -/\n")
    out.append(f"def {lo}Shift : Int × Int := ({s0}, {s1})\n\n")
    out.append(f"/-- Lattice coordinates of the rows, translated to non-negative integers. -/\n")
    out.append(f"def {lo}Nat : List NP := [\n")
    out.append(",\n".join(f"  ({x}, {y})" for x, y in N))
    out.append("]\n\nend LeanLB\n")
    return "".join(out), sha, len(W)

def main():
    check = "--check" in sys.argv
    ok = True
    for name, src, kind in SETS:
        text, sha, n = render(name, src, kind)
        dst = os.path.join(PKG, "LeanLB", "Data", name + ".lean")
        if check:
            same = os.path.exists(dst) and open(dst).read() == text
            print(f"{'OK  ' if same else 'DIFF'} {dst[len(PKG)+1:]} <- {src} ({n} rows, sha256 {sha})")
            ok &= same
        else:
            open(dst, "w").write(text)
            print(f"wrote {dst[len(PKG)+1:]} <- {src} ({n} rows, sha256 {sha})")
    sys.exit(0 if ok else 1)

if __name__ == "__main__":
    main()
