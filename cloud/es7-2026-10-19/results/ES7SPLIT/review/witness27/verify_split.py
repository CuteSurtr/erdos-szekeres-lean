#!/usr/bin/env python3
"""Exact check of the descriptive part of the claim about the 27-point witness (Proposition 8(b)).

  * the witness = (26-point upper part A of a (4,2)-split of the classical 32-point set) + (one point of the
    lower part B);
  * (A, B) is a z-split for the rational point z = (-290/3141, 1000290/3141) reported in logs/prop8b_witness.txt
    (homogeneous (-290, 1000290, 3141)), checked from Definition 1 of proofs/split_theorem.md with Fractions:
      (S1) every b in B strictly on z's side of every line aa' (a != a' in A);
      (S2) every a in A strictly on the side of every line bb' (b != b' in B) not containing z, z not on bb';
      z outside conv(S);
  * cap_z(A) = 4 and cup_z(B) = 2, by brute force over subsets directly from the definitions of z-order,
    z-cap and z-cup (no normal-form map, no DP).

Usage: verify_split.py CLASSICAL32 WITNESS27 REGENERATED_JSON
"""
import json
import sys
from fractions import Fraction
from itertools import combinations, permutations


def read_points(fn):
    pts = []
    for line in open(fn):
        f = line.split()
        if len(f) >= 2:
            pts.append((int(f[0]), int(f[1])))
    return pts


def orient(a, b, c):
    return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])


def sgn(v):
    return (v > 0) - (v < 0)


def hull_ccw(P):
    """Gift wrapping, CCW."""
    start = min(P)
    hull = [start]
    cur = start
    while True:
        cand = None
        for q in P:
            if q == cur:
                continue
            if cand is None or orient(cur, cand, q) < 0:
                cand = q
        if cand == start:
            break
        hull.append(cand)
        cur = cand
    return hull


def main():
    cls = read_points(sys.argv[1])
    wit = read_points(sys.argv[2])
    regen = [tuple(p) for p in json.load(open(sys.argv[3]))]
    print("classical32.txt points:", len(cls), "| regenerated by repository script:", len(regen),
          "| identical (same order):", cls == regen)
    # witness composition
    A = cls[6:32]
    B = cls[0:6]
    print("witness == classical[6..31] + [classical[0]] (same order):", wit == A + [cls[0]])
    print("witness as a set == A u {classical[0]}:", set(wit) == set(A) | {cls[0]})
    print("B (lower part) =", B)
    S = cls
    z = (Fraction(-290, 3141), Fraction(1000290, 3141))
    print("z =", z, "~ (%.6f, %.6f)" % (float(z[0]), float(z[1])))
    # z outside conv(S)
    H = hull_ccw(S)
    outside_edges = [i for i in range(len(H)) if orient(H[i], H[(i + 1) % len(H)], z) < 0]
    print("hull of classical set:", len(H), "vertices; z strictly outside hull edges", outside_edges,
          "-> z outside conv(S):", len(outside_edges) > 0)
    # (S1)
    s1_ok = True
    for a, a2 in combinations(A, 2):
        sz = sgn(orient(a, a2, z))
        if sz == 0:
            s1_ok = False
            continue
        for b in B:
            if sgn(orient(a, a2, b)) != sz:
                s1_ok = False
    # (S2)
    s2_ok = True
    for b, b2 in combinations(B, 2):
        sz = sgn(orient(b, b2, z))
        if sz == 0:
            s2_ok = False
            continue
        for a in A:
            if sgn(orient(b, b2, a)) != -sz:
                s2_ok = False
    print("(S1):", s1_ok, "| (S2):", s2_ok)

    # z-order: p <_z q iff orient(z, p, q) < 0
    def less(p, q):
        return orient(z, p, q) < 0

    def zorder(X):
        for p, q in combinations(X, 2):
            assert orient(z, p, q) != 0
        for p, q, r in permutations(X, 3):
            if less(p, q) and less(q, r):
                assert less(p, r), "z-order not transitive"
        rank = {p: sum(1 for q in X if q != p and less(q, p)) for p in X}
        assert sorted(rank.values()) == list(range(len(X)))
        return sorted(X, key=lambda p: rank[p])

    def is_zcap(seq):  # seq in z-order; q_j on the side of q_i q_k opposite to z, all i<j<k
        for i, j, k in combinations(range(len(seq)), 3):
            sz = sgn(orient(seq[i], seq[k], z))
            if sz == 0 or sgn(orient(seq[i], seq[k], seq[j])) != -sz:
                return False
        return True

    def is_zcup(seq):  # q_j on z's side of q_i q_k
        for i, j, k in combinations(range(len(seq)), 3):
            sz = sgn(orient(seq[i], seq[k], z))
            if sz == 0 or sgn(orient(seq[i], seq[k], seq[j])) != sz:
                return False
        return True

    Az = zorder(A)
    Bz = zorder(B)
    pos = {p: i for i, p in enumerate(Az)}

    def count(X_sorted, m, pred):
        c = 0
        for idx in combinations(range(len(X_sorted)), m):
            if pred([X_sorted[i] for i in idx]):
                c += 1
        return c

    capA = {m: count(Az, m, is_zcap) for m in (3, 4, 5)}
    cupB = {m: count(Bz, m, is_zcup) for m in (3,)}
    capB6 = is_zcap(Bz)
    print("A: number of z-caps of size 3/4/5:", capA[3], capA[4], capA[5], "-> cap_z(A) =",
          4 if capA[4] > 0 and capA[5] == 0 else "?")
    print("B: number of z-cup triples:", cupB[3], "-> cup_z(B) =", 2 if cupB[3] == 0 else ">2",
          "| B itself is a z-6-cap:", capB6)
    b = cls[0]
    print("added point b =", b, "| b in B:", b in B)


if __name__ == "__main__":
    main()
