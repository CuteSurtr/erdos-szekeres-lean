#!/usr/bin/env python3
"""Write a Lean file with the leaf lists of the 450 cases (from assemble_leaves.py output).

  gen_leaves.py ASM_DIR OUT.lean [--closed-only]

The file defines `V2L.leafPacked` (per case `(U, L)`, its leaves in the storage encoding of
`V2L.Data`, 5 hex digits per literal), `V2L.leafTable` and `V2L.leavesOf : List Nat × List Nat → List (List Int)`, the
parameter of `V2L.InteriorCertificates`. With --closed-only only the closed cases are written
(for timing the kernel cover check before all cases are closed)."""
import hashlib, json, os, sys
asm, out = sys.argv[1], sys.argv[2]; closed_only = "--closed-only" in sys.argv
st = json.load(open(os.path.join(asm, "status.json")))

def enc(z):
    assert z != 0
    d = 2 * z if z > 0 else 2 * (-z) + 1
    assert d < 1 << 20
    return d
def packed(c):
    return "(%d, %s)" % (len(c), ("0x" + "".join("%05x" % enc(z) for z in c)) if c else "0")
def natlist(xs): return "[" + ", ".join(map(str, xs)) + "]"

ents = []
for r in st["rows"]:
    if closed_only and not r["closed"]: continue
    f = os.path.join(asm, "leaves", r["case"] + ".icnf")
    cubes = [list(map(int, l.split()[1:-1])) for l in open(f) if l.startswith("a")]
    ents.append("  ((%s, %s), [%s])" % (natlist(r["U"]), natlist(r["L"]), ", ".join(packed(c) for c in cubes)))
src = """import V2L.Data

/-!
# Leaf lists of the 450 cases (generated by `scripts/gen_leaves.py`; do not edit by hand)

Source: `%s` (summary %s).
-/

namespace V2L

/-- Read the low `k` base-2^20 digits of `n`, most significant first (as `unpackAux`, with
5 hex digits per literal, since leaf cubes may use auxiliary variables up to 47002). -/
def unpackAux20 : Nat → Nat → List Int → List Int
  | 0, _, acc => acc
  | k + 1, n, acc => unpackAux20 k (n / 1048576) (decLit (n %% 1048576) :: acc)

def unpack20 (p : Nat × Nat) : List Int := unpackAux20 p.1 p.2 []

set_option maxRecDepth 100000 in
/-- Per case `(U, L)`, its leaf cubes, stored as `(k, n)` with 5 hex digits per literal. -/
def leafPacked : List ((List Nat × List Nat) × List (Nat × Nat)) := [
%s]

def leafTable : List ((List Nat × List Nat) × List (List Int)) :=
  leafPacked.map fun p => (p.1, p.2.map unpack20)

/-- The leaf list of a case (`[]` for a case not in the table). -/
def leavesOf (s : List Nat × List Nat) : List (List Int) :=
  match leafTable.find? (·.1 == s) with
  | some p => p.2
  | none => []

end V2L
""" % (os.path.join(asm, "status.json"), json.dumps({k: v for k, v in st["summary"].items() if k != "open"}), ",\n".join(ents))
open(out, "w").write(src)
print(len(ents), "cases", hashlib.sha256(src.encode()).hexdigest())
