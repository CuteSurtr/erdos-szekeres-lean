#!/usr/bin/env python3
"""Write V2L/Data.lean: the 121 upper-chain cubes UP(U) and the 450 case cubes of the
hull-pair split of sub-case (ii), as Lean data.

  gen_data.py MII_S_DIR OUT.lean

UP(U) comes from MII_S_DIR/scripts/cover.py (`UPS`, `up`); the case list (U, L) from
hullsplit.py `cases()`; the case cubes are read from MII_S_DIR/cases.icnf and checked
against hullsplit.py `cube(U, L)`.  A cube of k literals is stored as (k, n), where the
hexadecimal numeral n has 4 hex digits per literal, most significant first, and a literal
z is stored as 2z (z > 0) or 2|z| + 1 (z < 0).  `V2L.unpack` decodes this.
"""
import hashlib, os, sys
mii = os.path.abspath(sys.argv[1]); out = sys.argv[2]
sys.path.insert(0, os.path.join(mii, "scripts"))
import cover, hullsplit as H

def enc(z):
    assert z != 0
    d = 2 * z if z > 0 else 2 * (-z) + 1
    assert d < 65536
    return d

def packed(c):
    return "(%d, 0x%s)" % (len(c), "".join("%04x" % enc(z) for z in c))

icnf = os.path.join(mii, "cases.icnf")
raw = open(icnf, "rb").read()
sha = hashlib.sha256(raw).hexdigest()
cubes = []
for line in raw.decode().splitlines():
    t = line.split()
    assert t[0] == "a" and t[-1] == "0"
    cubes.append([int(x) for x in t[1:-1]])
specs = H.cases()
assert len(cubes) == len(specs) == 450
for (U, L), c in zip(specs, cubes):
    assert c == H.cube(U, L), (U, L)
ups = [cover.up(U) for U in cover.UPS]
assert len(ups) == 121

def natlist(xs): return "[" + ", ".join(map(str, xs)) + "]"

o = []
o.append("""/-!
# Data: the upper-chain cubes and the case cubes of the hull-pair split (sub-case (ii))

Generated by `scripts/gen_data.py` from `results/Mii-S` (`scripts/cover.py`,
`scripts/hullsplit.py`, and `cases.icnf`, sha256
`%s`). Do not edit by hand.
`lake exe v2l_data` regenerates the cube files and the obligation CNFs from these terms.

A cube of `k` literals is stored as `(k, n)`; `n` has 4 hex digits per literal, most
significant first, and the literal `z` is stored as `2z` (`z > 0`) or `2|z| + 1` (`z < 0`).
-/

namespace V2L

/-- Inverse of the storage encoding `z ↦ 2z` (z > 0), `z ↦ 2|z| + 1` (z < 0). -/
def decLit (d : Nat) : Int := if d %% 2 = 0 then Int.ofNat (d / 2) else -Int.ofNat (d / 2)

/-- Read the low `k` base-65536 digits of `n`, consing onto `acc` (so the most significant
digit comes first). -/
def unpackAux : Nat → Nat → List Int → List Int
  | 0, _, acc => acc
  | k + 1, n, acc => unpackAux k (n / 65536) (decLit (n %% 65536) :: acc)

/-- Decode a stored cube `(k, n)`. -/
def unpack (p : Nat × Nat) : List Int := unpackAux p.1 p.2 []
""" % sha)
o.append("/-- The 121 upper chains `U ⊆ {2..16}`, `|U| ≤ 2`, in the order of `cover.py`'s `UPS`. -/")
o.append("def upSets : List (List Nat) := [\n  " + ",\n  ".join(natlist(U) for U in cover.UPS) + "]\n")
o.append("/-- `UP(U)` for each `U` of `upSets`, in the same order (`cover.py` `up(U)`), stored. -/")
o.append("def upPacked : List (Nat × Nat) := [\n  " + ",\n  ".join(packed(c) for c in ups) + "]\n")
o.append("/-- The 450 cases `(U, L)`, in the order of `hullsplit.py` `cases()` and `cases.icnf`. -/")
o.append("def caseSpecs : List (List Nat × List Nat) := [\n  " +
         ",\n  ".join("(%s, %s)" % (natlist(U), natlist(L)) for U, L in specs) + "]\n")
o.append("/-- `cube(U, L)` for each case, line by line of `cases.icnf`, stored. -/")
o.append("def casePacked : List (Nat × Nat) := [\n  " + ",\n  ".join(packed(c) for c in cubes) + "]\n")
o.append("""/-- The cubes `UP(U)`. -/
def upCubes : List (List Int) := upPacked.map unpack

/-- The case cubes `cube(U, L)`, i.e. the lines of `cases.icnf`. -/
def caseCubes : List (List Int) := casePacked.map unpack

end V2L
""")
open(out, "w").write("\n".join(o))
print("upSets", len(ups), "cases", len(cubes), "literals", sum(map(len, cubes)) + sum(map(len, ups)))
