#!/usr/bin/env python3
"""Write V1L/Leaves.lean from a march_cu cube file (`a l1 ... lk 0` per line).

Usage: gen_leaves.py CUBES.icnf OUT.lean

Each literal z is stored as the natural number 2z (z > 0) or 2|z| + 1 (z < 0), because
Lean elaborates large `Nat` list literals much faster than `Int` ones; `V1L.decLit` undoes
the encoding. The cubes are split into chunks of 100 so that each `def` stays small. The
sha256 of the source file is written into the header.
"""
import hashlib
import sys

src, out = sys.argv[1], sys.argv[2]
raw = open(src, 'rb').read()
sha = hashlib.sha256(raw).hexdigest()
cubes = []
for line in raw.decode().splitlines():
    t = line.split()
    if not t:
        continue
    assert t[0] == 'a' and t[-1] == '0', line
    c = [int(x) for x in t[1:-1]]
    assert all(z != 0 for z in c), line
    cubes.append(c)

enc = lambda z: 2 * z if z > 0 else -2 * z + 1
K = 100
chunks = [cubes[i:i + K] for i in range(0, len(cubes), K)]
with open(out, 'w') as f:
    f.write('/-!\n# The leaf cubes of sub-case (i)\n\n')
    f.write('Generated by `scripts/gen_leaves.py` from `cloud/es7-2026-10-19/verify/hull_leaves.icnf`\n')
    f.write(f'(sha256 `{sha}`, {len(cubes)} cubes). Do not edit by hand.\n')
    f.write('`lake exe leaves_eq FILE` compares `hullLeaves` with a cube file.\n-/\n\n')
    f.write('namespace V1L\n\n')
    f.write('/-- Inverse of the storage encoding `z ↦ 2z` (z > 0), `z ↦ 2|z| + 1` (z < 0). -/\n')
    f.write('def decLit (d : Nat) : Int := if d % 2 = 0 then Int.ofNat (d / 2) else -Int.ofNat (d / 2)\n\n')
    for j, ch in enumerate(chunks):
        f.write(f'/-- Encoded cubes {j * K}..{j * K + len(ch) - 1} of `hull_leaves.icnf`. -/\n')
        f.write(f'def leafChunk{j} : List (List Nat) := [\n')
        f.write(',\n'.join('  [' + ', '.join(str(enc(z)) for z in c) + ']' for c in ch))
        f.write(']\n\n')
    f.write(f'/-- The {len(cubes)} leaf cubes of `hull_leaves.icnf`, in file order. -/\n')
    f.write('def hullLeaves : List (List Int) :=\n  (' +
            ' ++\n    '.join(f'leafChunk{j}' for j in range(len(chunks))) +
            ').map (List.map decLit)\n\nend V1L\n')
print(f'{len(cubes)} cubes, sha256 {sha}')
