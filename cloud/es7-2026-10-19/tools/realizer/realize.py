# =============================================================== problem
class Prob:
    def __init__(self, chi, n, m=1, has_center=False):
        self.chi, self.n, self.m, self.hc = chi, n, m, bool(has_center)
        keys = sorted(chi)
        assert len(keys) == n * (n - 1) * (n - 2) // 6, "chirotope must list all C(n,3) triples"
        self.A = np.array([k[0] for k in keys])
        self.B = np.array([k[1] for k in keys])
        self.C = np.array([k[2] for k in keys])
        self.S = np.array([chi[k] for k in keys], dtype=float)
        self.T = len(keys)
        eye = np.eye(n)
        self.Ea, self.Eb, self.Ec = eye[self.A], eye[self.B], eye[self.C]
        if m > 1:
            norb = n - (1 if self.hc else 0)
            assert norb % m == 0
            self.t = norb // m
            self.orb = np.array([i // m for i in range(norb)])
            # rotation direction: for m >= 3 the triangle (0,0),(0,1),(0,2) is counter-clockwise iff
            # the labels follow the counter-clockwise rotation (for m = 2 the direction is immaterial)
            self.dir = 1 if m == 2 else int(chi_get(chi, 0, 1, 2))
            self.phi = np.array([self.dir * 2 * math.pi * (i % m) / m for i in range(norb)])
            self.Eo = np.zeros((norb, self.t))
            self.Eo[np.arange(norb), self.orb] = 1.0
            self.norb = norb

    # ---------------------------------------------------------- loss
    def lossgrad(self, X, Y, delta, need_grad=True):
        A, B, C, S = self.A, self.B, self.C, self.S
        xa, ya, xb, yb, xc, yc = X[:, A], Y[:, A], X[:, B], Y[:, B], X[:, C], Y[:, C]
        ux, uy = xb - xa, yb - ya
        vx, vy = xc - xa, yc - ya
        wx, wy = xc - xb, yc - yb
        D = ux * vy - uy * vx
        lab = np.sqrt(ux * ux + uy * uy) + 1e-300
        lac = np.sqrt(vx * vx + vy * vy) + 1e-300
        lbc = np.sqrt(wx * wx + wy * wy) + 1e-300
        mab = (lab >= lac) & (lab >= lbc)
        mac = (~mab) & (lac >= lbc)
        mbc = ~(mab | mac)
        lmax = np.where(mab, lab, np.where(mac, lac, lbc))
        N = lab * lac * lbc / lmax
        g = S * D / N
        h = np.maximum(delta - g, 0.0)
        loss = (h * h).sum(1)
        nviol = (g <= 0).sum(1)
        if not need_grad:
            return loss, nviol, None, None, g
        dg = -2.0 * h
        kD = dg * S / N
        kN = -dg * g / N
        fab = np.where(mab, 0.0, kN * N / lab) / lab
        fac = np.where(mac, 0.0, kN * N / lac) / lac
        fbc = np.where(mbc, 0.0, kN * N / lbc) / lbc
        gxa = kD * (uy - vy) - fab * ux - fac * vx
        gya = kD * (vx - ux) - fab * uy - fac * vy
        gxb = kD * vy + fab * ux - fbc * wx
        gyb = -kD * vx + fab * uy - fbc * wy
        gxc = -kD * uy + fac * vx + fbc * wx
        gyc = kD * ux + fac * vy + fbc * wy
        GX = gxa @ self.Ea + gxb @ self.Eb + gxc @ self.Ec
        GY = gya @ self.Ea + gyb @ self.Eb + gyc @ self.Ec
        return loss, nviol, GX, GY, g

    # ---------------------------------------------------------- symmetric parametrisation
    def sym_points(self, U, TH):
        R = U.shape[0]
        X = np.zeros((R, self.n))
        Y = np.zeros((R, self.n))
        r = np.exp(U[:, self.orb])
        a = TH[:, self.orb] + self.phi
        X[:, :self.norb] = r * np.cos(a)
        Y[:, :self.norb] = r * np.sin(a)
        return X, Y

    def sym_grad(self, X, Y, GX, GY):
        k = self.norb
        x, y, gx, gy = X[:, :k], Y[:, :k], GX[:, :k], GY[:, :k]
        GU = (gx * x + gy * y) @ self.Eo
        GT = (gy * x - gx * y) @ self.Eo
        GU[:, 0] = 0.0
        GT[:, 0] = 0.0
        return GU, GT


# =============================================================== exact rounding
def int_points_from_float(prob, x, y, k):
    """round a float configuration to integers with max |coordinate| about 2^k"""
    s = float(max(np.max(np.abs(x)), np.max(np.abs(y)), 1e-300))
    sc = (2.0 ** k) / s
    m = prob.m
    if m in (2, 4):
        pts = [None] * prob.n
        for o in range(prob.t):
            i0 = o * m
            px, py = int(round(x[i0] * sc)), int(round(y[i0] * sc))
            for r in range(m):
                pts[i0 + r] = (px, py)
                px, py = (-px, -py) if m == 2 else ((-py, px) if prob.dir > 0 else (py, -px))
        if prob.hc:
            pts[prob.n - 1] = (0, 0)
        return pts
    pts = [(int(round(x[i] * sc)), int(round(y[i] * sc))) for i in range(prob.n)]
    if prob.m > 1 and prob.hc:
        pts[prob.n - 1] = (0, 0)
    return pts


def quick_check(prob, pts):
    """exact sign check; int64 when safe, Python ints otherwise.  Returns number of bad triples."""
    mx = max(max(abs(p[0]), abs(p[1])) for p in pts)
    if mx < 2 ** 29:
        P = np.array(pts, dtype=np.int64)
        xa, ya = P[prob.A, 0], P[prob.A, 1]
        D = (P[prob.B, 0] - xa) * (P[prob.C, 1] - ya) - (P[prob.B, 1] - ya) * (P[prob.C, 0] - xa)
        return int(np.sum(np.sign(D) != prob.S.astype(np.int64)))
    bad = 0
    for a, b, c, s in zip(prob.A.tolist(), prob.B.tolist(), prob.C.tolist(), prob.S.tolist()):
        d = (pts[b][0] - pts[a][0]) * (pts[c][1] - pts[a][1]) - (pts[b][1] - pts[a][1]) * (pts[c][0] - pts[a][0])
        if d == 0 or (d > 0) != (s > 0):
            bad += 1
    return bad


def try_exact(prob, x, y, scales=(10, 14, 18, 22, 26, 28, 34, 42, 52, 64)):
    for k in scales:
        pts = int_points_from_float(prob, x, y, k)
        if len(set(pts)) < len(pts):
            continue
        if quick_check(prob, pts) == 0:
            return pts
    return None


# =============================================================== penalty descent
def penalty_descent(prob, rng, deadline, mode="sym", R=48, steps=700, lr=None, log=None, init=None, max_rounds=None):
    """batched Adam with random multi-scale restarts and leaderboard perturbations.
    Returns (points or None, best_violations, best float config)."""
    n = prob.n
    best_v, best_par = 10 ** 9, None
    best_xy = None
    rounds = 0
    while _clock() < deadline:
        rounds += 1
        if mode == "sym":
            t, m = prob.t, prob.m
            L = rng.choice([0.3, 1.0, 2.0, 3.5, 5.0], size=(R, 1))
            U = rng.uniform(-1, 1, size=(R, t)) * L
            TH = rng.uniform(0, 2 * math.pi / m, size=(R, t))
            if best_par is None and init is not None:
                # representatives of the given configuration, normalised so that q_0 = (1, 0)
                qx = np.array([init[0][o * m] for o in range(t)])
                qy = np.array([init[1][o * m] for o in range(t)])
                r0, a0 = math.hypot(qx[0], qy[0]), math.atan2(qy[0], qx[0])
                u0 = np.log(np.hypot(qx, qy) / r0)
                th0 = np.arctan2(qy, qx) - a0
                best_par = [u0, th0]
                U[:] = u0
                TH[:] = th0
            if best_par is not None:
                h = R // 2 if init is None else R
                sc = rng.choice([0.0, 0.003, 0.01, 0.03, 0.1, 0.3], size=(h, 1))
                U[:h] = best_par[0] + rng.normal(size=(h, t)) * sc
                TH[:h] = best_par[1] + rng.normal(size=(h, t)) * sc
            U[:, 0] = 0.0
            TH[:, 0] = 0.0
            params = [U, TH]
            lr_ = lr or 0.03
        else:
            kind = rng.integers(0, 3, size=R)
            X = rng.normal(size=(R, n))
            Y = rng.normal(size=(R, n))
            Y[kind == 1] = rng.uniform(-1, 1, size=(int((kind == 1).sum()), n))
            ms = kind == 2  # multi-scale: random log-scale per point around clusters
            if ms.any():
                k = int(ms.sum())
                sc = np.exp(rng.uniform(-4, 0, size=(k, n)))
                X[ms] = X[ms] * sc + rng.normal(size=(k, 1)) * 0
                Y[ms] = Y[ms] * sc
            if best_par is None and init is not None:
                best_par = [np.asarray(init[0], float), np.asarray(init[1], float)]
                cx_, cy_ = best_par[0].mean(), best_par[1].mean()
                s_ = np.sqrt(((best_par[0] - cx_) ** 2 + (best_par[1] - cy_) ** 2).mean()) + 1e-300
                best_par = [(best_par[0] - cx_) / s_, (best_par[1] - cy_) / s_]
                X[:] = best_par[0]
                Y[:] = best_par[1]
            if best_par is not None:
                h = R // 2 if init is None else R
                sc = rng.choice([0.0, 0.001, 0.003, 0.01, 0.03, 0.1], size=(h, 1))
                X[:h] = best_par[0] + rng.normal(size=(h, n)) * sc
                Y[:h] = best_par[1] + rng.normal(size=(h, n)) * sc
            params = [X, Y]
            lr_ = lr or 0.01
        m1 = [np.zeros_like(p) for p in params]
        m2 = [np.zeros_like(p) for p in params]
        b1, b2 = 0.9, 0.999
        for it in range(1, steps + 1):
            delta = 0.3 * (0.02 / 0.3) ** min(1.0, it / (0.8 * steps))
            if mode == "sym":
                X, Y = prob.sym_points(params[0], params[1])
            else:
                X, Y = params
            loss, nv, GX, GY, g = prob.lossgrad(X, Y, delta)
            if it % 20 == 0 or it == steps:
                j = int(np.argmin(nv))
                if nv[j] < best_v:
                    best_v = int(nv[j])
                    best_par = [p[j].copy() for p in params]
                    best_xy = (X[j].copy(), Y[j].copy())
                for j in np.nonzero(nv == 0)[0][:4]:
                    pts = try_exact(prob, X[j], Y[j])
                    if pts is not None:
                        return pts, 0, (X[j].copy(), Y[j].copy())
                if _clock() > deadline:
                    break
            if mode == "sym":
                G = list(prob.sym_grad(X, Y, GX, GY))
            else:
                G = [GX, GY]
            for q in range(len(params)):
                m1[q] = b1 * m1[q] + (1 - b1) * G[q]
                m2[q] = b2 * m2[q] + (1 - b2) * G[q] * G[q]
                step = lr_ * (m1[q] / (1 - b1 ** it)) / (np.sqrt(m2[q] / (1 - b2 ** it)) + 1e-12)
                params[q] = params[q] - step
            if mode == "sym":
                params[0][:, 0] = 0.0
                params[1][:, 0] = 0.0
            else:
                # re-normalise (similarity transformations do not change orientations)
                X, Y = params
                X = X - X.mean(1, keepdims=True)
                Y = Y - Y.mean(1, keepdims=True)
                s = np.sqrt((X * X + Y * Y).mean(1, keepdims=True)) + 1e-300
                params = [X / s, Y / s]
        if log:
            log(f"penalty[{mode}] round {rounds}: best violations {best_v}")
        if max_rounds and rounds >= max_rounds:
            break
    return None, best_v, best_xy


# =============================================================== alternating LP
def _lp_solve(nv, rows_idx, rows_val, rlo, cost, lo, hi):
    """min cost.z  s.t.  rows (CSR) >= rlo, lo <= z <= hi.  Returns z or None."""
    h = highspy.Highs()
    h.setOptionValue("output_flag", False)
    h.setOptionValue("threads", 1)
    h.setOptionValue("primal_feasibility_tolerance", 1e-9)
    h.setOptionValue("dual_feasibility_tolerance", 1e-9)
    h.setOptionValue("time_limit", 20.0)
    lp = highspy.HighsLp()
    lp.num_col_ = nv
    lp.num_row_ = len(rlo)
    lp.col_cost_ = cost
    lp.col_lower_ = lo
    lp.col_upper_ = hi
    lp.row_lower_ = rlo
    lp.row_upper_ = np.full(len(rlo), highspy.kHighsInf)
    lp.a_matrix_.format_ = highspy.MatrixFormat.kRowwise
    starts = np.zeros(len(rlo) + 1, dtype=np.int32)
    starts[1:] = np.cumsum([len(r) for r in rows_idx])
    lp.a_matrix_.start_ = starts
    lp.a_matrix_.index_ = np.concatenate(rows_idx).astype(np.int32)
    lp.a_matrix_.value_ = np.concatenate(rows_val).astype(float)
    h.passModel(lp)
    h.run()
    st = h.getModelStatus()
    if st != highspy.HighsModelStatus.kOptimal:
        return None
    return np.array(h.getSolution().col_value)


def block_lp(x, y, A, B, C, S, Lmap, which, delta, box, order=None, gapfrac=0.05):
    """One LP step.  Points: x, y (length n).  The free block (which = 'y' or 'x') is
    coord = Lmap @ z with z the LP variables (len nz); the other coordinate is fixed.
    Rows: s_t * det_t(z) / N_t + e_t >= delta, e_t >= 0; minimise sum e_t.
    order: list of point indices whose x must stay increasing (x-step only).
    Returns (new coordinate vector, total slack) or (None, inf)."""
    n = len(x)
    T = len(A)
    nz = Lmap.shape[1]
    ux, uy = x[B] - x[A], y[B] - y[A]
    vx, vy = x[C] - x[A], y[C] - y[A]
    wx, wy = x[C] - x[B], y[C] - y[B]
    lab, lac, lbc = np.hypot(ux, uy), np.hypot(vx, vy), np.hypot(wx, wy)
    N = lab * lac * lbc / np.maximum(np.maximum(lab, lac), lbc) + 1e-300
    if which == "y":   # det = (x_c - x_b) y_a + (x_a - x_c) y_b + (x_b - x_a) y_c
        ca, cb, cc = x[C] - x[B], x[A] - x[C], x[B] - x[A]
    else:              # det = (y_b - y_c) x_a + (y_c - y_a) x_b + (y_a - y_b) x_c
        ca, cb, cc = y[B] - y[C], y[C] - y[A], y[A] - y[B]
    k = S / N
    coef = (k * ca)[:, None] * Lmap[A] + (k * cb)[:, None] * Lmap[B] + (k * cc)[:, None] * Lmap[C]
    rows_idx, rows_val = [], []
    nzmask = coef != 0
    for t in range(T):
        idx = np.nonzero(nzmask[t])[0]
        rows_idx.append(np.append(idx, nz + t))
        rows_val.append(np.append(coef[t, idx], 1.0))
    rlo = [delta] * T
    if order is not None and which == "x":
        for p in range(len(order) - 1):
            i, j = order[p], order[p + 1]
            rows_idx.append(np.array([j, i]))
            rows_val.append(np.array([1.0, -1.0]))
            rlo.append(gapfrac * (x[j] - x[i]))
    nv = nz + T
    cost = np.concatenate([np.zeros(nz), np.ones(T)])
    lo = np.concatenate([np.full(nz, -box), np.zeros(T)])
    hi = np.concatenate([np.full(nz, box), np.full(T, highspy.kHighsInf)])
    z = _lp_solve(nv, rows_idx, rows_val, np.array(rlo, dtype=float), cost, lo, hi)
    if z is None:
        return None, float("inf")
    return z[:nz], float(z[nz:].sum())


# x-grids taken from known realizations (set by set_known_xgrids / --xgrid-pool): sorted x-coordinate
# lists of known point sets, used as x initialisations by the lp method
KNOWN_XGRIDS = []


def set_known_xgrids(point_sets, rotations=4, seed=0):
    """store sorted x-coordinates of the given point sets (and of a few random rotations of each)"""
    r = np.random.default_rng(seed)
    for P in point_sets:
        P = np.array(P, dtype=float)
        for k in range(rotations):
            a = 0.0 if k == 0 else r.uniform(0, 2 * math.pi)
            KNOWN_XGRIDS.append(np.sort(math.cos(a) * P[:, 0] - math.sin(a) * P[:, 1]))


def _known_grid(rng, nn):
    g = KNOWN_XGRIDS[rng.integers(len(KNOWN_XGRIDS))]
    if len(g) >= nn:
        idx = np.sort(rng.choice(len(g), size=nn, replace=False))
        return g[idx]
    return None


def lp_infinity(prob, rng, deadline, x_hint=None, iters=12, log=None):
    """alternating LP with an extreme point sent to y=+infinity.  Returns points or None."""
    if highspy is None:
        return None, None
    n, chi = prob.n, prob.chi
    hv = hull_vertices(chi, n)
    if not hv:
        return None, None
    best_slack = float("inf")
    attempt = 0
    while _clock() < deadline:
        attempt += 1
        v, order = hv[rng.integers(len(hv))]
        nn = n - 1
        lab = order  # new label r -> old point order[r]; x increasing in r
        # reduced triples among the others, relabelled
        A, B, C, S = [], [], [], []
        for i in range(nn):
            for j in range(i + 1, nn):
                for k in range(j + 1, nn):
                    A.append(i); B.append(j); C.append(k)
                    S.append(chi_get(chi, lab[i], lab[j], lab[k]))
        A, B, C, S = map(np.array, (A, B, C, S))
        S = S.astype(float)
        kinds = [0, 1, 2, 3] + ([4] if x_hint is not None else []) + ([5] if KNOWN_XGRIDS else [])
        kind = kinds[attempt % len(kinds)]
        xk = _known_grid(rng, nn) if kind == 5 else None
        if kind == 5 and xk is not None and np.all(np.diff(xk) > 0):
            x = xk.copy()
        elif kind == 5:
            kind = 1
        if kind == 5:
            pass
        elif kind == 0:
            x = np.arange(nn, dtype=float)
        elif kind == 1:
            b = rng.uniform(1.05, 1.8)
            x = b ** np.arange(nn)
        elif kind == 2:
            x = np.cumsum(np.exp(rng.normal(0, rng.choice([0.5, 1.0, 2.0]), size=nn)))
        elif kind == 3:
            # two-sided exponential (dense in the middle)
            b = rng.uniform(1.05, 1.6)
            r = np.arange(nn) - (nn - 1) / 2
            x = np.sign(r) * (b ** np.abs(r) - 1)
        else:
            # the hint's x-values, re-assigned in the required order
            x = np.sort(np.array([x_hint[lab[i]] for i in range(nn)]))
            x = x + 1e-6 * (x.max() - x.min() + 1e-300) * np.arange(nn)
        x = (x - x.min()) / (x.max() - x.min())
        y = np.zeros(nn)
        I = np.eye(nn)
        ord_ = list(range(nn))
        prev = float("inf")
        for it in range(iters):
            if _clock() > deadline:
                break
            z, sl = block_lp(x, y, A, B, C, S, I, "y", 1e-3, 1e4)
            if z is None:
                break
            y = z
            sy = np.max(np.abs(y)) or 1.0
            y = y / sy
            best_slack = min(best_slack, sl)
            if sl < 1e-9:
                pts = _place_infinity(prob, v, lab, x, y)
                if pts is not None:
                    if log:
                        log(f"lp: realized at attempt {attempt} iter {it} kind {kind}")
                    return pts, 0.0
            z, sl = block_lp(x, y, A, B, C, S, I, "x", 1e-3, 1e4, order=ord_)
            if z is None:
                break
            x = (z - z.min()) / (z.max() - z.min())
            best_slack = min(best_slack, sl)
            if sl < 1e-9:
                pts = _place_infinity(prob, v, lab, x, y)
                if pts is not None:
                    if log:
                        log(f"lp: realized at attempt {attempt} iter {it}x kind {kind}")
                    return pts, 0.0
            if sl > prev * 0.999:
                break
            prev = sl
        if log and attempt % 10 == 0:
            log(f"lp attempt {attempt}: best slack {best_slack:.3g}")
    return None, best_slack


def _place_infinity(prob, v, lab, x, y):
    """round the n-1 finite points, check their triples exactly, then put v at (0, L) with L exact."""
    nn = len(lab)
    sub_chi_ok = None
    for k in (14, 18, 22, 26, 30, 36, 44, 56):
        s = max(np.max(np.abs(x)), np.max(np.abs(y)))
        sc = 2.0 ** k / s
        P = [(int(round(x[i] * sc)), int(round(y[i] * sc))) for i in range(nn)]
        if any(P[i + 1][0] <= P[i][0] for i in range(nn - 1)):
            continue
        pts = [None] * prob.n
        for i in range(nn):
            pts[lab[i]] = P[i]
        # L: need x_i*y_j - y_i*x_j + L*(x_j - x_i) > 0 for all i<j (x increasing)
        L = 1
        for i in range(nn):
            for j in range(i + 1, nn):
                num = -(P[i][0] * P[j][1] - P[i][1] * P[j][0])
                den = P[j][0] - P[i][0]
                q = num // den + 1
                if q > L:
                    L = q
        pts[v] = (0, L + 1)
        if quick_check(prob, pts) == 0:
            return pts
    return None


# =============================================================== random-direction LP repair
def dir_repair(A, B, C, S, x, y, deadline, rounds=30, rng=None, delta=1e-3):
    """Alternating LPs along random directions: rotate by -alpha, solve for the new y with the new x
    fixed (orientations are linear in y), rotate back.  Minimises total relative slack.
    Returns (x, y, slack)."""
    n = len(x)
    I = np.eye(n)
    best = float("inf")
    stall = 0
    for r in range(rounds):
        if _clock() > deadline:
            break
        al = rng.uniform(0, math.pi) if rng is not None else r * 0.7
        c, s_ = math.cos(al), math.sin(al)
        xr, yr = c * x + s_ * y, -s_ * x + c * y
        z, sl = block_lp(xr, yr, A, B, C, S, I, "y", delta, 1e4)
        if z is None:
            break
        yr = z
        x, y = c * xr - s_ * yr, s_ * xr + c * yr
        x, y = x - x.mean(), y - y.mean()
        sc = max(np.max(np.abs(x)), np.max(np.abs(y)))
        x, y = x / sc, y / sc
        if sl < best * 0.999:
            best, stall = sl, 0
        else:
            stall += 1
        if sl < 1e-9 or stall >= 6:
            best = min(best, sl)
            break
    return x, y, best


def _triples_of(prob, idx):
    """triples (in local indices) of the sub-chirotope on the points idx"""
    k = len(idx)
    A, B, C, S = [], [], [], []
    for i in range(k):
        for j in range(i + 1, k):
            for l in range(j + 1, k):
                A.append(i); B.append(j); C.append(l)
                S.append(chi_get(prob.chi, idx[i], idx[j], idx[l]))
    return np.array(A), np.array(B), np.array(C), np.array(S, dtype=float)


def _cell_point(px, py, pairs_s, box):
    """maximise t s.t. s*det(a,b,p)/|b-a| >= t for all placed pairs (a,b) with required sign s.
    Returns (x, y, t)."""
    ax, ay, bx, by, s = pairs_s
    L = np.hypot(bx - ax, by - ay) + 1e-300
    # s*((bx-ax)(qy-ay) - (by-ay)(qx-ax))/L - t >= 0
    cx = -s * (by - ay) / L
    cy = s * (bx - ax) / L
    c0 = s * (-(bx - ax) * ay + (by - ay) * ax) / L
    # the four box faces as extra rows: +-x - t >= -box, +-y - t >= -box
    cx = np.concatenate([cx, [1.0, -1.0, 0.0, 0.0]])
    cy = np.concatenate([cy, [0.0, 0.0, 1.0, -1.0]])
    c0 = np.concatenate([c0, [box, box, box, box]])
    T = len(cx)
    rlo = -c0
    h = highspy.Highs()
    h.setOptionValue("output_flag", False)
    h.setOptionValue("threads", 1)
    lp = highspy.HighsLp()
    lp.num_col_ = 3
    lp.num_row_ = T
    lp.col_cost_ = np.array([0.0, 0.0, -1.0])
    lp.col_lower_ = np.array([-box, -box, -highspy.kHighsInf])
    lp.col_upper_ = np.array([box, box, highspy.kHighsInf])
    lp.row_lower_ = rlo
    lp.row_upper_ = np.full(T, highspy.kHighsInf)
    lp.a_matrix_.format_ = highspy.MatrixFormat.kRowwise
    lp.a_matrix_.start_ = np.arange(0, 3 * T + 1, 3, dtype=np.int32)
    lp.a_matrix_.index_ = np.tile(np.array([0, 1, 2], dtype=np.int32), T)
    lp.a_matrix_.value_ = np.column_stack([cx, cy, -np.ones(T)]).ravel()
    h.passModel(lp)
    h.run()
    if h.getModelStatus() != highspy.HighsModelStatus.kOptimal:
        return None
    z = h.getSolution().col_value
    return z[0], z[1], z[2]


def insertion(prob, rng, deadline, log=None, order=None, failfirst=False):
    """Incremental insertion: each new point is put at the centre of the largest disc inside its
    cell (the intersection of the half-planes given by its orientations with all placed pairs, an
    exact 2-D LP).  When the cell is empty the new point is put at the least-violating position and
    the whole placed configuration is repaired by random-direction LPs; if that fails, restart with
    another random order.  failfirst=True ("ins-ff"): instead of a fixed random order, compute the
    cell of every remaining point and insert the most constrained one (smallest inscribed disc;
    an empty cell first).  Returns integer points or None."""
    if highspy is None:
        return None, None
    n, chi = prob.n, prob.chi
    best_k = 0
    attempt = 0
    while _clock() < deadline:
        attempt += 1
        if order is not None and attempt == 1:
            ordr = list(order)
        else:
            ordr = [int(v) for v in rng.permutation(n)]
        a, b, c = ordr[:3]
        X = {a: 0.0, b: 1.0}
        Y = {a: 0.0, b: 0.0}
        X[c] = 0.5
        Y[c] = 0.8 * chi_get(chi, a, b, c)
        placed = [a, b, c]
        ok = True
        for k in range(3, n):
            if _clock() > deadline:
                ok = False
                break
            xs = np.array([X[q] for q in placed]); ys = np.array([Y[q] for q in placed])
            xs, ys = xs - xs.mean(), ys - ys.mean()
            sc0 = max(np.max(np.abs(xs)), np.max(np.abs(ys)))
            xs, ys = xs / sc0, ys / sc0
            for q, xv, yv in zip(placed, xs, ys):
                X[q], Y[q] = xv, yv
            ii, jj = np.triu_indices(len(placed), 1)
            box = 2.0
            if failfirst:
                cand = []
                pl = set(placed)
                for p_ in ordr:
                    if p_ in pl:
                        continue
                    s_ = np.array([chi_get(chi, placed[i], placed[j], p_) for i, j in zip(ii, jj)], dtype=float)
                    r_ = _cell_point(None, None, (xs[ii], ys[ii], xs[jj], ys[jj], s_), box)
                    if r_ is None:
                        continue
                    noise = math.exp(rng.normal(0, 0.5)) if attempt > 1 else 1.0
                    key = r_[2] * noise if r_[2] > 0 else r_[2] - 1e9
                    cand.append((key, p_, r_))
                if not cand:
                    ok = False
                    break
                cand.sort(key=lambda c_: c_[0])
                _, p, r = cand[0]
            else:
                p = ordr[k]
                s = np.array([chi_get(chi, placed[i], placed[j], p) for i, j in zip(ii, jj)], dtype=float)
                r = _cell_point(None, None, (xs[ii], ys[ii], xs[jj], ys[jj], s), box)
            if r is None:
                ok = False
                break
            qx, qy, t = r
            X[p], Y[p] = qx, qy
            placed.append(p)
            if t <= 1e-12 * box:
                # empty cell: repair the placed configuration (penalty descent from the current
                # positions on the sub-chirotope, then random-direction LPs)
                sub = Prob({(i, j, l): chi_get(chi, placed[i], placed[j], placed[l])
                            for i in range(len(placed)) for j in range(i + 1, len(placed))
                            for l in range(j + 1, len(placed))}, len(placed))
                x = np.array([X[q] for q in placed]); y = np.array([Y[q] for q in placed])
                sl = 1.0
                pts_, bv, bxy = penalty_descent(sub, rng, min(deadline, _clock() + 2.0), mode="free",
                                                R=16, steps=300, init=(x, y), max_rounds=2)
                if pts_ is not None:
                    x = np.array([float(q[0]) for q in pts_]); y = np.array([float(q[1]) for q in pts_])
                    sl = 0.0
                elif bxy is not None:
                    x, y, sl = dir_repair(sub.A, sub.B, sub.C, sub.S, bxy[0], bxy[1], deadline, rounds=20, rng=rng)
                if sl > 1e-9:
                    ok = False
                    if log:
                        log(f"ins attempt {attempt}: stuck at {k + 1}/{n} points (slack {sl:.3g})")
                    break
                for q, xv, yv in zip(placed, x, y):
                    X[q], Y[q] = xv, yv
            best_k = max(best_k, k + 1)
        if not ok:
            continue
        x = np.array([X[i] for i in range(n)]); y = np.array([Y[i] for i in range(n)])
        pts = try_exact(prob, x, y)
        if pts is not None:
            if log:
                log(f"ins: realized at attempt {attempt}")
            return pts, 0
        # float configuration with tiny margins: polish once with LP margins
        x, y, sl = dir_repair(prob.A, prob.B, prob.C, prob.S, x, y, deadline, rounds=6, rng=rng)
        pts = try_exact(prob, x, y)
        if pts is not None:
            return pts, 0
    return None, n - best_k


# =============================================================== symmetric (m = 2) insertion
def _affine_rows(chi, labels, coef, base, newpts):
    """rows (gx, gy, g0, s) for every triple that contains a new point: point i is
    coef[i]*p + base[i] (coef 0 for placed points); det is affine in p because det(p, p) = 0."""
    rows = []
    allp = list(labels)
    for a_i in range(len(allp)):
        for b_i in range(a_i + 1, len(allp)):
            for c_i in range(b_i + 1, len(allp)):
                A_, B_, C_ = allp[a_i], allp[b_i], allp[c_i]
                if A_ not in newpts and B_ not in newpts and C_ not in newpts:
                    continue
                cu, cv = coef[B_] - coef[A_], coef[C_] - coef[A_]
                u0x, u0y = base[B_][0] - base[A_][0], base[B_][1] - base[A_][1]
                v0x, v0y = base[C_][0] - base[A_][0], base[C_][1] - base[A_][1]
                gx = cu * v0y - cv * u0y
                gy = -cu * v0x + cv * u0x
                g0 = u0x * v0y - u0y * v0x
                rows.append((gx, gy, g0, chi_get(chi, A_, B_, C_)))
    return rows


def _cell_rows(rows, box):
    """max t s.t. s*(gx px + gy py + g0)/|g| >= t, inside the box.  Returns (px, py, t) or None."""
    R_ = np.array(rows, dtype=float)
    gx, gy, g0, s = R_[:, 0], R_[:, 1], R_[:, 2], R_[:, 3]
    nrm = np.hypot(gx, gy)
    keep = nrm > 1e-300
    if not np.all(keep):
        # constant rows: must already have the right sign
        if np.any(s[~keep] * g0[~keep] <= 0):
            return None
        gx, gy, g0, s, nrm = gx[keep], gy[keep], g0[keep], s[keep], nrm[keep]
    cx = np.concatenate([s * gx / nrm, [1.0, -1.0, 0.0, 0.0]])
    cy = np.concatenate([s * gy / nrm, [0.0, 0.0, 1.0, -1.0]])
    c0 = np.concatenate([s * g0 / nrm, [box, box, box, box]])
    T = len(cx)
    h = highspy.Highs()
    h.setOptionValue("output_flag", False)
    h.setOptionValue("threads", 1)
    lp = highspy.HighsLp()
    lp.num_col_ = 3
    lp.num_row_ = T
    lp.col_cost_ = np.array([0.0, 0.0, -1.0])
    lp.col_lower_ = np.array([-box, -box, -highspy.kHighsInf])
    lp.col_upper_ = np.array([box, box, highspy.kHighsInf])
    lp.row_lower_ = -c0
    lp.row_upper_ = np.full(T, highspy.kHighsInf)
    lp.a_matrix_.format_ = highspy.MatrixFormat.kRowwise
    lp.a_matrix_.start_ = np.arange(0, 3 * T + 1, 3, dtype=np.int32)
    lp.a_matrix_.index_ = np.tile(np.array([0, 1, 2], dtype=np.int32), T)
    lp.a_matrix_.value_ = np.column_stack([cx, cy, -np.ones(T)]).ravel()
    h.passModel(lp)
    h.run()
    if h.getModelStatus() != highspy.HighsModelStatus.kOptimal:
        return None
    z = h.getSolution().col_value
    return z[0], z[1], z[2]


def sym2_insertion(prob, rng, deadline, log=None):
    """m = 2 (points q_o, -q_o): insert whole orbits.  For a new orbit {p, -p} every required
    orientation with the placed points, including (a, p, -p), is affine in p, so the cell is an exact
    convex polygon; p goes to its Chebyshev centre.  Empty cells are repaired by symmetric penalty
    descent started from the current configuration, then symmetric random-direction LPs."""
    if highspy is None or prob.m != 2 or prob.hc:
        return None, None
    n, t, chi = prob.n, prob.t, prob.chi
    best_k = 0
    attempt = 0
    while _clock() < deadline:
        attempt += 1
        orbs = [int(v) for v in rng.permutation(t)]
        pos = {}
        o0 = orbs[0]
        pos[2 * o0] = (1.0, 0.0)
        pos[2 * o0 + 1] = (-1.0, 0.0)
        placed_orbs = [o0]
        ok = True
        bv = None
        remaining = orbs[1:]
        for k in range(1, t):
            if _clock() > deadline:
                ok = False
                break
            ext = max(max(abs(v[0]), abs(v[1])) for v in pos.values())
            # fail-first: compute the cell of every remaining orbit, insert the most constrained one
            # (an empty cell is a conflict that must be repaired now)
            cand = []
            for o in remaining:
                labels = sorted(pos.keys()) + [2 * o, 2 * o + 1]
                coef = {i: 0.0 for i in pos}
                base = dict(pos)
                coef[2 * o], base[2 * o] = 1.0, (0.0, 0.0)
                coef[2 * o + 1], base[2 * o + 1] = -1.0, (0.0, 0.0)
                rows = _affine_rows(chi, labels, coef, base, {2 * o, 2 * o + 1})
                r = _cell_rows(rows, 2.0 * ext)
                if r is None:
                    continue
                noise = math.exp(rng.normal(0, 0.5)) if attempt > 1 else 1.0
                key = r[2] * noise if r[2] > 0 else r[2] - 1e9
                cand.append((key, o, r))
            if not cand:
                ok = False
                break
            cand.sort(key=lambda c: c[0])
            _, o, r = cand[0]
            remaining.remove(o)
            px, py, tt = r
            pos[2 * o], pos[2 * o + 1] = (px, py), (-px, -py)
            placed_orbs.append(o)
            if tt <= 1e-12 * ext:
                # repair: sub-problem on the placed orbits, relabelled 0..2k+1 (orbit order kept)
                lab = []
                for oo in placed_orbs:
                    lab += [2 * oo, 2 * oo + 1]
                sub_chi = {}
                for i in range(len(lab)):
                    for j in range(i + 1, len(lab)):
                        for l in range(j + 1, len(lab)):
                            sub_chi[(i, j, l)] = chi_get(chi, lab[i], lab[j], lab[l])
                sub = Prob(sub_chi, len(lab), 2, False)
                x = np.array([pos[q][0] for q in lab]); y = np.array([pos[q][1] for q in lab])
                pts_, bv, bxy = penalty_descent(sub, rng, min(deadline, _clock() + 3.0), mode="sym",
                                                R=24, steps=300, init=(x, y), max_rounds=2)
                if pts_ is None and bxy is not None:
                    pts_, _ = lp2_polish(sub, bxy[0], bxy[1], min(deadline, _clock() + 3.0), iters=6, rng=rng)
                if pts_ is None:
                    ok = False
                    if log:
                        log(f"sym2-ins attempt {attempt}: stuck at orbit {k + 1}/{t} (violations {bv})")
                    break
                sc_ = float(max(max(abs(q[0]), abs(q[1])) for q in pts_))
                for q, (xv, yv) in zip(lab, pts_):
                    pos[q] = (xv / sc_, yv / sc_)
            else:
                ext2 = max(max(abs(v[0]), abs(v[1])) for v in pos.values())
                for q in list(pos):
                    pos[q] = (pos[q][0] / ext2, pos[q][1] / ext2)
            best_k = max(best_k, k + 1)
        if not ok:
            continue
        x = np.array([pos[i][0] for i in range(n)]); y = np.array([pos[i][1] for i in range(n)])
        pts = try_exact(prob, x, y)
        if pts is not None:
            if log:
                log(f"sym2-ins: realized at attempt {attempt}")
            return pts, 0
    return None, t - best_k


# =============================================================== symmetric m = 2 LP
def lp2_polish(prob, x, y, deadline, iters=20, log=None, rng=None):
    """m = 2: points (o,0) = q_o, (o,1) = -q_o.  Alternate LPs in the y_o and x_o."""
    if highspy is None or prob.m != 2:
        return None, None
    n, t = prob.n, prob.t
    Lmap = np.zeros((n, t))
    for i in range(n):
        Lmap[i, i // 2] = 1.0 if i % 2 == 0 else -1.0
    A, B, C, S = prob.A, prob.B, prob.C, prob.S
    x, y = x.copy(), y.copy()
    s = max(np.max(np.abs(x)), np.max(np.abs(y)))
    x, y = x / s, y / s
    prev = float("inf")
    best = float("inf")
    for it in range(iters):
        if _clock() > deadline:
            break
        for which in ("y", "x"):
            # rotate by a random angle (rotations about the centre keep the symmetry), solve for y
            al = rng.uniform(0, math.pi) if rng is not None else (0.0 if which == "y" else math.pi / 2)
            c, s_ = math.cos(al), math.sin(al)
            xr, yr = c * x + s_ * y, -s_ * x + c * y
            z, sl = block_lp(xr, yr, A, B, C, S, Lmap, "y", 1e-3, 1e4)
            if z is None:
                return None, best
            yr = Lmap @ z
            x, y = c * xr - s_ * yr, s_ * xr + c * yr
            s = max(np.max(np.abs(x)), np.max(np.abs(y)))
            x, y = x / s, y / s
            best = min(best, sl)
            if sl < 1e-9:
                pts = try_exact(prob, x, y)
                if pts is not None:
                    if log:
                        log(f"lp2: realized at iter {it}{which}")
                    return pts, 0.0
        if best > prev * 0.999:
            break
        prev = best
    return None, best


# =============================================================== driver
def default_methods(m, has_center):
    """the portfolio used when methods = "auto" (chosen from the calibration runs of task F)"""
    if m == 1:
        return ["ins-ff", "lp"]
    if m == 2 and not has_center:
        return ["ins", "sym", "lp", "ins-ff"]
    return ["sym", "lp", "ins-ff", "polish"]


def realize(chi, n, m=1, has_center=False, budget=30.0, seed=1, methods="auto",
            log=None, R=None, steps=None, passes=(0.1, 0.3, 0.6)):
    """Try to realize chi within `budget` CPU seconds.  The methods are run as a portfolio in
    passes: pass p gets the fraction passes[p] of the budget, split evenly over the methods, so a
    method that fails early does not use up the budget.  Returns a dict with keys realized, points
    (integer list, label order), method, seconds (CPU), wall_seconds, best_violations (fewest
    violated triples seen in penalty descent) and diagnostics.  realized=True only after
    verify_exact (exact Fraction arithmetic) accepts the integer points."""
    t0 = _clock()
    w0 = time.time()
    rng = np.random.default_rng(seed)
    prob = Prob(chi, n, m, has_center)
    if methods in (None, "auto") or list(methods) == ["auto"]:
        methods = default_methods(m, has_center)
    if m == 1:
        methods = [mm for mm in methods if mm not in ("sym", "lp2")]
    res = {"realized": False, "method": None, "best_violations": None}
    hint = None
    tot = float(sum(passes))
    spent_frac = 0.0
    for frac in passes:
        spent_frac += frac / tot
        pass_end = t0 + budget * spent_frac
        for i, meth in enumerate(methods):
            rem = pass_end - _clock()
            if rem <= 0:
                break
            deadline = _clock() + rem / (len(methods) - i)
            pts = None
            if meth in ("sym", "free"):
                pts, bv, bxy = penalty_descent(prob, rng, deadline, mode=meth, R=R or 48, steps=steps or 700, log=log)
                if bxy is not None:
                    hint = bxy
                if res["best_violations"] is None or bv < res["best_violations"]:
                    res["best_violations"] = bv
                if pts is None and meth == "sym" and m == 2 and bxy is not None and highspy is not None:
                    pts, _ = lp2_polish(prob, bxy[0], bxy[1], deadline + 2, log=log, rng=rng)
                    if pts is not None:
                        meth = "sym+lp2"
            elif meth == "lp":
                pts, bs = lp_infinity(prob, rng, deadline, x_hint=(hint[0] if hint else None), log=log)
                if pts is None and bs is not None:
                    res["lp_best_slack"] = min(res.get("lp_best_slack", float("inf")), float(bs))
            elif meth == "ins":
                if m == 2 and not has_center:
                    pts, unp = sym2_insertion(prob, rng, deadline, log=log)
                    if pts is not None:
                        meth = "sym2-ins"
                    elif unp is not None:
                        res["insertion_max_orbits_placed"] = max(res.get("insertion_max_orbits_placed", 0), prob.t - unp)
                else:
                    pts, unp = insertion(prob, rng, deadline, log=log)
                    if pts is None and unp is not None:
                        res["insertion_max_points_placed"] = max(res.get("insertion_max_points_placed", 0), n - unp)
            elif meth == "ins-free":
                pts, _ = insertion(prob, rng, deadline, log=log)
            elif meth == "ins-ff":
                pts, unp = insertion(prob, rng, deadline, log=log, failfirst=True)
                if pts is None and unp is not None:
                    res["insertion_ff_max_points_placed"] = max(res.get("insertion_ff_max_points_placed", 0), n - unp)
            elif meth == "polish" and hint is not None and highspy is not None:
                # non-symmetric LP repair of the best penalty-descent configuration
                x, y, sl = dir_repair(prob.A, prob.B, prob.C, prob.S, hint[0], hint[1], deadline, rounds=60, rng=rng)
                if sl < 1e-9:
                    pts = try_exact(prob, x, y)
            if pts is not None:
                ok, bad, zero = verify_exact(pts, chi)
                if ok:
                    res.update(realized=True, points=[list(p) for p in pts], method=meth, best_violations=0)
                    break
        if res["realized"]:
            break
    res["seconds"] = round(_clock() - t0, 3)
    res["wall_seconds"] = round(time.time() - w0, 3)
    return res


def read_point_sets(path):
    """lines 'label [label2] hash n x1 y1 ... xn yn' (the inputs/distinct_K7*.txt format) or 'n x1 y1 ...'"""
    out = []
    for line in open(path):
        p = line.split()
        for i in range(len(p)):
            if p[i].lstrip("-").isdigit() and 2 * int(p[i]) == len(p) - i - 1:
                c = list(map(int, p[i + 1:]))
                out.append([(c[2 * j], c[2 * j + 1]) for j in range(len(c) // 2)])
                break
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sig")
    ap.add_argument("--m", type=int, default=1)
    ap.add_argument("--center", action="store_true")
    ap.add_argument("--time", type=float, default=30.0, help="CPU-second budget")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--methods", default="auto",
                    help="comma list of sym,free,ins,ins-ff,ins-free,lp,polish, or auto (see default_methods)")
    ap.add_argument("--out")
    ap.add_argument("--verbose", action="store_true")
    ap.add_argument("--xgrid-pool", help="file of known point sets ('... n x1 y1 ... xn yn' per line); "
                    "their sorted x-coordinates seed the lp method")
    a = ap.parse_args()
    if a.xgrid_pool:
        set_known_xgrids(read_point_sets(a.xgrid_pool))
    chi = read_sig(a.sig)
    n = max(max(k) for k in chi) + 1
    log = (lambda s: print(s, file=sys.stderr, flush=True)) if a.verbose else None
    res = realize(chi, n, a.m, a.center, a.time, a.seed, a.methods.split(","), log=log)
    if res["realized"] and a.out:
        with open(a.out, "w") as f:
            for x, y in res["points"]:
                f.write(f"{x} {y}\n")
    out = {k: v for k, v in res.items() if k != "points"}
    out["sig"] = a.sig
    print(json.dumps(out), flush=True)
    sys.exit(0 if res["realized"] else 1)


if __name__ == "__main__":
    main()
