#!/usr/bin/env python3
"""Heuristic realizer for (optionally rotationally symmetric) uniform chirotopes, with exact check.

Input: a chirotope on n points (all C(n,3) triples, ".sig" lines "a b c s", 0-based, s = +1 for
counter-clockwise).  Output: integer points whose orientation signs equal the chirotope exactly
(checked in exact integer/Fraction arithmetic), or "not realized" (which proves nothing).

Symmetry convention (that of tools/symmetric/symcnf.py): point o*m + r is R^r applied to the orbit
representative q_o, R the rotation by 2*pi/m; the centre, if present, is the last point and sits at
the origin.  For m >= 3 the direction of R is read off the chirotope (chi(0,1,2) = +1 means
counter-clockwise); symcnf.py models of even m without centre come in both directions.

Methods (a portfolio: passes with 10%, 30%, 60% of the CPU budget, each split over the methods):
  sym     symmetric penalty descent: only the orbit representatives vary, in log-polar coordinates
          (u_o, theta_o); orbit 0 fixes rotation and scale.  Loss = sum over triples of
          max(0, delta - g_t)^2 with g_t = s_t*det/(l1*l2), l1, l2 the two shortest sides of the
          triangle (scale-free, so multi-scale configurations are not penalised).  Batched Adam over
          random multi-scale starts plus perturbations of the best chain (leaderboard restarts, as in
          Localizer).  For m = 2 the best chain is then polished by lp2.
  free    the same penalty descent on all 2n coordinates (no symmetry).
  ins     incremental insertion with exact 2-D cells (ins-ff: m = 1 variant with fail-first order;
          ins-free: m = 1 insertion ignoring the symmetry).  m = 2: whole orbits {p, -p} are inserted; all
          orientations with placed points, including (a, p, -p), are affine in p, so the cell of p is
          a convex polygon and p goes to its Chebyshev centre; the most constrained remaining orbit is
          inserted first (fail-first); an empty cell triggers a repair (symmetric penalty descent from
          the current positions, then lp2).  m = 1: the same, point by point, with free repairs.
  lp      alternating linear programs ("linear subreduction" with alternation): an abstract extreme
          point v is sent to y = +infinity, so the angular order around v becomes the x-order of the
          other n-1 points; x is initialised from a grid (uniform, exponential with random base,
          random log-normal gaps, two-sided exponential, x-coordinates of known realizations given by
          --xgrid-pool, or of the best penalty-descent chain); then
            repeat: fix x, LP in y minimising the total slack of s*det/N_t >= delta;
                    fix y, LP in x (x-order kept) minimising the same slack;
          until the slack is 0 (a realization) or stalls.  v is then placed at (0, L), L exact.
  lp2     (m = 2) the alternation in symmetric form along random directions: rotations about the
          centre keep the symmetry, and with the rotated x_o fixed the orientations are linear in y_o.
  polish  non-symmetric random-direction LP repair of the best penalty-descent configuration.
Every floating-point success is rounded to integers at increasing scales (for m = 2 and m = 4 the
orbits are generated by the exact integer rotation, so the integer set is exactly symmetric) and
all C(n,3) orientations are re-checked exactly.  Nothing is reported as realized otherwise.

usage: realize.py file.sig [--m M] [--center] [--time CPU_SECONDS] [--seed S]
                           [--methods auto|LIST] [--xgrid-pool FILE] [--out points.txt]
  --methods auto (default): m = 1: ins-ff,lp;  m = 2 without centre: ins,sym,lp,ins-ff;
                            otherwise sym,lp,ins-ff,polish.
  --center: the last point is the centre of the rotation (fixed at the origin).
Prints a JSON line {"realized": bool, "method": ..., "seconds": CPU s, ...}; exit code 0 iff realized.
Needs numpy and highspy (the LP methods are skipped without highspy).
"""
