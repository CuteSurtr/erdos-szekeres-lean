/* Localizer-style realizer for (rotationally symmetric) chirotopes.
 *
 * Input: a full chirotope on N points given as lines "a b c s" (0-based, a<b<c, s=+1/-1), all
 * C(N,3) triples.  Symmetry: the rotation R by 2*pi/m about the origin acts on the points;
 * point i = o*m + r is R^r applied to the representative q_o (o = 0..t-1, t = (N-has_center)/m);
 * an optional centre is the last point and is fixed at the origin.  m = 1 means no symmetry.
 *
 * Search (after Subercaseaux-Mackey-Qian-Heule 2025, "Localizer"): simulated annealing over the
 * representatives.  Energy = number of violated triples (orientation sign != required, 0 counts
 * as violated).  A representative is chosen with probability proportional to the number of
 * violated triples through its orbit (+eps); it is moved inside a ball whose radius decays
 * exponentially during a restart; Metropolis acceptance with a geometrically cooling
 * temperature.  Restarts are either random or perturbations of a top-K leaderboard entry.
 * Several threads run independent chains and stop as soon as one of them succeeds.
 *
 * Exactness: when a chain reaches energy 0, the representatives are rounded to integers at
 * increasing scales; for m=2 and m=4 the orbit is generated by the EXACT integer symmetry
 * ((x,y) -> (-x,-y) resp. (-y,x)), so the integer set is exactly symmetric; otherwise every point
 * is rounded independently.  All C(N,3) orientations are then re-checked in __int128 arithmetic.
 * Only an integer set passing this check is reported as REALIZED (re-check it independently).
 *
 * usage: localizer N m has_center file.sig seed threads time_limit_s out.pts [key=value ...]
 *   keys: steps (per restart, default 200000) T0 T1 (temperature, 1.0 .. 0.02) r0 r1 (radius,
 *         0.6 .. 1e-4) pjump (prob. of a uniform re-placement move, 0.02) topk (8)
 *         plb (prob. that a restart starts from the leaderboard, 0.5) pert (perturbation radius
 *         for leaderboard restarts, 0.05) eps (0.5) verbose (0/1)
 * Exit code 0 = realized, 1 = not realized, 2 = usage/input error.
 */
#include <math.h>
#include <pthread.h>
#include <stdatomic.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

#define MAXN 64

static int N, M, HASC, T_ORB;                /* points, fold, centre flag, number of orbits */
static signed char CHI[MAXN][MAXN][MAXN];    /* required orientation, antisymmetric */
static int NTRI;                             /* C(N,3) */
static int *TRI_A, *TRI_B, *TRI_C;           /* triple id -> points */
static int (*TID)[MAXN][MAXN];               /* (a<b<c) -> triple id */
static int **AFF, *NAFF;                     /* per orbit: triple ids touching the orbit */
static double CR[64], SR[64];                /* rotation table */

/* parameters */
static long P_STEPS = 200000;
static double P_T0 = 1.0, P_T1 = 0.02, P_R0 = 0.6, P_R1 = 1e-4, P_PJUMP = 0.02, P_PLB = 0.5, P_PERT = 0.05, P_EPS = 0.5;
static int P_TOPK = 8, P_VERBOSE = 0;
static double TIME_LIMIT = 60;
static const char *OUT_PATH;
static struct timespec T_START;

static atomic_int FOUND = 0;
static atomic_int GLOBAL_BEST = 1 << 30;
static pthread_mutex_t IO_LOCK = PTHREAD_MUTEX_INITIALIZER;
static double BEST_QX[MAXN], BEST_QY[MAXN];   /* best (lowest energy) representatives seen */

static double now_s(void) {
    struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t);
    return (t.tv_sec - T_START.tv_sec) + 1e-9 * (t.tv_nsec - T_START.tv_nsec);
}

/* ---------------- RNG ---------------- */
typedef struct { unsigned long long s; } rng_t;
static inline unsigned long long rng_u64(rng_t *r) {
    unsigned long long x = r->s; x ^= x >> 12; x ^= x << 25; x ^= x >> 27; r->s = x;
    return x * 2685821657736338717ULL;
}
static inline double rng_d(rng_t *r) { return (double)(rng_u64(r) >> 11) / 9007199254740992.0; }

/* ---------------- geometry ---------------- */
static inline void orbit_coords(int o, double qx, double qy, double *px, double *py) {
    for (int r = 0; r < M; r++) {
        px[r] = CR[r] * qx - SR[r] * qy;
        py[r] = SR[r] * qx + CR[r] * qy;
    }
}

static inline int tri_sign(const double *x, const double *y, int a, int b, int c) {
    double d = (x[b] - x[a]) * (y[c] - y[a]) - (y[b] - y[a]) * (x[c] - x[a]);
    return d > 0 ? 1 : (d < 0 ? -1 : 0);
}

/* ---------------- exact integer check ---------------- */
static int exact_check(const long long *X, const long long *Y) {
    int bad = 0;
    for (int t = 0; t < NTRI; t++) {
        int a = TRI_A[t], b = TRI_B[t], c = TRI_C[t];
        __int128 d = (__int128)(X[b] - X[a]) * (Y[c] - Y[a]) - (__int128)(Y[b] - Y[a]) * (X[c] - X[a]);
        int sg = d > 0 ? 1 : (d < 0 ? -1 : 0);
        if (sg != CHI[a][b][c]) bad++;
    }
    return bad;
}

/* round representatives at scale 2^sc; returns 1 if the integer set satisfies every triple exactly */
static int try_round(const double *qx, const double *qy, int sc, long long *X, long long *Y) {
    double S = ldexp(1.0, sc);
    for (int o = 0; o < T_ORB; o++) {
        long long rx = llround(qx[o] * S), ry = llround(qy[o] * S);
        if (M == 2) {
            X[2 * o] = rx; Y[2 * o] = ry; X[2 * o + 1] = -rx; Y[2 * o + 1] = -ry;
        } else if (M == 4) {
            X[4 * o] = rx; Y[4 * o] = ry;
            X[4 * o + 1] = -ry; Y[4 * o + 1] = rx;
            X[4 * o + 2] = -rx; Y[4 * o + 2] = -ry;
            X[4 * o + 3] = ry; Y[4 * o + 3] = -rx;
        } else if (M == 1) {
            X[o] = rx; Y[o] = ry;
        } else {
            double px[64], py[64];
            orbit_coords(o, qx[o], qy[o], px, py);
            for (int r = 0; r < M; r++) { X[o * M + r] = llround(px[r] * S); Y[o * M + r] = llround(py[r] * S); }
        }
    }
    if (HASC) { X[N - 1] = 0; Y[N - 1] = 0; }
    return exact_check(X, Y) == 0;
}

/* ---------------- chain state ---------------- */
typedef struct {
    double qx[MAXN], qy[MAXN];
    double x[MAXN], y[MAXN];
    unsigned char *status;     /* per triple: 1 = violated */
    int viol[MAXN];            /* per point: violated triples through it */
    int E;
} state_t;

static void state_eval(state_t *s) {
    for (int o = 0; o < T_ORB; o++) {
        double px[64], py[64];
        orbit_coords(o, s->qx[o], s->qy[o], px, py);
        for (int r = 0; r < M; r++) { s->x[o * M + r] = px[r]; s->y[o * M + r] = py[r]; }
    }
    if (HASC) { s->x[N - 1] = 0; s->y[N - 1] = 0; }
    memset(s->viol, 0, sizeof(s->viol));
    s->E = 0;
    for (int t = 0; t < NTRI; t++) {
        int a = TRI_A[t], b = TRI_B[t], c = TRI_C[t];
        int v = tri_sign(s->x, s->y, a, b, c) != CHI[a][b][c];
        s->status[t] = (unsigned char)v;
        if (v) { s->E++; s->viol[a]++; s->viol[b]++; s->viol[c]++; }
    }
}

static void state_random(state_t *s, rng_t *rng) {
    for (int o = 0; o < T_ORB; o++) {
        double rad = sqrt(rng_d(rng)), an = 2 * M_PI * rng_d(rng);
        s->qx[o] = rad * cos(an); s->qy[o] = rad * sin(an);
    }
    state_eval(s);
}

typedef struct {
    double qx[MAXN], qy[MAXN];
    int E;
    int used;
} lb_entry_t;

typedef struct {
    int id;
    unsigned long long seed;
    long steps_done;
    int restarts;
    int bestE;
} thread_arg_t;

static void *worker(void *varg) {
    thread_arg_t *arg = (thread_arg_t *)varg;
    rng_t rng = { arg->seed * 0x9E3779B97F4A7C15ULL + 0xD1B54A32D192ED03ULL * (arg->id + 1) };
    for (int i = 0; i < 10; i++) rng_u64(&rng);
    state_t *s = calloc(1, sizeof(state_t));
    s->status = malloc(NTRI);
    unsigned char *newstat = malloc(NTRI);
    lb_entry_t *lb = calloc(P_TOPK, sizeof(lb_entry_t));
    for (int i = 0; i < P_TOPK; i++) lb[i].E = 1 << 30;
    long long *X = malloc(sizeof(long long) * N), *Y = malloc(sizeof(long long) * N);
    double tx[MAXN], ty[MAXN];
    int bestE = 1 << 30;
    double logT = log(P_T1 / P_T0), logR = log(P_R1 / P_R0);

    for (int rs = 0;; rs++) {
        if (atomic_load(&FOUND) || now_s() > TIME_LIMIT) break;
        /* initialisation */
        int from_lb = 0;
        if (rs > 0 && rng_d(&rng) < P_PLB) {
            int cnt = 0; for (int i = 0; i < P_TOPK; i++) cnt += lb[i].used;
            if (cnt > 0) {
                int pick = (int)(rng_d(&rng) * cnt), j = 0;
                for (int i = 0; i < P_TOPK; i++) if (lb[i].used) { if (j == pick) { pick = i; break; } j++; }
                for (int o = 0; o < T_ORB; o++) {
                    double an = 2 * M_PI * rng_d(&rng), rad = P_PERT * sqrt(rng_d(&rng));
                    s->qx[o] = lb[pick].qx[o] + rad * cos(an);
                    s->qy[o] = lb[pick].qy[o] + rad * sin(an);
                }
                state_eval(s);
                from_lb = 1;
            }
        }
        if (!from_lb) state_random(s, &rng);
        double Tstart = from_lb ? P_T0 * 0.3 : P_T0, Rstart = from_lb ? P_R0 * 0.3 : P_R0;
        long steps = P_STEPS;
        int restart_best = s->E;
        for (long st = 0; st < steps; st++) {
            if ((st & 4095) == 0) {
                if (atomic_load(&FOUND) || now_s() > TIME_LIMIT) { steps = st; break; }
            }
            double frac = (double)st / (double)steps;
            double Temp = Tstart * exp(logT * frac), rad = Rstart * exp(logR * frac);
            /* pick an orbit proportional to its violations */
            double wsum = 0, w[MAXN];
            for (int o = 0; o < T_ORB; o++) {
                double wo = P_EPS;
                for (int r = 0; r < M; r++) wo += s->viol[o * M + r];
                w[o] = wo; wsum += wo;
            }
            double u = rng_d(&rng) * wsum; int o = 0;
            while (o < T_ORB - 1 && u >= w[o]) { u -= w[o]; o++; }
            /* propose */
            double nqx, nqy;
            if (rng_d(&rng) < P_PJUMP) {
                double rr = sqrt(rng_d(&rng)), an = 2 * M_PI * rng_d(&rng);
                nqx = rr * cos(an); nqy = rr * sin(an);
            } else {
                double rr = rad * sqrt(rng_d(&rng)), an = 2 * M_PI * rng_d(&rng);
                nqx = s->qx[o] + rr * cos(an); nqy = s->qy[o] + rr * sin(an);
                double nr = nqx * nqx + nqy * nqy;
                if (nr > 1.0) { nr = sqrt(nr); nqx /= nr; nqy /= nr; }
            }
            memcpy(tx, s->x, sizeof(double) * N); memcpy(ty, s->y, sizeof(double) * N);
            {
                double px[64], py[64];
                orbit_coords(o, nqx, nqy, px, py);
                for (int r = 0; r < M; r++) { tx[o * M + r] = px[r]; ty[o * M + r] = py[r]; }
            }
            int dE = 0;
            const int *aff = AFF[o]; int naff = NAFF[o];
            for (int i = 0; i < naff; i++) {
                int t = aff[i];
                int a = TRI_A[t], b = TRI_B[t], c = TRI_C[t];
                int v = tri_sign(tx, ty, a, b, c) != CHI[a][b][c];
                newstat[t] = (unsigned char)v;
                dE += v - s->status[t];
            }
            int accept = dE <= 0 || rng_d(&rng) < exp(-(double)dE / Temp);
            if (accept) {
                s->qx[o] = nqx; s->qy[o] = nqy;
                for (int r = 0; r < M; r++) { s->x[o * M + r] = tx[o * M + r]; s->y[o * M + r] = ty[o * M + r]; }
                for (int i = 0; i < naff; i++) {
                    int t = aff[i];
                    int d = (int)newstat[t] - (int)s->status[t];
                    if (d) {
                        s->status[t] = newstat[t];
                        s->viol[TRI_A[t]] += d; s->viol[TRI_B[t]] += d; s->viol[TRI_C[t]] += d;
                    }
                }
                s->E += dE;
                if (s->E < restart_best) restart_best = s->E;
                if (s->E < bestE) {
                    bestE = s->E;
                    int gb = atomic_load(&GLOBAL_BEST);
                    if (bestE < gb) {
                        pthread_mutex_lock(&IO_LOCK);
                        if (bestE < atomic_load(&GLOBAL_BEST)) {
                            atomic_store(&GLOBAL_BEST, bestE);
                            memcpy(BEST_QX, s->qx, sizeof(double) * T_ORB); memcpy(BEST_QY, s->qy, sizeof(double) * T_ORB);
                            if (P_VERBOSE) { printf("  t=%.1fs thread %d restart %d step %ld: best E=%d\n", now_s(), arg->id, rs, st, bestE); fflush(stdout); }
                        }
                        pthread_mutex_unlock(&IO_LOCK);
                    }
                }
                if (s->E == 0) {
                    /* exact rounding */
                    int ok = 0;
                    for (int sc = 20; sc <= 56 && !ok; sc += 4) ok = try_round(s->qx, s->qy, sc, X, Y);
                    if (ok) {
                        pthread_mutex_lock(&IO_LOCK);
                        if (!atomic_load(&FOUND)) {
                            atomic_store(&FOUND, 1);
                            FILE *f = fopen(OUT_PATH, "w");
                            if (f) { for (int i = 0; i < N; i++) fprintf(f, "%lld %lld\n", X[i], Y[i]); fclose(f); }
                            printf("REALIZED thread=%d restart=%d step=%ld time=%.2fs; exact integer check passed (all %d triples)\n", arg->id, rs, st, now_s(), NTRI);
                            fflush(stdout);
                        }
                        pthread_mutex_unlock(&IO_LOCK);
                        steps = st; break;
                    } else if (P_VERBOSE) {
                        printf("  float energy 0 but no integer rounding scale worked (thread %d); continuing\n", arg->id);
                    }
                }
            }
        }
        arg->steps_done += steps;
        arg->restarts++;
        /* leaderboard insert (replace worst if better) */
        {
            int worst = 0;
            for (int i = 1; i < P_TOPK; i++) if (!lb[i].used || (lb[worst].used && lb[i].E > lb[worst].E)) worst = i;
            if (!lb[worst].used || s->E < lb[worst].E) {
                lb[worst].used = 1; lb[worst].E = s->E;
                memcpy(lb[worst].qx, s->qx, sizeof(double) * T_ORB); memcpy(lb[worst].qy, s->qy, sizeof(double) * T_ORB);
            }
        }
        if (P_VERBOSE > 1) { printf("  thread %d restart %d (%s): end E=%d restart-best=%d\n", arg->id, rs, from_lb ? "lb" : "rand", s->E, restart_best); fflush(stdout); }
    }
    arg->bestE = bestE;
    free(s->status); free(s); free(newstat); free(lb); free(X); free(Y);
    return NULL;
}

int main(int argc, char **argv) {
    if (argc < 9) { fprintf(stderr, "usage: localizer N m has_center file.sig seed threads time_limit_s out.pts [key=value ...]\n"); return 2; }
    N = atoi(argv[1]); M = atoi(argv[2]); HASC = atoi(argv[3]);
    const char *sigpath = argv[4];
    unsigned long long seed = strtoull(argv[5], 0, 10);
    int nthreads = atoi(argv[6]);
    TIME_LIMIT = atof(argv[7]);
    OUT_PATH = argv[8];
    for (int i = 9; i < argc; i++) {
        char key[64]; double val;
        if (sscanf(argv[i], "%63[^=]=%lf", key, &val) != 2) { fprintf(stderr, "bad option %s\n", argv[i]); return 2; }
        if (!strcmp(key, "steps")) P_STEPS = (long)val;
        else if (!strcmp(key, "T0")) P_T0 = val; else if (!strcmp(key, "T1")) P_T1 = val;
        else if (!strcmp(key, "r0")) P_R0 = val; else if (!strcmp(key, "r1")) P_R1 = val;
        else if (!strcmp(key, "pjump")) P_PJUMP = val; else if (!strcmp(key, "topk")) P_TOPK = (int)val;
        else if (!strcmp(key, "plb")) P_PLB = val; else if (!strcmp(key, "pert")) P_PERT = val;
        else if (!strcmp(key, "eps")) P_EPS = val; else if (!strcmp(key, "verbose")) P_VERBOSE = (int)val;
        else { fprintf(stderr, "unknown option %s\n", key); return 2; }
    }
    if (N > MAXN || M < 1 || M > 64 || (N - HASC) % M != 0) { fprintf(stderr, "bad N/m/has_center\n"); return 2; }
    T_ORB = (N - HASC) / M;
    for (int r = 0; r < M; r++) {
        CR[r] = cos(2 * M_PI * r / M); SR[r] = sin(2 * M_PI * r / M);
        if (M == 2) { CR[r] = r ? -1 : 1; SR[r] = 0; }
        if (M == 4) { static const double c4[4] = {1, 0, -1, 0}, s4[4] = {0, 1, 0, -1}; CR[r] = c4[r]; SR[r] = s4[r]; }
    }
    /* read chirotope */
    NTRI = N * (N - 1) * (N - 2) / 6;
    TRI_A = malloc(sizeof(int) * NTRI); TRI_B = malloc(sizeof(int) * NTRI); TRI_C = malloc(sizeof(int) * NTRI);
    TID = malloc(sizeof(*TID) * MAXN);
    {
        int t = 0;
        for (int a = 0; a < N; a++) for (int b = a + 1; b < N; b++) for (int c = b + 1; c < N; c++) {
            TRI_A[t] = a; TRI_B[t] = b; TRI_C[t] = c; TID[a][b][c] = t; t++;
        }
    }
    memset(CHI, 0, sizeof(CHI));
    {
        FILE *f = fopen(sigpath, "r");
        if (!f) { fprintf(stderr, "cannot open %s\n", sigpath); return 2; }
        int a, b, c, s, cnt = 0;
        while (fscanf(f, "%d %d %d %d", &a, &b, &c, &s) == 4) {
            if (!(0 <= a && a < b && b < c && c < N) || (s != 1 && s != -1)) { fprintf(stderr, "bad sig line %d %d %d %d\n", a, b, c, s); return 2; }
            CHI[a][b][c] = s; CHI[b][c][a] = s; CHI[c][a][b] = s;
            CHI[b][a][c] = -s; CHI[a][c][b] = -s; CHI[c][b][a] = -s;
            cnt++;
        }
        fclose(f);
        if (cnt != NTRI) { fprintf(stderr, "expected %d triples, read %d\n", NTRI, cnt); return 2; }
    }
    /* affected triples per orbit */
    AFF = malloc(sizeof(int *) * T_ORB); NAFF = calloc(T_ORB, sizeof(int));
    for (int o = 0; o < T_ORB; o++) {
        AFF[o] = malloc(sizeof(int) * NTRI);
        for (int t = 0; t < NTRI; t++) {
            int a = TRI_A[t], b = TRI_B[t], c = TRI_C[t];
            int hit = (a / M == o && a < N - HASC) || (b / M == o && b < N - HASC) || (c / M == o && c < N - HASC);
            if (hit) AFF[o][NAFF[o]++] = t;
        }
    }
    clock_gettime(CLOCK_MONOTONIC, &T_START);
    pthread_t *th = malloc(sizeof(pthread_t) * nthreads);
    thread_arg_t *args = calloc(nthreads, sizeof(thread_arg_t));
    for (int i = 0; i < nthreads; i++) {
        args[i].id = i; args[i].seed = seed + 1000003ULL * i; args[i].bestE = 1 << 30;
        pthread_create(&th[i], NULL, worker, &args[i]);
    }
    long total_steps = 0; int total_restarts = 0, bestE = 1 << 30;
    for (int i = 0; i < nthreads; i++) {
        pthread_join(th[i], NULL);
        total_steps += args[i].steps_done; total_restarts += args[i].restarts;
        if (args[i].bestE < bestE) bestE = args[i].bestE;
    }
    double el = now_s();
    if (atomic_load(&FOUND)) {
        printf("SUMMARY REALIZED time=%.2fs steps=%ld restarts=%d threads=%d\n", el, total_steps, total_restarts, nthreads);
        return 0;
    }
    /* dump best float configuration (scaled) for inspection */
    {
        char path[4096]; snprintf(path, sizeof(path), "%s.best", OUT_PATH);
        FILE *f = fopen(path, "w");
        if (f) {
            fprintf(f, "# best energy %d of %d triples\n", bestE, NTRI);
            for (int o = 0; o < T_ORB; o++) fprintf(f, "%.12f %.12f\n", BEST_QX[o], BEST_QY[o]);
            fclose(f);
        }
    }
    printf("NOT REALIZED: best violated-triple count %d of %d (time=%.2fs steps=%ld restarts=%d threads=%d)\n", bestE, NTRI, el, total_steps, total_restarts, nthreads);
    return 1;
}
