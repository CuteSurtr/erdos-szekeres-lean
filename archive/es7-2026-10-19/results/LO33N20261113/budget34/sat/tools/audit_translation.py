#!/usr/bin/env python3
"""Independent streamed CNF audit by local truth tables, no encoder import.

Rebuilds the counter index layout from raw supports. Actual clause groups are
checked against their Boolean truth table, rather than regenerated by the
emitter's clause-building code. No finder or row-clauses metadata is trusted.
"""
import argparse
import gzip
import hashlib
import itertools
import json
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument('directory')
a = ap.parse_args()
p = Path(a.directory)
meta = json.loads((p/'encoding.json').read_text())
with gzip.open(meta['base'], 'rt') as f:
    source = json.load(f)
pool = json.loads(Path(meta['pool']).read_text())
states = source['states']
F = [i for i in range(154) if states[i][0] > 4]
Lo = [i for i in range(154) if states[i][0] < 5]
t = meta['slice']
rows = source['constraints'] + pool + [
    {'support': F, 'rhs': t if t else 19},
    {'support': Lo, 'rhs': 34-t if t else 14}]
mode = meta.get('counter_mode', 'exact')
handle = (p/'system.cnf').open()
tag, cnf, variables, clauses = handle.readline().split()
assert (tag, cnf) == ('p', 'cnf')
variables, clauses = int(variables), int(clauses)
seen, literals, lastvar, gates, cases = 0, 0, 154, 0, 0


def read_clause():
    global seen, literals
    line = handle.readline()
    assert line, ('early EOF', seen)
    vals = list(map(int, line.split()))
    assert vals[-1] == 0 and 0 not in vals[:-1]
    vals.pop()
    assert len(vals) == len(set(vals)) and all(abs(v) <= variables for v in vals)
    seen += 1
    literals += len(vals)
    return set(vals)


def counter(support, threshold, direction):
    global lastvar, gates, cases
    previous = {0: True}
    for i, basevar in enumerate(support, 1):
        current = {0: True}
        for j in range(1, min(i, threshold)+1):
            aa, bb = previous.get(j, False), previous.get(j-1, False)
            assert bb is not False
            lastvar += 1
            yy = lastvar
            current[j] = yy
            # The number of non-tautological gate clauses follows solely
            # from whether the two boundary counter inputs are constants.
            number = (int(aa is not False)+1 if direction == 'forward' else
                      1+int(bb is not True) if direction == 'backward' else
                      2+int(aa is not False)+int(bb is not True))
            group = [read_clause() for _ in range(number)]
            names = [v for v in (aa, basevar, bb, yy) if type(v) is int]
            assert len(names) == len(set(names))
            assert set().union(*(set(abs(v) for v in row) for row in group)) == set(names)
            for bits in itertools.product((False, True), repeat=len(names)):
                values = dict(zip(names, bits))
                aval = aa if type(aa) is bool else values[aa]
                bval = bb if type(bb) is bool else values[bb]
                xval, yval = values[basevar], values[yy]
                rhs = aval or (xval and bval)
                actual = all(any(values[abs(v)] == (v > 0) for v in row) for row in group)
                expected = (not rhs or yval) if direction == 'forward' else (
                    (not yval or rhs) if direction == 'backward' else yval == rhs)
                assert actual == expected, (seen, i, j, direction, values, group)
                cases += 1
            gates += 1
        previous = current
    return previous[threshold]


assert read_clause() == {-1}
for row in rows:
    inputs = [v+1 for v in row['support']]
    assert len(inputs) == len(set(inputs))
    if row['rhs'] == 1:
        assert read_clause() == set(inputs)
    else:
        end = counter(inputs, row['rhs'], 'backward' if mode == 'implication' else 'exact')
        assert read_clause() == {end}
end = counter(list(range(1, 155)), 35, 'forward' if mode == 'implication' else 'exact')
assert read_clause() == {-end}
assert handle.read() == ''
assert lastvar == variables and seen == clauses and literals == meta['literals']
result = {'label': 'COMPUTED independent complete CNF translation audit', 'result': 'PASS',
          'cnf_sha256': hashlib.sha256((p/'system.cnf').read_bytes()).hexdigest(),
          'variables': variables, 'clauses': clauses, 'literals': literals,
          'counter_gates': gates, 'local_truth_assignments_checked': cases,
          'row_constraints_checked': len(rows), 'h0_unit_checked': True,
          'budget34_checked': True, 'mode': mode}
(p/'translation-audit.json').write_text(json.dumps(result, indent=2)+'\n')
print(json.dumps(result, indent=2))
