#!/usr/bin/env python3
"""Write LeanLB/Check/<Name>.lean for the six k = 7 sets (standard library only). A copy of LEANLB20261111's
gen_checks.py with three changes: the chain bound is B = 5 (at most 6 points in convex position, so no convex
7-gon; the k = 8 package used 6), the modules import LeanLB.Geometry7 (the new row symmetries mulZeta3,
rot90XY, G.mulZ5), and the 5-fold closure uses G.mulZ5 (rows c0..c3 in the basis 1, z, z^2, z^3) instead of
cycShift 5. The anchor ranges only affect resource use (checkFrom_trans / checkAll_of_checkFrom recombine them)."""
import os, re, sys
from math import comb
HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
B = 5
SETS = [("C3N31", "lat3", "mulOmega"), ("C6N30", "lat3", "mulZeta3"), ("C4N28", "latXY", "rot90XY"),
        ("C2N32", "latXY", "negXY"), ("MirN32", "latXY", "reflXY")]
FIELD_SETS = [("C5N31", "lat5", "mulZ5", "Five", "lo5", "D5")]
BUDGET = int(os.environ.get("LB_BUDGET", "40000"))
TILT = 1

def nat_data(name):
    txt = open(os.path.join(PKG, "LeanLB", "Data", name + ".lean")).read()
    body = txt.split("Nat : List NP := [", 1)[1].split("]", 1)[0]
    return [(int(a), int(b)) for a, b in re.findall(r"\((\d+), (\d+)\)", body)]

def split(cost):
    out, a, acc = [], 0, 0
    for i, c in enumerate(cost):
        if acc and acc + c > BUDGET:
            out.append((a, i)); a, acc = i, 0
        acc += c
    out.append((a, len(cost)))
    return out

def ranges(N):
    cost = []
    for p in N:
        m = sum(1 for q in N if (q[1], q[0]) > (p[1], p[0]))
        cost.append(comb(m, 3) + m * m)
    return split(cost)

def chain(lo, rg, pre=""):
    term = f"{pre}{lo}_dp_0"
    for k in range(1, len(rg)):
        a, b = rg[k]
        term = f"(checkFrom_trans (by decide : 0 ≤ {a}) (by decide : {a} ≤ {b})\n      {term} {pre}{lo}_dp_{k})"
    return term

def render(name, lat, R):
    lo = name[0].lower() + name[1:]
    N = nat_data(name); n = len(N); rg = ranges(N)
    L = [f"import LeanLB.Geometry7\nimport LeanLB.Data.{name}\n\n",
         f"/-! Kernel evaluations for `{lo}` (`decide +kernel`; no `native_decide`). Generated by\n",
         f"`scripts/gen_checks7.py` (budget {BUDGET}); the anchor loop is split into {len(rg)} ranges. -/\n\n",
         "namespace LeanLB\n\nset_option maxRecDepth 100000\n\n",
         f"/-- {n} points. -/\ntheorem {lo}_len : {lo}Nat.length = {n} := by decide +kernel\n\n",
         "/-- Distinct points, no three collinear (lattice coordinates). -/\n",
         f"theorem {lo}_gp : gpOK {lo}Nat = true := by decide +kernel\n\n"]
    for k, (a, b) in enumerate(rg):
        L.append(f"theorem {lo}_dp_{k} : checkFrom {B} {lo}Nat {a} {b} = true := by decide +kernel\n")
    L += [f"\n/-- No anchor starts a chain of {B + 1} left turns: no {B + 2} points in convex position. -/\n",
          f"theorem {lo}_dp : checkAll {B} {lo}Nat = true := by\n  apply checkAll_of_checkFrom\n",
          f"  rw [{lo}_len]\n  exact {chain(lo, rg)}\n\n",
          "/-- The checker's coordinates are the lattice coordinates of the rows, translated. -/\n",
          f"theorem {lo}_link : {lo}Rows.map {lat} = {lo}Nat.map (unshift {lo}Shift) := by decide +kernel\n\n",
          "/-- The rows are closed under the symmetry. -/\n",
          f"theorem {lo}_closed : ∀ w ∈ {lo}Rows, {R} w ∈ {lo}Rows := by decide +kernel\n\nend LeanLB\n"]
    return "".join(L), rg

def field_data(name):
    txt = open(os.path.join(PKG, "LeanLB", "Data", name + ".lean")).read()
    body = txt.split("(Nat × Nat)) := [", 1)[1]
    return [(int(a), int(b)) for a, b in re.findall(r"\), \((\d+), (\d+)\)\)", body)]

def field_ranges(N):
    key = lambda p: p[1] + TILT * p[0]
    cost = []
    for p in N:
        m = sum(1 for q in N if key(q) > key(p) + 2 + 2 * TILT)
        cost.append(comb(m, 3) + m * m)
    return split(cost)

def render_field(name, lat, R, mod, lo, D):
    lo_ = name[0].lower() + name[1:]
    N = field_data(name); n = len(N); rg = field_ranges(N)
    op = f"(opA (8 * {lo_}Mx + 8))"
    ab = f"(abA {TILT} (2 + 2 * {TILT}))"
    L = [f"import LeanLB.Geometry7\nimport LeanLB.Data.{name}\n\n",
         f"/-! Kernel evaluations for `{lo_}` (`decide +kernel`; no `native_decide`). Generated by\n",
         f"`scripts/gen_checks7.py` (budget {BUDGET}); the anchor loop is split into {len(rg)} ranges. -/\n\n",
         "namespace LeanLB.G\n\nset_option maxRecDepth 100000\n\n",
         f"/-- {n} points. -/\ntheorem {lo_}_len : {lo_}L.length = {n} := by decide +kernel\n\n",
         "/-- The approximations are certified. -/\n",
         f"theorem {lo_}_cert : {lo_}L.all (certOK {lo} {D} {lo_}Sc {lo_}Shift.1 {lo_}Shift.2 {lo_}Mx) = true := by\n  decide +kernel\n\n",
         "/-- Every pair ordered, every triple decided. -/\n",
         f"theorem {lo_}_gp : gpOK {op} {ab} {lo_}L = true := by decide +kernel\n\n"]
    for k, (a, b) in enumerate(rg):
        L.append(f"theorem {lo_}_dp_{k} : checkFrom {op} {ab} {B} {lo_}L {a} {b} = true := by\n  decide +kernel\n")
    L += [f"\n/-- No anchor starts a chain of {B + 1} left turns. -/\n",
          f"theorem {lo_}_dp : checkAll {op} {ab} {B} {lo_}L = true := by\n  apply checkAll_of_checkFrom\n",
          f"  rw [{lo_}_len]\n  exact {chain(lo_, rg)}\n\n",
          "/-- The exact coordinates are those of the rows. -/\n",
          f"theorem {lo_}_link : {lo_}L.map Prod.fst = {lo_}Rows.map {lat} := by decide +kernel\n\n",
          "/-- The rows are closed under the rotation (multiplication by z, reduced to the basis 1, z, z², z³). -/\n",
          f"theorem {lo_}_closed : ∀ w ∈ {lo_}Rows, {R} w ∈ {lo_}Rows := by decide +kernel\n\nend LeanLB.G\n"]
    return "".join(L), rg

if __name__ == "__main__":
    for name, lat, R in SETS:
        text, rg = render(name, lat, R)
        open(os.path.join(PKG, "LeanLB", "Check", name + ".lean"), "w").write(text)
        print(name, len(rg), "ranges", rg)
    for name, lat, R, mod, lo, D in FIELD_SETS:
        text, rg = render_field(name, lat, R, mod, lo, D)
        open(os.path.join(PKG, "LeanLB", "Check", name + ".lean"), "w").write(text)
        print(name, len(rg), "ranges", rg)
