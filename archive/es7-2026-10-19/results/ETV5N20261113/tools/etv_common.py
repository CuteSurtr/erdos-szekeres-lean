"""ETV internal-state catalog (13 Nov 2026, discovery tooling).

Setting (A, B): planar point sets, distinct x, general position, every cap has at most A+1 points,
every cup at most B+1 points, no convex octagon.  Pair label d(u,v) = (E_-(u,v)-1, E_+(u,v)-1) in
[1..A] x [1..B].  Incoming state I(v) = down-set generated by incoming labels; profiles are
nonincreasing column heights f_1 >= ... >= f_A (column a = cap coordinate a), f_a <= B.
  a=5, n=8 case : A=3, B=6  (84 states)
  balanced half : A=4, B=5  (no 6-cap, no 7-cup; 126 states)
Env ETV_A / ETV_B select the case (default 3, 6).

Domains (directed):  D(s->t) = I(t) \\ I(s)                               (state separation)
Refined domains:     D'(s->t) = {(a,b) in D(s->t): a <= capH(s)+1, b <= cupH(s)+1}
  capH(s) = number of nonempty columns of s (max cap coordinate in I(s)), cupH(s) = f_1(s).
  (rank attainment: the prefix of an attaining cap/cup ending with (u,v) ends with some (t,u).)
TT[a,b,c] (plain) / TTR (refined): six-order bounding-box test with the respective domains.
"""
import itertools, os
import numpy as np

A = int(os.environ.get('ETV_A', '3'))
B = int(os.environ.get('ETV_B', '6'))

def profiles():
    out = [f for f in itertools.product(range(B + 1), repeat=A)
           if all(f[i] >= f[i + 1] for i in range(A - 1))]
    out.sort(key=lambda f: (sum(f), f))
    return out

STATES = profiles()
N = len(STATES)
SINDEX = {s: i for i, s in enumerate(STATES)}
CELLS = [frozenset((a + 1, y) for a in range(A) for y in range(1, f[a] + 1)) for f in STATES]
CAPH = [sum(1 for x in f if x > 0) for f in STATES]
CUPH = [f[0] for f in STATES]

def dom_plain(s, t):
    return CELLS[t] - CELLS[s]

def dom_ref(s, t):
    return frozenset(z for z in CELLS[t] - CELLS[s] if z[0] <= CAPH[s] + 1 and z[1] <= CUPH[s] + 1)

DPLAIN = [[dom_plain(s, t) for t in range(N)] for s in range(N)]
DREF = [[dom_ref(s, t) for t in range(N)] for s in range(N)]

def triple_table(D):
    nonempty = np.zeros((N, N), bool)
    mn = np.zeros((2, N, N), np.int16); mx = np.zeros((2, N, N), np.int16)
    for s in range(N):
        for t in range(N):
            d = D[s][t]
            if d:
                nonempty[s, t] = True
                mn[0, s, t] = min(z[0] for z in d); mx[0, s, t] = max(z[0] for z in d)
                mn[1, s, t] = min(z[1] for z in d); mx[1, s, t] = max(z[1] for z in d)
    idx = np.arange(N, dtype=np.int16)
    A_, B_, C_ = np.meshgrid(idx, idx, idx, indexing='ij')
    TT = (A_ != B_) & (B_ != C_) & (A_ != C_)
    grids = (A_, B_, C_)
    for perm in itertools.permutations(range(3)):
        odd = sum(perm[i] > perm[j] for i in range(3) for j in range(i + 1, 3)) % 2
        coord = 1 if odd else 0
        p, q, r = (grids[perm[k]] for k in range(3))
        present = nonempty[p, q] & nonempty[q, r] & nonempty[p, r]
        forced = mx[coord][q, r] <= mn[coord][p, q]
        TT &= (~present) | forced
    return TT

_cache = os.path.join(os.path.dirname(os.path.abspath(__file__)), f'tt_A{A}_B{B}.npz')
if os.path.exists(_cache):
    _z = np.load(_cache); TT = _z['TT']; TTR = _z['TTR']
else:
    TT = triple_table(DPLAIN); TTR = triple_table(DREF)
    np.savez_compressed(_cache + '.tmp.npz', TT=TT, TTR=TTR); os.replace(_cache + '.tmp.npz', _cache)

FIXED_OCC = [SINDEX[tuple([0] * A)], SINDEX[tuple([1] + [0] * (A - 1))]]  # first two points

def check(holes, rows):
    H = set(holes)
    return [k for k, (s, d) in enumerate(rows) if len(H.intersection(s)) < d]
