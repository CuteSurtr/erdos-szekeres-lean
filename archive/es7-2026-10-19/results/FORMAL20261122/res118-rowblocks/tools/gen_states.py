#!/usr/bin/env python3
"""Write lean/RowEnc/StatesData.lean: the 154 residual states of source-2650.json (field `states`), in file order.
Read-only on its input; asserts the raw sha256 recorded by common.py and Res118 (e800d5f8...)."""
import gzip, hashlib, json, sys
SRC = '/home/jay/research/data/es308-20261114/inputs/source-2650.json.gz'
RAW = 'e800d5f8a6c5cc45c73ddcc1e57488f2ca8f2ffb704a1515ff7444d589c682f6'
raw = gzip.decompress(open(SRC, 'rb').read())
assert hashlib.sha256(raw).hexdigest() == RAW
st = json.loads(raw)['states']
assert len(st) == 154 and all(len(s) == 5 and s[4] == 0 and max(s) <= 6 for s in st)
body = ','.join('[' + ','.join(map(str, s)) + ']' for s in st)
out = f'''/-
res118-rowblocks (22 Nov 2026), GENERATED by tools/gen_states.py; do not edit by hand.
The 154 residual states (`states` of source-2650.json, raw sha256 {RAW}), in file order:
column heights h1..h4 of the Ferrers shape, then 0. `RowGeo` proves this list equal to `ResidualCatalog.catalog`.
-/
namespace RowEnc

def stateTable : List (List Nat) := [{body}]

end RowEnc
'''
open(sys.argv[1], 'w').write(out)
print('ok', len(st))
