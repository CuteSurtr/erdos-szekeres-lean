"""Generate the packed tables of V182Geo/SixData.lean from the six-colour list (untrusted helper: Lean checks the
colouring itself). Input: wave 1's decoding of the notes' table, a-t34-sat182/verify/a2/col6_mine.json
(sha256 22cee12c...1578), plus an own decoding of notes_src/diamond-colors.txt for comparison.
Also simulates walkOK (the Lean kernel check) in Python. usage: python3 -I gen_six.py OUT.lean"""
import json, sys, hashlib
SRC = '/home/jay/research/data/e810-linux-20261121/a-t34-sat182/verify/a2/col6_mine.json'
NOTES = '/home/jay/research/data/e810-linux-20261121/a-t34-sat182/notes_src/diamond-colors.txt'
pc = lambda m: bin(m).count('1')
four = [m for m in range(256) if pc(m) == 4]
col = json.load(open(SRC))['col6']
assert len(col) == 560 and set(col) == set(range(6))
# own decoding of the notes' table (format as in rainbow.py notes182: per 3-set: mask, 5 lower colours, 5 upper)
tok = open(NOTES).read().split()
assert len(tok) == 168
mine = [None] * 560
eid = lambda T, x: 8 * four.index(T) + x
for p in range(56):
    tri, lo, up = int(tok[3 * p]), tok[3 * p + 1], tok[3 * p + 2]
    assert pc(tri) == 3
    outside = [x for x in range(8) if not tri >> x & 1]
    for pos, x in enumerate(outside):
        a = tri | (1 << x)
        mine[eid(a, x)] = int(lo[pos])                       # edge tri - (tri+x)
        mine[eid(255 ^ tri ^ (1 << x), x)] = int(up[pos])    # edge comp(tri+x) - comp(tri)
assert None not in mine
same = mine == col
# packed tables
BIG = 0
for e, c in enumerate(col):
    T, x = four[e // 8], e % 8
    BIG |= c << (3 * (8 * T + x))
POP = sum(pc(m) << (4 * m) for m in range(256))
VT = sum(1 << m for m in range(256) if 3 <= pc(m) <= 5)
def popT(m): return (POP >> (4 * m)) % 16
def isV(m): return (VT >> m) % 2 == 1
def col6At(m, mp):
    hi, lo = m | mp, m & mp
    T = hi if popT(hi) == 4 else lo
    return ((BIG >> (3 * (8 * T + popT((m ^ mp) - 1)))) % 8) % 6
def onebit(z): return z != 0 and (z & (z - 1)) == 0
bad = cnt = 0
for a in range(256):
    if not isV(a): continue
    for i in range(8):
        for j in range(8):
            for k in range(8):
                b = a ^ (1 << i); c = b ^ (1 << j); d = c ^ (1 << k)
                if isV(b) and isV(c) and isV(d) and a != c and b != d and onebit(d ^ a):
                    cnt += 1
                    cs = [col6At(a, b), col6At(b, c), col6At(c, d), col6At(d, a)]
                    if len(set(cs)) != 4: bad += 1
print(json.dumps({'col6_sha256': hashlib.sha256(open(SRC, 'rb').read()).hexdigest(), 'own_notes_decoding_equal': same,
                  'walks': cnt, 'bad': bad}))
with open(sys.argv[1], 'w') as f:
    f.write('/-! # V182Geo.SixData: packed tables for the six-colouring (generated by tools/gen_six.py; data only,\n'
            'checked by the kernel in V182Geo.Six). -/\n\nnamespace V182Geo\n\n')
    f.write('/-- The six-colour table: colour of the edge (4-set mask `T`, bit `x`) in bits `3 (8 T + x)`. -/\n')
    f.write(f'def col6Big : Nat := {BIG}\n\n')
    f.write('/-- Bit counts of the masks `0..255`, 4 bits each. -/\n')
    f.write(f'def popBig : Nat := {POP}\n\n')
    f.write('/-- Bit `m` is set iff `m` has 3, 4 or 5 bits. -/\n')
    f.write(f'def vtxBig : Nat := {VT}\n\nend V182Geo\n')
