"""Generate the Std-only walk-check modules of the six-colouring (untrusted helper; the kernel checks the output):
  lean/V182Chk/WalkDefs.lean  definitions (popT, isV, col6At, onebit, rainbow4, walkBody) and onebit_shl;
  lean/V182Chk/WalkA.lean, WalkB.lean  the kernel chunks walk_c<t> (each its own declaration);
  lean/V182Chk/Walk.lean  walk_all (all start masks a < 256) and walk_spec.
Chunks are ranges of start masks with at most PER vertex masks each; two chunk modules keep each compile's memory
low.  usage: python3 -I gen_walk.py PER"""
import sys
per = int(sys.argv[1])
pc = lambda m: bin(m).count('1')
bounds, cnt = [0], 0
for m in range(256):
    if 3 <= pc(m) <= 5:
        cnt += 1
        if cnt == per:
            bounds.append(m + 1)
            cnt = 0
if bounds[-1] != 256:
    bounds.append(256)
chunks = list(zip(bounds[:-1], bounds[1:]))
half = (len(chunks) + 1) // 2

DEFS = f'''import V182Geo.SixData

/-!
# V182Chk.WalkDefs: definitions of the walk check for the six-colouring (Std-only; generated by tools/gen_walk.py)

`walkBody a`: every closed bit-toggle walk `a, a⊕2^i, a⊕2^i⊕2^j, a⊕2^i⊕2^j⊕2^k` through vertex masks that is a
4-cycle (`a ≠ third`, `second ≠ fourth`, `fourth ⊕ a` one bit) gets four distinct colours `col6At`. Checked by
`decide +kernel` in {len(chunks)} chunks (`V182Chk.WalkA`, `V182Chk.WalkB`; at most {per} vertex masks each).
-/

namespace V182Geo

/-- Bit count of a mask `< 256` (packed table). -/
def popT (m : Nat) : Nat := (popBig >>> (4 * m)) % 16

/-- `m` is a vertex mask (3, 4 or 5 bits; packed table). -/
def isV (m : Nat) : Bool := (vtxBig >>> m) % 2 == 1

/-- The colour of the pair of masks `(m, m')`: the table entry at the 4-set end and the differing bit. -/
def col6At (m m' : Nat) : Nat :=
  ((col6Big >>> (3 * (8 * (if popT (m ||| m') = 4 then m ||| m' else m &&& m') + popT ((m ^^^ m') - 1)))) % 8) % 6

/-- `z` is a single bit. -/
def onebit (z : Nat) : Bool := z != 0 && (z &&& (z - 1)) == 0

/-- The four colours of the closed walk `a b c d` are distinct. -/
def rainbow4 (a b c d : Nat) : Bool := decide ([col6At a b, col6At b c, col6At c d, col6At d a].Nodup)

/-- The walk check at the start mask `a`. -/
def walkBody (a : Nat) : Bool :=
  !isV a || (List.range 8).all fun i => (List.range 8).all fun j => (List.range 8).all fun k =>
    !(isV (a ^^^ 1 <<< i) && isV (a ^^^ 1 <<< i ^^^ 1 <<< j) && isV (a ^^^ 1 <<< i ^^^ 1 <<< j ^^^ 1 <<< k) &&
        (a != a ^^^ 1 <<< i ^^^ 1 <<< j) && (a ^^^ 1 <<< i != a ^^^ 1 <<< i ^^^ 1 <<< j ^^^ 1 <<< k) &&
        onebit (a ^^^ 1 <<< i ^^^ 1 <<< j ^^^ 1 <<< k ^^^ a)) ||
      rainbow4 a (a ^^^ 1 <<< i) (a ^^^ 1 <<< i ^^^ 1 <<< j) (a ^^^ 1 <<< i ^^^ 1 <<< j ^^^ 1 <<< k)

theorem onebit_shl : ∀ l, l < 8 → onebit (1 <<< l) = true := by decide +kernel

end V182Geo
'''
open('lean/V182Chk/WalkDefs.lean', 'w').write(DEFS)

for name, part in (('WalkA', list(enumerate(chunks))[:half]), ('WalkB', list(enumerate(chunks))[half:])):
    M = ['import V182Chk.WalkDefs', '',
         f'/-! # V182Chk.{name}: kernel chunks of the walk check (generated by tools/gen_walk.py) -/', '',
         'namespace V182Geo', '']
    for t, (lo, hi) in part:
        M.append(f'theorem walk_c{t} : ∀ a, a < {hi} → {lo} ≤ a → walkBody a = true := by decide +kernel')
        M.append('')
    M.append('end V182Geo')
    open(f'lean/V182Chk/{name}.lean', 'w').write('\n'.join(M) + '\n')

W = ['import V182Chk.WalkA', 'import V182Chk.WalkB', '',
     '/-! # V182Chk.Walk: the walk check for every start mask, and its use (generated by tools/gen_walk.py) -/', '',
     'namespace V182Geo', '',
     'theorem walk_all (a : Nat) (ha : a < 256) : walkBody a = true := by']
for t, (lo, hi) in enumerate(chunks):
    if t < len(chunks) - 1:
        W.append(f'  if h{t} : a < {hi} then exact walk_c{t} a h{t} (by omega) else')
    else:
        W.append(f'  exact walk_c{t} a ha (by omega)')
W.append('''
theorem walk_spec {a b c d i j k : Nat} (ha : a < 256) (hi : i < 8) (hj : j < 8) (hk : k < 8)
    (hb : b = a ^^^ 1 <<< i) (hc : c = b ^^^ 1 <<< j) (hd : d = c ^^^ 1 <<< k)
    (hva : isV a = true) (hvb : isV b = true) (hvc : isV c = true) (hvd : isV d = true)
    (hac : a ≠ c) (hbd : b ≠ d) (h1 : onebit (d ^^^ a) = true) : rainbow4 a b c d = true := by
  subst hb hc hd
  have hac' : (a != a ^^^ 1 <<< i ^^^ 1 <<< j) = true := bne_iff_ne.2 hac
  have hbd' : (a ^^^ 1 <<< i != a ^^^ 1 <<< i ^^^ 1 <<< j ^^^ 1 <<< k) = true := bne_iff_ne.2 hbd
  have h2 := walk_all a ha
  unfold walkBody at h2
  rw [hva, Bool.not_true, Bool.false_or, List.all_eq_true] at h2
  have h3 := h2 i (List.mem_range.2 hi)
  rw [List.all_eq_true] at h3
  have h4 := h3 j (List.mem_range.2 hj)
  rw [List.all_eq_true] at h4
  have h5 := h4 k (List.mem_range.2 hk)
  rw [hvb, hvc, hvd, hac', hbd', h1] at h5
  simpa using h5

end V182Geo''')
open('lean/V182Chk/Walk.lean', 'w').write('\n'.join(W) + '\n')
print(len(chunks), half, chunks)
