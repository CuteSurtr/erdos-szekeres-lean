"""Write the per-row certificate data RowChk/Rows<f>.lean (own code, untrusted: every row is checked by the kernel
with `chkRows`).  Rows in N66Enc.R0 order (rows_used.txt); certificates from data/just_R0.json (the first record
justification over the 132 leaves, tools/stats.py).  Template index = position in the sorted template ids, core
index = position in the sorted VB job keys (as tools/gen_data.py).  Chunks of 100 rows, 10 chunks per file.
Also writes RowChk/RowsAll.lean (R1nat, J as concatenations) and data/rows_manifest.tsv."""
import sys as _sys
if '--write' not in _sys.argv:
    raise SystemExit('refusing to overwrite generated Lean files without --write (DESIGN.md §7: recompile downstream)')

import json, hashlib
D = '/home/jay/research/data/formalize-20261122/n66-rowsvalid/'
src = json.load(open(D + 'data/just_R0.json'))
tids = sorted(src['templates'])
tix = {t: i for i, t in enumerate(tids)}
def job_key_core(c):
    T = sorted(c['support'])
    return 'C_' + hashlib.sha256(json.dumps([list(T), c.get('octs')]).encode()).hexdigest()[:16]
cores = sorted(src['cores'], key=job_key_core)
cix = {tuple(sorted(c['support'])): i for i, c in enumerate(cores)}
R0 = [tuple(map(int, l.split())) for l in open('/home/jay/research/data/formalize-20261122/n66enc/lean/N66Enc/data/rows_used.txt') if l.strip()]
assert [tuple(r[0]) for r in src['rows']] == R0
def rc(j):
    k = j['kind']
    if k == 'transported': return f".tr {tix[j['template']]} [{', '.join(map(str, j['sigma']))}]"
    if k == 'core': return f".co {cix[tuple(sorted(j['support']))]}"
    if k == 'cycle': return f".cy [{', '.join(map(str, j['order']))}]"
    if k == 'mirror':
        o = j['of']
        if o['kind'] == 'transported': return f".mt {tix[o['template']]} [{', '.join(map(str, o['sigma']))}]"
        if o['kind'] == 'core': return f".mc {cix[tuple(sorted(o['support']))]}"
    raise SystemExit('unknown ' + json.dumps(j)[:200])
rows = [(list(T), rc(j)) for T, j, _ in src['rows']]
CH = 100; PER = 4
chunks = [rows[i:i + CH] for i in range(0, len(rows), CH)]
nf = (len(chunks) + PER - 1) // PER
for f in range(nf):
    L = ['import RowChk.Check', '', f'/-! Generated by tools/gen_rows.py: rows {f * PER * CH} .. of R0 with certificates; kernel checks. -/', '',
         'namespace RowChk', '']
    for c in range(f * PER, min((f + 1) * PER, len(chunks))):
        ch = chunks[c]
        L.append(f'def rows{c} : List (List Nat) := [' + ', '.join('[' + ', '.join(map(str, T)) + ']' for T, _ in ch) + ']')
        L.append(f'def just{c} : List RC := [' + ', '.join(r for _, r in ch) + ']')
        L.append(f'theorem chk{c} : chkRows rows{c} just{c} = true := by decide +kernel')
        L.append('')
    L += ['end RowChk', '']
    open(D + f'lean/RowChk/Rows{f}.lean', 'w').write('\n'.join(L))
L = [f'import RowChk.Rows{f}' for f in range(nf)] + ['', '/-! Generated: R1nat and J as concatenations of the chunks. -/', '', 'namespace RowChk', '',
     'def rowChunks : List (List (List Nat) × List RC) := [' + ', '.join(f'(rows{c}, just{c})' for c in range(len(chunks))) + ']', '',
     'def R1nat : List (List Nat) := rowChunks.flatMap Prod.fst', '',
     'theorem chkAll : ∀ p ∈ rowChunks, chkRows p.1 p.2 = true := by',
     '  intro p hp',
     '  simp only [rowChunks, List.mem_cons, List.not_mem_nil, or_false] at hp',
     '  rcases hp with ' + ' | '.join('rfl' for _ in chunks),
     '  ' + ' '.join(f'· exact chk{c}' for c in range(len(chunks))).replace(' · ', '\n  · '),
     '', 'end RowChk', '']
open(D + 'lean/RowChk/RowsAll.lean', 'w').write('\n'.join(L))
print('rows', len(rows), 'chunks', len(chunks), 'files', nf)
