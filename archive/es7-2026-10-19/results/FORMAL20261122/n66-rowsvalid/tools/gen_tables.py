"""Write lean/RowChk/Tables.lean: kernel-friendly lookup tables (Nat bitmasks selected by a binary tree of `if`s)
for the six-order test (`ttRow`), the plain-domain statistics (`psRow`), the refined domains (`drRow`) and their
nonemptiness (`canRow`).  Own code, untrusted: every table entry the proofs use is checked against n66enc's
definitions by the kernel (RowChk/TabChk*.lean).  usage: python3 -I gen_tables.py"""
import sys as _sys
if '--write' not in _sys.argv:
    raise SystemExit('refusing to overwrite generated Lean files without --write (DESIGN.md §7: recompile downstream)')

import itertools
D = '/home/jay/research/data/formalize-20261122/n66-rowsvalid/'
profs = sorted([f for f in itertools.product(range(5), repeat=4) if all(f[i] >= f[i + 1] for i in range(3))],
               key=lambda f: (sum(f), f))
assert len(profs) == 70
def col(p, x): return p[x - 1] if 1 <= x <= 4 else 0
def cellIn(p, x, y): return 1 <= x <= 4 and 1 <= y <= col(p, x)
def capH(p): return sum(1 for x in p if x > 0)
def cupH(p): return p[0]
grid = [(x + 1, y + 1) for x in range(4) for y in range(4)]
def domPlain(s, t, z): return cellIn(t, *z) and not cellIn(s, *z)
def domRef(s, t, z): return domPlain(s, t, z) and z[0] <= capH(s) + 1 and z[1] <= cupH(s) + 1
def stats(u, v):
    zs = [z for z in grid if domPlain(profs[u], profs[v], z)]
    ne = bool(zs)
    mn0 = min(z[0] for z in zs) if zs else 0; mx0 = max(z[0] for z in zs) if zs else 0
    mn1 = min(z[1] for z in zs) if zs else 0; mx1 = max(z[1] for z in zs) if zs else 0
    return ne, mn0, mx0, mn1, mx1
ST = [[stats(u, v) for v in range(70)] for u in range(70)]
def tt(a, b, c):
    if len({a, b, c}) < 3: return False
    for (p, q, r, odd) in [(a, b, c, 0), (a, c, b, 1), (b, a, c, 1), (b, c, a, 0), (c, a, b, 0), (c, b, a, 1)]:
        co = 1 if odd else 0
        if ST[p][q][0] and ST[q][r][0] and ST[p][r][0]:
            mx = ST[q][r][2] if co == 0 else ST[q][r][4]
            mn = ST[p][q][1] if co == 0 else ST[p][q][3]
            if not mx <= mn: return False
    return True
ttRow = [sum(1 << (b * 70 + c) for b in range(70) for c in range(70) if tt(a, b, c)) for a in range(70)]
psRow = []
for u in range(70):
    x = 0
    for v in range(70):
        ne, mn0, mx0, mn1, mx1 = ST[u][v]
        code = int(ne) + 2 * (mn0 + 8 * (mx0 + 8 * (mn1 + 8 * mx1)))
        assert code < 65536
        x |= code << (16 * v)
    psRow.append(x)
drRow = []
for u in range(70):
    x = 0
    for v in range(70):
        for (a, b) in grid:
            if domRef(profs[u], profs[v], (a, b)): x |= 1 << (16 * v + 4 * (a - 1) + (b - 1))
    drRow.append(x)
canRow = [sum(1 << v for v in range(70) if any(domRef(profs[u], profs[v], z) for z in grid)) for u in range(70)]
print('TT true triples', sum(bin(x).count('1') for x in ttRow))

def tree(name, vals, lo=0, hi=70, ind='  '):
    if hi - lo == 1:
        return f'{vals[lo]}'
    mid = (lo + hi) // 2
    return f'(if x < {mid} then {tree(name, vals, lo, mid)} else {tree(name, vals, mid, hi)})'

L = ['/-!', '# RowChk.Tables (generated by tools/gen_tables.py; untrusted data, checked in RowChk.TabChk*)', '',
     'Row `x` (a state `< 70`) of each table is a Nat literal; `x ≥ 70` gives the last row (never used: callers check',
     '`x < 70`). Bit layout: `ttRow a` bit `70 b + c` = the six-order test `TT[a,b,c]`; `psRow u` 16 bits per `v`:',
     '`ne + 2 (mn0 + 8 (mx0 + 8 (mn1 + 8 mx1)))` of the plain domain `D(u → v)`; `drRow u` bit `16 v + 4 (a-1) + (b-1)`:',
     '`(a, b) ∈ D\'(u → v)`; `canRow u` bit `v`: `D\'(u → v) ≠ ∅`.', '-/', '', 'namespace RowChk', '']
for name, vals in [('ttRow', ttRow), ('psRow', psRow), ('drRow', drRow), ('canRow', canRow)]:
    L.append(f'def {name} (x : Nat) : Nat :=')
    L.append('  ' + tree(name, vals))
    L.append('')
L.append('end RowChk')
open(D + 'lean/RowChk/Tables.lean', 'w').write('\n'.join(L) + '\n')
print('written')
