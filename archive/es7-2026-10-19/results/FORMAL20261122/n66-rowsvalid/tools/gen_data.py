"""Write the Lean data modules of the 629 row certificates (own code; untrusted: every CNF it describes is checked
by hash against VB's certified files, M9).  Input: data/just_R0.json (tools/stats.py) and VB's job files
(vfy15/rows/jobs/*.json, *.job).  Output: lean/RowEnc/DataT.lean (421 templates), lean/RowEnc/DataC.lean
(208 cores), data/certs_manifest.tsv (index, kind, id, n, VB cnf_sha256, record cnf_sha256).
Templates are sorted by template id, cores by VB job key.  usage: python3 -I gen_data.py"""
import sys as _sys
if '--write' not in _sys.argv:
    raise SystemExit('refusing to overwrite generated Lean files without --write (DESIGN.md §7: recompile downstream)')

import json, hashlib, os
D = '/home/jay/research/data/formalize-20261122/n66-rowsvalid/'
J = '/home/jay/research/data/n66-20261113/vfy15/rows/jobs/'
src = json.load(open(D + 'data/just_R0.json'))

def lean_tests(ts):
    out = []
    for t in ts:
        if t[0] == 'empty': out.append(f'.E {t[1]} {t[2]}')
        elif t[0] == 'domain': out.append(f'.D {t[1]} {t[2]} {t[3]} {t[4]}')
        elif t[0] == 'positive': out.append(f'.P {t[1]} {t[2]} {t[3]}')
        else: raise SystemExit('bad test ' + repr(t))
    return '[' + ', '.join(out) + ']'

def lean_octs(o):
    if o is None: return 'none'
    return '(some [' + ', '.join('[' + ', '.join(map(str, e)) + ']' for e in o) + '])'

def job_key_core(c):
    T = sorted(c['support'])
    return 'C_' + hashlib.sha256(json.dumps([list(T), c.get('octs')]).encode()).hexdigest()[:16]


NCH = 4
def write_chunks(tag, pre, name, L, count):
    """Split the generated definitions (lines after the 6 header lines, two lines per item) into NCH modules
    RowEnc/Data<tag><c>.lean and an aggregator RowEnc/Data<tag>.lean defining the list `name`."""
    body = L[6:]
    assert len(body) == 2 * count
    per = (count + NCH - 1) // NCH
    for c in range(NCH):
        part = body[2 * per * c: 2 * per * (c + 1)]
        hdr = ['import RowEnc.Gen', '', f'/-! Generated by tools/gen_data.py: part {c} of the {name}. -/', '', 'namespace RowEnc', '']
        open(D + f'lean/RowEnc/Data{tag}{c}.lean', 'w').write('\n'.join(hdr + part + ['', 'end RowEnc', '']))
    agg = [f'import RowEnc.Data{tag}{c}' for c in range(NCH)] + ['', f'/-! Generated by tools/gen_data.py: the list of {name}. -/', '', 'namespace RowEnc', '',
           f'def {name} : List Cert := [' + ', '.join(f'{pre}{k}' for k in range(count)) + ']', '', 'end RowEnc', '']
    open(D + f'lean/RowEnc/Data{tag}.lean', 'w').write('\n'.join(agg))

man = []
tids = sorted(src['templates'])
L = ['import RowEnc.Gen', '', '/-! Generated by tools/gen_data.py: the 421 templates of R0 (sorted by template id). -/', '',
     'namespace RowEnc', '']
for k, tid in enumerate(tids):
    t = src['templates'][tid]
    v = json.load(open(J + 'T_' + tid + '.json'))
    job = open(J + 'T_' + tid + '.job').read().split('\n')
    assert int(job[0]) == len(t['core']) and list(map(int, job[1].split())) == t['core']
    L.append(f'/-- template {tid} -/')
    L.append(f'def tmpl{k} : Cert := .tmpl {len(t["core"])} {lean_tests(t["tests"])} {lean_octs(t.get("octs"))}')
    man.append([k, 'T', tid, len(t['core']), v['cnf_sha256'], t['cnf_sha256'], v.get('certified'), v.get('cake_exact')])
write_chunks('T', 'tmpl', 'templates', L, len(tids))

cores = sorted(src['cores'], key=job_key_core)
L = ['import RowEnc.Gen', '', '/-! Generated by tools/gen_data.py: the 208 cores of R0 (sorted by VB job key). -/', '',
     'namespace RowEnc', '']
for k, c in enumerate(cores):
    key = job_key_core(c)
    v = json.load(open(J + key + '.json'))
    T = sorted(c['support'])
    job = open(J + key + '.job').read().split('\n')
    assert int(job[0]) == len(T) and list(map(int, job[1].split())) == T and job[2] == 'all'
    L.append(f'/-- core {key} -/')
    L.append(f'def core{k} : Cert := .core [' + ', '.join(map(str, T)) + f'] {lean_octs(c.get("octs"))}')
    man.append([k, 'C', key, len(T), v['cnf_sha256'], c['cnf_sha256'], v.get('certified'), v.get('cake_exact')])
write_chunks('C', 'core', 'cores', L, len(cores))
with open(D + 'data/certs_manifest.tsv', 'w') as f:
    f.write('idx\tkind\tid\tn\tvb_cnf_sha256\trecord_cnf_sha256\tvb_certified\tvb_cake_exact\n')
    for r in man: f.write('\t'.join(map(str, r)) + '\n')
print('templates', len(tids), 'cores', len(cores), 'all VB certified', all(r[6] is True and r[7] == 1 for r in man))
