"""Write the level-15 row data and per-row certificates (own code; UNTRUSTED: every row/certificate pair is checked by
the kernel with `chkRows`, and the cube printer's row list is these very constants).
Inputs: R0_15 = n66-level15's rows_used15.txt (order kept: the trim descriptors `R k` index into it);
data/just_R15.json (tools/stats15.py: first c15 record justification per row); the certificate order of the copied
N66R15Enc.DataT*/DataC* (index -> id read from their docstrings, checked against n66-rowsvalid's certs_manifest.tsv).
Outputs (chunks of 100 rows, 4 chunks per file):
  lean/N66R15Enc/RowsD<f>.lean   Std-only, no imports: def rows<c> : List (List Nat)
  lean/N66R15Enc/RowList.lean    rowsAll (the chunk constants, in order), R1nat15 = rowsAll.flatten, toFin70, R1_15
  lean/N66R15Chk/Rows<f>.lean    def just<c> : List RC; theorem chk<c> : chkRows rows<c> just<c> = true (decide +kernel)
  lean/N66R15Chk/RowsAll.lean    rowChunks, rowChunks_fst (rfl), chkAll
  data/rows_manifest15.tsv       row index, chunk, kind, justifying cube, row
usage: python3 -I gen_rows15.py --write"""
import sys
if '--write' not in sys.argv:
    raise SystemExit('refusing to overwrite generated Lean files without --write (recompile downstream afterwards)')
import json, hashlib, re, glob, collections
D = '/home/jay/research/data/formalize-20261122/n66-l15-rows/'
RV = '/home/jay/research/data/formalize-20261122/n66-rowsvalid/'
R15F = '/home/jay/research/data/formalize-20261122/n66-level15/lean/N66E15/data/rows_used15.txt'
CH, PER = 100, 4

R15 = [tuple(map(int, l.split())) for l in open(R15F) if l.strip()]
assert len(R15) == 10859
src = json.load(open(D + 'data/just_R15.json'))
assert [tuple(r[0]) for r in src['rows']] == R15

# certificate indices from the copied data modules (docstring ids), checked against the level-14 manifest
def ids_of(kind, files):
    out = {}
    for f in files:
        txt = open(f).read()
        pat = r'/-- template ([0-9a-f]{16}) -/\ndef tmpl(\d+) :' if kind == 'T' else r'/-- core (C_[0-9a-f]{16}) -/\ndef core(\d+) :'
        for i, k in re.findall(pat, txt):
            assert int(k) not in out
            out[int(k)] = i
    return out
tid = ids_of('T', sorted(glob.glob(D + 'lean/N66R15Enc/DataT[0-9].lean')))
cid = ids_of('C', sorted(glob.glob(D + 'lean/N66R15Enc/DataC[0-9].lean')))
assert sorted(tid) == list(range(421)) and sorted(cid) == list(range(208))
man = [l.rstrip('\n').split('\t') for l in open(RV + 'data/certs_manifest.tsv')][1:]
assert {int(r[0]): r[2] for r in man if r[1] == 'T'} == tid
assert {int(r[0]): r[2] for r in man if r[1] == 'C'} == cid
assert [tid[k] for k in range(421)] == sorted(tid.values())
tix = {v: k for k, v in tid.items()}
cix = {v: k for k, v in cid.items()}
core_key = {tuple(map(int, k.split())): v for k, v in src['core_keys'].items()}

def rc(j):
    k = j['kind']
    if k == 'transported': return f".tr {tix[j['template']]} [{', '.join(map(str, j['sigma']))}]", 'tr'
    if k == 'core': return f".co {cix[core_key[tuple(sorted(j['support']))]]}", 'co'
    if k == 'cycle': return f".cy [{', '.join(map(str, j['order']))}]", 'cy'
    if k == 'mirror':
        o = j['of']
        if o['kind'] == 'transported': return f".mt {tix[o['template']]} [{', '.join(map(str, o['sigma']))}]", 'mt'
        if o['kind'] == 'core': return f".mc {cix[core_key[tuple(sorted(o['support']))]]}", 'mc'
    raise SystemExit('unknown ' + json.dumps(j)[:200])

rows = []
for T, j, cube in src['rows']:
    r, kind = rc(j)
    rows.append((list(T), r, kind, cube))
chunks = [rows[i:i + CH] for i in range(0, len(rows), CH)]
nf = (len(chunks) + PER - 1) // PER
for f in range(nf):
    cs = range(f * PER, min((f + 1) * PER, len(chunks)))
    L = [f'/-! Generated by tools/gen_rows15.py (Std-only data, no imports): chunks {cs[0]}..{cs[-1]} of the level-15 row',
         '    list R1nat15 (n66-level15 rows_used15.txt order). Checked by the kernel in N66R15Chk.Rows' + str(f) + '. -/', '',
         'namespace N66R15Enc', '']
    for c in cs:
        L.append(f'def rows{c} : List (List Nat) := [' + ', '.join('[' + ', '.join(map(str, T)) + ']' for T, _, _, _ in chunks[c]) + ']')
        L.append('')
    L += ['end N66R15Enc', '']
    open(D + f'lean/N66R15Enc/RowsD{f}.lean', 'w').write('\n'.join(L))
    K = ['import N66R15Chk.Check', f'import N66R15Enc.RowsD{f}', '',
         f'/-! Generated by tools/gen_rows15.py: certificates of chunks {cs[0]}..{cs[-1]} of R1nat15; kernel checks. -/', '',
         'namespace N66R15Chk', 'open N66R15Enc', '']
    for c in cs:
        K.append(f'def just{c} : List RC := [' + ', '.join(r for _, r, _, _ in chunks[c]) + ']')
        K.append(f'theorem chk{c} : chkRows rows{c} just{c} = true := by decide +kernel')
        K.append('')
    K += ['end N66R15Chk', '']
    open(D + f'lean/N66R15Chk/Rows{f}.lean', 'w').write('\n'.join(K))
n = len(chunks)
L = [f'import N66R15Enc.RowsD{f}' for f in range(nf)] + ['',
     '/-!',
     '# N66R15Enc.RowList: the level-15 row list from the kernel-checked chunk constants (Std-only; generated)',
     '',
     '`R1nat15` is the concatenation of the chunk constants `rows<k>` that `N66R15Chk.Rows*` check with `decide +kernel`,',
     'in the order of n66-level15\'s `rows_used15.txt` (10,859 rows). `R1_15` is the row list of the cube printer',
     '(`N66R15Enc.Print`) and of the theorem (`CubesUnsat105R`, `RowsValid R1_15`): no parsed text, nothing the kernel',
     'cannot evaluate.',
     '-/', '',
     'namespace N66R15Enc', '',
     'def rowsAll : List (List (List Nat)) := [' + ', '.join(f'rows{c}' for c in range(n)) + ']', '',
     'def R1nat15 : List (List Nat) := rowsAll.flatten', '',
     '/-- A state number as a state (`x % 70`; every row entry is below 70, checked by `chkRows`). -/',
     'def toFin70 (x : Nat) : Fin 70 := ⟨x % 70, Nat.mod_lt _ (by decide)⟩', '',
     '/-- **The level-15 row list** (10,859 supports). -/',
     'def R1_15 : List (List (Fin 70)) := R1nat15.map (·.map toFin70)', '',
     'end N66R15Enc', '']
open(D + 'lean/N66R15Enc/RowList.lean', 'w').write('\n'.join(L))
L = [f'import N66R15Chk.Rows{f}' for f in range(nf)] + ['import N66R15Enc.RowList', '',
     '/-! Generated by tools/gen_rows15.py: the chunks with their certificates, and their kernel checks. -/', '',
     'namespace N66R15Chk', 'open N66R15Enc', '',
     'def rowChunks : List (List (List Nat) × List RC) := [' + ', '.join(f'(rows{c}, just{c})' for c in range(n)) + ']', '',
     '/-- The chunk rows are exactly the constants of `N66R15Enc.rowsAll` (no `rows<k>` is unfolded). -/',
     'theorem rowChunks_fst : rowChunks.map Prod.fst = rowsAll := rfl', '',
     'theorem chkAll : ∀ p ∈ rowChunks, chkRows p.1 p.2 = true := by',
     '  intro p hp',
     '  simp only [rowChunks, List.mem_cons, List.not_mem_nil, or_false] at hp',
     '  rcases hp with ' + ' | '.join('rfl' for _ in range(n))] + [f'  · exact chk{c}' for c in range(n)] + ['', 'end N66R15Chk', '']
open(D + 'lean/N66R15Chk/RowsAll.lean', 'w').write('\n'.join(L))
with open(D + 'data/rows_manifest15.tsv', 'w') as g:
    g.write('row\tchunk\tkind\tcube\tsupport\n')
    for i, (T, r, kind, cube) in enumerate(rows):
        g.write(f'{i}\t{i // CH}\t{kind}\t{cube}\t{" ".join(map(str, T))}\n')
print('rows', len(rows), 'chunks', n, 'files', nf, 'kinds', dict(collections.Counter(k for _, _, k, _ in rows)))
