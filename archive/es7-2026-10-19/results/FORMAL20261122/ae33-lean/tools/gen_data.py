#!/usr/bin/env python3
"""Write lean/AE33Enc/Data.lean from ref/ae33.txt and ref/hashes_203.tsv (untrusted helper: the Lean constants it
writes are bound by M9, which prints them back through the exe and compares SHA-256 / pair names)."""
import sys
from pathlib import Path

D = Path(__file__).resolve().parent.parent
pts = [tuple(int(t) for t in line.split()) for line in (D / "ref/ae33.txt").read_text().splitlines() if line.strip()]
assert len(pts) == 33 and all(len(p) == 2 for p in pts)
rows = [l.split("\t") for l in (D / "ref/hashes_203.tsv").read_text().splitlines() if l and not l.startswith("#")]
pairs = [(int(r[1]), int(r[2])) for r in rows]
assert len(pairs) == 203 and all(r[0] == f"ae_d{u}_{v}" for r, (u, v) in zip(rows, pairs))
H = [14, 15, 17, 20, 23, 32, 25]  # ccw order (REC §1)
assert sorted(pairs) == sorted((u, v) for u in range(33) for v in range(u + 1, 33) if u in H or v in H)

out = []
out.append("import AE33Enc.Gen\nimport EncB.Render\n")
out.append("/-!\n# AE33Enc.Data: AE33, the 203 pairs, the bases and the printed texts (Std-only)\n")
out.append("Generated by `tools/gen_data.py` from `ref/ae33.txt` (`cb6a5327…`) and `ref/hashes_203.tsv`; bound by M9.\n-/\n")
out.append("namespace AE33\n")
out.append("/-- The 33 integer points of `ae33.txt` (AlphaEvolve's `points_7` × 10^17), in file order. -/")
out.append("@[irreducible] def ae33 : Array Pt := #[")
out.append(",\n".join(f"  ({x}, {y})" for x, y in pts) + "]\n")
out.append("/-- The 203 pairs (u, v), u < v, meeting H, in the order of `hashes_203.tsv`. -/")
out.append("@[irreducible] def pairs203 : Array (Nat × Nat) := #[")
out.append(",\n".join("  " + ", ".join(f"({u}, {v})" for u, v in pairs[i:i + 8]) for i in range(0, 203, 8)) + "]\n")
out.append("/-- H, the unique convex heptagon of AE33, in ccw order. -/")
out.append("def hept : List Nat := [" + ", ".join(map(str, H)) + "]\n")
out.append("""/-- Indices of AE33 without `u` and `v`, in increasing order. -/
def keepIdx (u v : Nat) : List Nat := (List.range 33).filter fun i => i != u && i != v

/-- The base B(u, v) = AE33 − {u, v}, labels 0..30 in file order. -/
def base (u v : Nat) : Array Pt := ((keepIdx u v).map fun i => ae33.getD i (0, 0)).toArray

def pairOfIdx (i : Nat) : Nat × Nat := pairs203.getD i (0, 0)
def baseOf (i : Nat) : Array Pt := base (pairOfIdx i).1 (pairOfIdx i).2

/-- **The text the exe prints for pair `i`** (`ae33print cnf i` writes exactly this string). -/
def cnfText (i : Nat) : String := EncB.render (numVars (baseOf i)) (cnf (baseOf i))

/-- **The 203 verdicts** (cake_lpr's `s VERIFIED UNSAT` on the file whose bytes are `cnfText i`, read through E3). -/
def TextsUnsat203 : Prop :=
  ∀ i, i < 203 → ∀ nv F, EncB.parseDimacs (cnfText i) = some (nv, F) → ¬ EncB.DimacsSatisfiable F

def CnfsUnsat203 : Prop := ∀ i, i < 203 → ¬ EncB.DimacsSatisfiable (cnf (baseOf i))

end AE33
""")
(D / "lean/AE33Enc/Data.lean").write_text("\n".join(out))
print("wrote", D / "lean/AE33Enc/Data.lean", len(pts), "points", len(pairs), "pairs")
