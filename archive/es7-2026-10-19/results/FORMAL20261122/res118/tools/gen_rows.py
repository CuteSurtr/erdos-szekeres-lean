#!/usr/bin/env python3
"""Generate lean/Res118/Rows.lean: the unit rows (rhs 1) of the residual slice trees as Lean literals.

res118-lean, 22 Nov 2026. Read-only on its inputs. The six slice row files nest (asserted below):
  s19            = [F,19], [Lo,15], P                 (P: 812 rows, the pool)
  s18-v13        = [F,18], [Lo,16], P ++ Q            (Q: 208 rows)
  b35s18-v13     = [F,18], [Lo,17], P ++ Q
  b35s19-v16     = [F,19], [Lo,16], P ++ Q ++ U       (U: 35 rows)
  b35s20-v169    = [F,20], [Lo,15], P ++ Q ++ A       (A: 970 rows)
  extra_66_55_leanrows = [F,18], [Lo,15]              (budget 33, capacity rows only)
Every listed row has rhs 1; the capacity rows are checked against the states of source-2650.json.gz.
Writes the Lean file and data/rows_manifest.json (sha256 of every input and of the output).
"""
import gzip, hashlib, json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
W = Path('/home/jay/research/data/es308-20261114/inputs')
LO = Path('/home/jay/research/lean/erdos-szekeres-lean/archive/es7-2026-10-19/results/LO33N20261113')
SRC = W / 'source-2650.json.gz'
FILES = {
    'b33s18': (LO / 'data/cert_66_55_leanrows/extra_66_55_leanrows.json', 33, 18),
    'b34s18': (W / 's18-v13/extra.json', 34, 18),
    'b34s19': (W / 's19/extra.json', 34, 19),
    'b35s18': (W / 'b35s18-v13/extra.json', 35, 18),
    'b35s19': (W / 'b35s19-v16/extra.json', 35, 19),
    'b35s20': (W / 'b35s20-v169/extra.json', 35, 20),
}
CHUNK = 128


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


raw = gzip.decompress(SRC.read_bytes())
assert hashlib.sha256(raw).hexdigest() == 'e800d5f8a6c5cc45c73ddcc1e57488f2ca8f2ffb704a1515ff7444d589c682f6'
st = json.loads(raw)['states']
F = [i for i, s in enumerate(st) if s[0] >= 5]
LOW = [i for i, s in enumerate(st) if s[0] <= 4]
assert len(F) == 84 and len(LOW) == 70

unit = {}
for k, (p, B, T) in FILES.items():
    ex = json.loads(Path(p).read_text())
    assert ex[0] == {'support': F, 'rhs': T} and ex[1] == {'support': LOW, 'rhs': B - T}, k
    rows = ex[2:]
    assert all(set(r) == {'support', 'rhs'} and r['rhs'] == 1 for r in rows), k
    for r in rows:
        s = r['support']
        assert s == sorted(set(s)) and all(type(i) is int and 0 <= i < 154 for i in s) and s, k
    unit[k] = [r['support'] for r in rows]

P = unit['b34s19']
assert unit['b33s18'] == []
assert unit['b34s18'][:len(P)] == P and unit['b34s18'] == unit['b35s18']
Q = unit['b34s18'][len(P):]
PQ = P + Q
assert unit['b35s19'][:len(PQ)] == PQ and unit['b35s20'][:len(PQ)] == PQ
U = unit['b35s19'][len(PQ):]
A = unit['b35s20'][len(PQ):]
assert (len(P), len(Q), len(U), len(A)) == (812, 208, 35, 970), (len(P), len(Q), len(U), len(A))
blocks = {'P': P, 'Q': Q, 'U': U, 'A': A}
keys = {b: {tuple(s) for s in v} for b, v in blocks.items()}
overlap = {f'{a}&{b}': len(keys[a] & keys[b]) for a in blocks for b in blocks if a < b}
union = set().union(*keys.values())


def lean_list(xs):
    return '[' + ', '.join(str(i) for i in xs) + ']'


out = ['/-', 'res118-lean (22 Nov 2026), GENERATED by tools/gen_rows.py; do not edit by hand.', '',
       'The unit rows (demand 1) of the residual slice trees, as literal supports over the 154 residual states, in',
       'file order. Each block is a contiguous piece of the row files (sha256 of the uncompressed files):']
for k, (p, B, T) in FILES.items():
    out.append(f'  {k}: {p}  {sha(p)}')
out += ['Slice row lists (after the two capacity rows (F, T), (Lo, B - T)):',
        '  b33s18: []   b34s19: rowsP   b34s18 = b35s18: rowsP ++ rowsQ',
        '  b35s19: rowsP ++ rowsQ ++ rowsU   b35s20: rowsP ++ rowsQ ++ rowsA',
        'Nothing here asserts that a row is valid; validity is the hypothesis `BlockValid` (Res118/Glue.lean).', '-/',
        '', 'namespace Res118', '']
for b, rows in blocks.items():
    names = []
    for c in range(0, len(rows), CHUNK):
        name = f'rows{b}_{c // CHUNK:02d}'
        names.append(name)
        out.append(f'/-- Block {b}, rows {c}..{min(c + CHUNK, len(rows)) - 1}. -/')
        out.append(f'def {name} : List (List Nat) := [')
        part = rows[c:c + CHUNK]
        out += ['  ' + lean_list(s) + (',' if j + 1 < len(part) else '') for j, s in enumerate(part)]
        out.append(']')
        out.append('')
    out.append(f'/-- Block {b}: {len(rows)} unit rows. -/')
    out.append(f'def rows{b} : List (List Nat) := ' + ' ++ '.join(names))
    out.append('')
out.append('end Res118')
out.append('')
dst = HERE / 'lean/Res118/Rows.lean'
dst.write_text('\n'.join(out))
man = {'source_gz': str(SRC), 'source_gz_sha256': sha(SRC), 'source_raw_sha256': hashlib.sha256(raw).hexdigest(),
       'inputs': {k: {'path': str(p), 'sha256': sha(p), 'budget': B, 'T': T, 'unit_rows': len(unit[k])}
                  for k, (p, B, T) in FILES.items()},
       'blocks': {b: len(v) for b, v in blocks.items()}, 'block_overlaps_by_support': overlap,
       'distinct_unit_rows': len(union), 'F': F, 'Lo': LOW,
       'output': str(dst), 'output_sha256': sha(dst), 'generator_sha256': sha(__file__)}
(HERE / 'data/rows_manifest.json').write_text(json.dumps(man, indent=1) + '\n')
print(json.dumps({k: v for k, v in man.items() if k not in ('F', 'Lo')}, indent=1))
