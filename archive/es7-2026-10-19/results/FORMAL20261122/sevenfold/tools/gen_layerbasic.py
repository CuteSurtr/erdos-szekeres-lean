# gen_layerbasic.py: generate src/Geo7/LayerBasic.lean from ENCBLEAN's ModelBasic.lean (mechanical renames; the
# psiLt section, which needs psi_inj/psi_pos, is dropped). Prints the source hash.
import hashlib
src = '/home/jay/research/lean/erdos-szekeres-lean/archive/es7-2026-10-19/results/ENCBLEAN/geo/ES8Geo/ModelBasic.lean'
out = '/home/jay/research/data/formalize-20261122/sevenfold/src/Geo7/LayerBasic.lean'
s = open(src).read()
print('source sha256', hashlib.sha256(s.encode()).hexdigest())
body = 'namespace EncB.Geo\n' + s.split('namespace EncB.Geo\n', 1)[1]
# drop the psiLt section
a = body.index('/-! ## The `psiLt` fields -/')
b = body.index('/-! ## The `chi` fields -/')
body = body[:a] + body[b:]
lines = [l for l in body.split('\n') if 'psiLt' not in l or not l.startswith('#print axioms')]
body = '\n'.join(lines)
rep = [('namespace EncB.Geo\n', 'namespace EncB.Geo7\n'), ('end EncB.Geo\n', 'end EncB.Geo7\n'),
       ('open ErdosSzekeres ErdosSzekeres.LayerLemma', 'open ErdosSzekeres ErdosSzekeres.LayerLemma\nopen EncB.Geo (orient_rotAbout_inv)'),
       ('PolarLabelling m t T c', 'LayerLab m t T c'),
       ('PolarLabelling.chi', 'LayerLab.chi'), ('labelling_', 'lab_'), ('#print axioms EncB.Geo.', '#print axioms EncB.Geo7.')]
for x, y in rep:
    assert x in body, x
    body = body.replace(x, y)
assert 'PolarLabelling' not in body and 'psiLt' not in body
hdr = '''import Geo7.LayerLab

/-! # The `chi` fields of the odd model from the layers of the counterexample itself

**A mechanical copy** of `ENCBLEAN/geo/ES8Geo/ModelBasic.lean` (generated by `tools/gen_layerbasic.py`, which
prints the source hash): `PolarLabelling m t T c` is replaced by `LayerLab m t T c` (no `ψ_pos`, no `ψ_inj`), the
namespace `EncB.Geo` by `EncB.Geo7`, `labelling_` by `lab_`, and the section of the four `psiLt` fields (the only
place that uses `ψ_inj`/`ψ_pos`) is dropped. No proof text was changed. G1 `lab_P_rot`, G2 `lab_P_injOn`, G3
`lab_orient_ne_zero`, `lab_chi_rot`, `lab_chi_cycle`, `lab_chi_swap`, `lab_nest`, `lab_noChain`.
-/

'''
open(out, 'w').write(hdr + body)
print('written', out)
