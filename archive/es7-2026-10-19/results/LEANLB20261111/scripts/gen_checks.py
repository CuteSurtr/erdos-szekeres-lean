#!/usr/bin/env python3
"""Write LeanLB/Check/<Name>.lean: the kernel evaluations for one point set (standard library only).

The anchor loop is split into ranges of positions so that each `decide +kernel` stays small (the
kernel caches every reduction of a declaration; one declaration for all anchors of a 64-point set
would need more than 12 GB). The ranges only affect resource use: `checkFrom_trans` and
`checkAll_of_checkFrom` (LeanLB/CheckerSound.lean) recombine them into `checkAll 6 L = true`.
"""
import os, re, sys
from math import comb
HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
SETS = [("C4N52", "lat4", "shift4"), ("C6N60", "lat6", "shift6"), ("C2N64", "latXY", "negXY"),
        ("MirN46", "latXY", "reflXY"), ("C3N61", "lat3", "mulOmega")]
BUDGET = int(os.environ.get("LB_BUDGET", "40000"))

def nat_data(name):
    txt = open(os.path.join(PKG, "LeanLB", "Data", name + ".lean")).read()
    body = txt.split("Nat : List NP := [", 1)[1].split("]", 1)[0]
    return [(int(a), int(b)) for a, b in re.findall(r"\((\d+), (\d+)\)", body)]

def ranges(N):
    cost = []
    for p in N:
        m = sum(1 for q in N if (q[1], q[0]) > (p[1], p[0]))
        cost.append(comb(m, 3) + m * m)
    out, a, acc = [], 0, 0
    for i, c in enumerate(cost):
        if acc and acc + c > BUDGET:
            out.append((a, i)); a, acc = i, 0
        acc += c
    out.append((a, len(N)))
    return out

def render(name, lat, R):
    lo = name[0].lower() + name[1:]
    N = nat_data(name)
    n = len(N)
    rg = ranges(N)
    L = []
    L.append(f"import LeanLB.Geometry\nimport LeanLB.Data.{name}\n\n")
    L.append(f"/-! Kernel evaluations for `{lo}` (`decide +kernel`; no `native_decide`). Generated by\n")
    L.append(f"`scripts/gen_checks.py` (budget {BUDGET}); the anchor loop is split into {len(rg)} ranges. -/\n\n")
    L.append("namespace LeanLB\n\nset_option maxRecDepth 100000\n\n")
    L.append(f"/-- {n} points. -/\ntheorem {lo}_len : {lo}Nat.length = {n} := by decide +kernel\n\n")
    L.append(f"/-- Distinct points, no three collinear (lattice coordinates). -/\n")
    L.append(f"theorem {lo}_gp : gpOK {lo}Nat = true := by decide +kernel\n\n")
    for k, (a, b) in enumerate(rg):
        L.append(f"theorem {lo}_dp_{k} : checkFrom 6 {lo}Nat {a} {b} = true := by decide +kernel\n")
    term = f"{lo}_dp_0"
    for k in range(1, len(rg)):
        a, b = rg[k]
        term = f"(checkFrom_trans (by decide : 0 ≤ {a}) (by decide : {a} ≤ {b})\n      {term} {lo}_dp_{k})"
    L.append(f"\n/-- No anchor starts a chain of 7 left turns: no 8 points in convex position. -/\n")
    L.append(f"theorem {lo}_dp : checkAll 6 {lo}Nat = true := by\n  apply checkAll_of_checkFrom\n")
    L.append(f"  rw [{lo}_len]\n  exact {term}\n\n")
    L.append(f"/-- The checker's coordinates are the lattice coordinates of the rows, translated. -/\n")
    L.append(f"theorem {lo}_link : {lo}Rows.map {lat} = {lo}Nat.map (unshift {lo}Shift) := by decide +kernel\n\n")
    L.append(f"/-- The rows are closed under the symmetry. -/\n")
    L.append(f"theorem {lo}_closed : ∀ w ∈ {lo}Rows, {R} w ∈ {lo}Rows := by decide +kernel\n\nend LeanLB\n")
    return "".join(L), rg

FIELD_SETS = [("C5N56", "lat5", 5, "Five", "lo5", "D5"), ("C7N64", "lat7", 7, "Seven", "lo7", "D7")]
TILT = 1

def field_data(name):
    txt = open(os.path.join(PKG, "LeanLB", "Data", name + ".lean")).read()
    body = txt.split("(Nat × Nat)) := [", 1)[1]
    return [(int(a), int(b)) for a, b in re.findall(r"\), \((\d+), (\d+)\)\)", body)]

def field_ranges(N):
    cost = []
    key = lambda p: p[1] + TILT * p[0]
    for p in N:
        m = sum(1 for q in N if key(q) > key(p) + 2 + 2 * TILT)
        cost.append(comb(m, 3) + m * m)
    out, a, acc = [], 0, 0
    for i, c in enumerate(cost):
        if acc and acc + c > BUDGET:
            out.append((a, i)); a, acc = i, 0
        acc += c
    out.append((a, len(N)))
    return out

def render_field(name, lat, m, mod, lo, D):
    lo_ = name[0].lower() + name[1:]
    N = field_data(name)
    n = len(N)
    rg = field_ranges(N)
    op = f"(opA (8 * {lo_}Mx + 8))"
    ab = f"(abA {TILT} (2 + 2 * {TILT}))"
    L = []
    L.append(f"import LeanLB.G.{mod}\nimport LeanLB.Data.{name}\n\n")
    L.append(f"/-! Kernel evaluations for `{lo_}` (`decide +kernel`; no `native_decide`). Generated by\n")
    L.append(f"`scripts/gen_checks.py` (budget {BUDGET}); the anchor loop is split into {len(rg)} ranges. -/\n\n")
    L.append("namespace LeanLB.G\n\nset_option maxRecDepth 100000\n\n")
    L.append(f"/-- {n} points. -/\ntheorem {lo_}_len : {lo_}L.length = {n} := by decide +kernel\n\n")
    L.append(f"/-- The approximations are certified. -/\n")
    L.append(f"theorem {lo_}_cert : {lo_}L.all (certOK {lo} {D} {lo_}Sc {lo_}Shift.1 {lo_}Shift.2 {lo_}Mx) = true := by\n  decide +kernel\n\n")
    L.append(f"/-- Every pair ordered, every triple decided. -/\n")
    L.append(f"theorem {lo_}_gp : gpOK {op} {ab} {lo_}L = true := by decide +kernel\n\n")
    for k, (a, b) in enumerate(rg):
        L.append(f"theorem {lo_}_dp_{k} : checkFrom {op} {ab} 6 {lo_}L {a} {b} = true := by\n  decide +kernel\n")
    term = f"{lo_}_dp_0"
    for k in range(1, len(rg)):
        a, b = rg[k]
        term = f"(checkFrom_trans (by decide : 0 ≤ {a}) (by decide : {a} ≤ {b})\n      {term} {lo_}_dp_{k})"
    L.append(f"\n/-- No anchor starts a chain of 7 left turns. -/\n")
    L.append(f"theorem {lo_}_dp : checkAll {op} {ab} 6 {lo_}L = true := by\n  apply checkAll_of_checkFrom\n")
    L.append(f"  rw [{lo_}_len]\n  exact {term}\n\n")
    L.append(f"/-- The exact coordinates are those of the rows. -/\n")
    L.append(f"theorem {lo_}_link : {lo_}L.map Prod.fst = {lo_}Rows.map {lat} := by decide +kernel\n\n")
    L.append(f"/-- The rows are closed under the cyclic shift. -/\n")
    L.append(f"theorem {lo_}_closed : ∀ w ∈ {lo_}Rows, cycShift {m} w ∈ {lo_}Rows := by decide +kernel\n\nend LeanLB.G\n")
    return "".join(L), rg

for name, lat, R in SETS:
    if len(sys.argv) > 1 and name not in sys.argv[1:]:
        continue
    text, rg = render(name, lat, R)
    open(os.path.join(PKG, "LeanLB", "Check", name + ".lean"), "w").write(text)
    print(name, len(rg), "ranges", rg)

for name, lat, m, mod, lo, D in FIELD_SETS:
    if len(sys.argv) > 1 and name not in sys.argv[1:]:
        continue
    text, rg = render_field(name, lat, m, mod, lo, D)
    open(os.path.join(PKG, "LeanLB", "Check", name + ".lean"), "w").write(text)
    print(name, len(rg), "ranges", rg)
