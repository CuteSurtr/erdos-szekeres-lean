"""Symmetries of the balanced catalog: transposition (conjugate partition) and
complementation (180-degree rotation of the complement inside the 5x5 box).
Checks exactly which rows are mapped to rows."""
import json
from common import *


def conj(f, k=5):
    # f = nonincreasing column heights (length k) of a down-set in [1..k]^2
    return tuple(sum(1 for h in f if h >= j) for j in range(1, k + 1))


def comp(f, k=5):
    return tuple(k - f[k - 1 - j] for j in range(k))


def perms(states):
    idx = {tuple(s): i for i, s in enumerate(states)}
    T = [idx[conj(tuple(s))] for s in states]
    C = [idx[comp(tuple(s))] for s in states]
    return T, C


def row_set(rows):
    return {(tuple(sorted(s)), d) for s, d in rows}


if __name__ == '__main__':
    states, rows = load(BAL_V2)
    T, C = perms(states)
    TC = [C[T[i]] for i in range(252)]
    base = rows[:2685]
    for name, p in [('T', T), ('C', C), ('TC', TC)]:
        assert sorted(p) == list(range(252))
        for nm, rr in [('base2685', base), ('all3131', rows)]:
            S = row_set(rr)
            img = {(tuple(sorted(p[i] for i in s)), d) for s, d in rr}
            print(name, nm, 'rows mapped into set:', len(img & S), 'of', len(S),
                  '| fixed states:', sum(1 for i in range(252) if p[i] == i))
    # orbits under the group generated by T and C
    seen = set(); orbits = []
    for i in range(252):
        if i in seen: continue
        orb = {i, T[i], C[i], TC[i]}
        seen |= orb; orbits.append(sorted(orb))
    print('orbits under <T,C>:', len(orbits), 'sizes', {k: sum(1 for o in orbits if len(o) == k) for k in (1, 2, 4)})
    json.dump({'T': T, 'C': C}, open('sym_perms.json', 'w'))
