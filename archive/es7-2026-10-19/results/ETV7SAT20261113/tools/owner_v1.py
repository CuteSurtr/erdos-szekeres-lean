#!/usr/bin/env python3
"""owner.py -- "owner model" CNF for the Erdos-Tuza-Valtr problem (state-indexed, 13 Nov 2026).

Setting.  S = planar point set, general position, distinct x, sorted by x, with every cap of at most
CA+1 points, every cup of at most CB+1 points and no convex G-gon.  For u<v let
d(u,v) = (E-(u,v)-1, E+(u,v)-1) in [1..CA]x[1..CB]  (E-/E+ = number of points of a longest cap/cup
ending with the pair (u,v)).  I(v) = down-set generated by {d(u,v): u<v} ("incoming state").  The map
v -> I(v) is injective (state separation), so each state has at most one OWNER.

The CNF has one block of variables per STATE (not per point).  If it is unsatisfiable together with
"at least N states are occupied", then no such S has N or more points.

Variables (semantic value for a given S in brackets):
  occ[s]            [state s has an owner]
  P[s,t]            [s,t occupied and owner(s) is left of owner(t)]        only if D'(s->t) nonempty
  Lab[s,t,z]        [P[s,t] and d(owner(s),owner(t)) = z]                  z in D'(s->t)
  cupge[s,t,k]      [P[s,t] and second coordinate of that label >= k]      (constants are folded)
  capge[s,t,k]      [P[s,t] and first coordinate >= k]
  ori[s,t,r]        [s,t,r occupied and det(p_s,p_t,p_r) > 0, index order s<t<r]
  Wu[t,x,y]         [P[t,x], P[x,y], (t,x,y) is a cup triple and d2(t,x)+1 = d2(x,y)]
  Wc[t,x,y]         [the same with cap triple and first coordinates]
  SU[b][s,j,k]      [P[s,j], P[j,k] and some b-cup starts at owner(s) and ends with the pair (j,k)]
  SC[a][s,j,k]      [the same for caps]
  U[b][s,t], K[a][s,t]   [P[s,t] and some b-cup / a-cap from owner(s) to owner(t)]
  cnt[i][j]         [at least j holes among the first i states]
Clause families: see README section 2 (each is satisfied by the semantic assignment).
"""
import itertools, sys, json, argparse, pickle, os
import cat_common


class Builder:
    def __init__(self, CA, CB, G, N, body_path, sig=True, wit=True, chains=True, fixed=True,
                 corner=True, sigmode='all'):
        self.CA, self.CB, self.G, self.N = CA, CB, G, N
        self.states, self.cells, self.capH, self.cupH, self.D = cat_common.make(CA, CB)
        self.NS = len(self.states)
        self.nv = 0
        self.names = {}
        self.nc = 0
        self.body = open(body_path, 'w')
        self.buf = []
        self.fam = {}
        self.opts = dict(sig=sig, wit=wit, chains=chains, fixed=fixed, corner=corner)

    # ---- variables / clauses
    def V(self, *name):
        v = self.names.get(name)
        if v is None:
            self.nv += 1
            v = self.nv
            self.names[name] = v
        return v

    def emit(self, lits, fam):
        out = []
        for l in lits:
            if l is True:
                return
            if l is False:
                continue
            out.append(l)
        assert out, ('empty clause', fam)
        so = set(out)
        if any(-l in so for l in out):
            return                      # tautology
        out = sorted(so, key=abs)
        self.buf.append(' '.join(map(str, out)) + ' 0\n')
        self.nc += 1
        self.fam[fam] = self.fam.get(fam, 0) + 1
        if len(self.buf) >= 200000:
            self.body.write(''.join(self.buf))
            self.buf = []

    @staticmethod
    def neg(l):
        if l is True:
            return False
        if l is False:
            return True
        return -l

    def build(self):
        CA, CB, G, N, NS, D = self.CA, self.CB, self.G, self.N, self.NS, self.D
        emit, neg, V = self.emit, self.neg, self.V
        feas = [[bool(D[s][t]) for t in range(NS)] for s in range(NS)]
        succ = [[t for t in range(NS) if feas[s][t]] for s in range(NS)]
        pred = [[s for s in range(NS) if feas[s][t]] for t in range(NS)]
        # feasible ordered triples
        triples = []
        for x in range(NS):
            for y in succ[x]:
                for z in succ[y]:
                    if feas[x][z]:
                        triples.append((x, y, z))
        self.ntriples = len(triples)

        # ---- low-level variables first, occupancy last (highest indices)
        ORI = {t: V('ori', *t) for t in itertools.combinations(range(NS), 3)}

        def orilit(x, y, z):
            t = tuple(sorted((x, y, z)))
            inv = (x > y) + (x > z) + (y > z)
            return ORI[t] if inv % 2 == 0 else -ORI[t]
        LAB = {}
        for s in range(NS):
            for t in succ[s]:
                for z in sorted(D[s][t]):
                    LAB[(s, t, z)] = V('Lab', s, t, z)
        # occupancy and order variables are created now but numbered after a gap: simply create
        OCC = [None] * NS
        PV = {}

        def thr(kind, s, t, k):
            """literal / constant for 'P[s,t] and coordinate >= k' (kind 0 = cap coord, 1 = cup coord)"""
            top = CB if kind else CA
            if k <= 1:
                return PV[(s, t)]
            if k > top:
                return False
            zs = D[s][t]
            if not any(z[kind] >= k for z in zs):
                return False
            if all(z[kind] >= k for z in zs):
                return PV[(s, t)]
            return V('cupge' if kind else 'capge', s, t, k)
        # threshold variables are created lazily by thr(); P and occ must exist first.
        for s in range(NS):
            OCC[s] = V('occ', s)
        for s in range(NS):
            for t in succ[s]:
                PV[(s, t)] = V('P', s, t)

        # ---- (P) order
        for s in range(NS):
            for t in succ[s]:
                emit([-PV[(s, t)], OCC[s]], 'P1')
                emit([-PV[(s, t)], OCC[t]], 'P1')
        for s in range(NS):
            for t in range(s + 1, NS):
                a = PV.get((s, t), False)
                b = PV.get((t, s), False)
                if a is not False and b is not False:
                    emit([-a, -b], 'P2')
                emit([-OCC[s], -OCC[t], a, b], 'P3')
        for x in range(NS):
            for y in succ[x]:
                for z in succ[y]:
                    if z == x:
                        continue
                    emit([-PV[(x, y)], -PV[(y, z)], PV.get((x, z), False)], 'P4')
        # ---- (L) labels
        for s in range(NS):
            for t in succ[s]:
                zs = sorted(D[s][t])
                for z in zs:
                    emit([-LAB[(s, t, z)], PV[(s, t)]], 'L1')
                emit([-PV[(s, t)]] + [LAB[(s, t, z)] for z in zs], 'L2')
                for z1, z2 in itertools.combinations(zs, 2):
                    emit([-LAB[(s, t, z1)], -LAB[(s, t, z2)]], 'L3')
                for kind in (0, 1):
                    top = CB if kind else CA
                    for k in range(2, top + 1):
                        l = thr(kind, s, t, k)
                        if l is False or l == PV[(s, t)]:
                            continue
                        emit([-l, PV[(s, t)]], 'T0')
                        for z in zs:
                            if z[kind] >= k:
                                emit([-LAB[(s, t, z)], l], 'T1')
                            else:
                                emit([-LAB[(s, t, z)], -l], 'T2')
        # ---- (G) growth with ceilings
        for (x, y, z) in triples:
            o = orilit(x, y, z)
            for k in range(1, CB + 1):
                emit([neg(thr(1, x, y, k)), -PV[(y, z)], -o, thr(1, y, z, k + 1)], 'Gcup')
            for k in range(1, CA + 1):
                emit([neg(thr(0, x, y, k)), -PV[(y, z)], o, thr(0, y, z, k + 1)], 'Gcap')
        # ---- (A) corner attainment
        if self.opts['corner']:
            for t in range(NS):
                for z in cat_common.corners(self.cells[t]):
                    emit([-OCC[t]] + [LAB[(s, t, z)] for s in pred[t] if z in D[s][t]], 'A')
        # ---- (W) predecessor witnesses
        if self.opts['wit']:
            byxy = {}
            for (t, x, y) in triples:
                byxy.setdefault((x, y), []).append(t)
            for x in range(NS):
                for y in succ[x]:
                    ts = byxy.get((x, y), [])
                    for kind in (0, 1):
                        top = CB if kind else CA
                        g2 = thr(kind, x, y, 2)
                        if g2 is False:
                            continue
                        ws = []
                        for t in ts:
                            w = V('Wu' if kind else 'Wc', t, x, y)
                            ws.append(w)
                            o = orilit(t, x, y)
                            emit([-w, PV[(t, x)]], 'W1')
                            emit([-w, PV[(x, y)]], 'W1')
                            emit([-w, o if kind else -o], 'W1')
                            for k in range(3, top + 1):
                                emit([-w, neg(thr(kind, x, y, k)), thr(kind, t, x, k - 1)], 'W2')
                        emit([neg(g2)] + ws, 'W3')
        # ---- (S) signotope packets and (C) chains: over feasible ordered 4-tuples
        polys = [(a, G + 2 - a) for a in range(3, CA + 2) if 3 <= G + 2 - a <= CB + 1]
        self.polys = polys
        bmax = max([b for a, b in polys], default=2)
        amax = max([a for a, b in polys], default=2)
        do_ch = self.opts['chains'] and polys
        SU = {}
        SC = {}
        if do_ch:
            for (s, j, k) in triples:
                o = orilit(s, j, k)
                if bmax >= 3:
                    SU[(3, s, j, k)] = V('SU', 3, s, j, k)
                    emit([-PV[(s, j)], -PV[(j, k)], -o, SU[(3, s, j, k)]], 'C1')
                if amax >= 3:
                    SC[(3, s, j, k)] = V('SC', 3, s, j, k)
                    emit([-PV[(s, j)], -PV[(j, k)], o, SC[(3, s, j, k)]], 'C1')
                for b in range(4, bmax + 1):
                    SU[(b, s, j, k)] = V('SU', b, s, j, k)
                for a in range(4, amax + 1):
                    SC[(a, s, j, k)] = V('SC', a, s, j, k)
        n4 = 0
        for (x, y, z) in triples:
            pxy, pyz = PV[(x, y)], PV[(y, z)]
            for w in succ[z]:
                if not (feas[x][w] and feas[y][w]):
                    continue
                n4 += 1
                pzw = PV[(z, w)]
                if self.opts['sig']:
                    q = [orilit(x, y, z), orilit(x, y, w), orilit(x, z, w), orilit(y, z, w)]
                    for a, b, c in ((0, 1, 2), (0, 1, 3), (0, 2, 3), (1, 2, 3)):
                        emit([-pxy, -pyz, -pzw, -q[a], q[b], -q[c]], 'S')
                        emit([-pxy, -pyz, -pzw, q[a], -q[b], q[c]], 'S')
                if do_ch:
                    o = orilit(y, z, w)
                    for b in range(4, bmax + 1):
                        emit([-SU[(b - 1, x, y, z)], -pzw, -o, SU[(b, x, z, w)]], 'C2')
                    for a in range(4, amax + 1):
                        emit([-SC[(a - 1, x, y, z)], -pzw, o, SC[(a, x, z, w)]], 'C2')
        self.n4 = n4
        if do_ch:
            UB = {}
            KA = {}
            for (s, j, t) in triples:
                for a, b in polys:
                    if (b, s, t) not in UB:
                        UB[(b, s, t)] = V('U', b, s, t)
                    if (a, s, t) not in KA:
                        KA[(a, s, t)] = V('K', a, s, t)
                    emit([-SU[(b, s, j, t)], UB[(b, s, t)]], 'C3')
                    emit([-SC[(a, s, j, t)], KA[(a, s, t)]], 'C3')
            for (b, s, t) in list(UB):
                for a, b2 in polys:
                    if b2 == b and (a, s, t) in KA:
                        emit([-KA[(a, s, t)], -UB[(b, s, t)]], 'C4')
        # ---- fixed states
        if self.opts['fixed']:
            st = self.states
            e0 = st.index(tuple([0] * CA))
            emit([OCC[e0]], 'F')
            if N >= 2:
                e1 = st.index(tuple([1] + [0] * (CA - 1)))
                emit([OCC[e1]], 'F')
        # ---- cardinality: at most Kh = NS - N holes (sequential counter, one-sided)
        Kh = NS - N
        assert Kh >= 0
        cnt = {}
        for i in range(1, NS + 1):
            h = -OCC[i - 1]
            for j in range(1, min(i, Kh) + 1):
                cnt[(i, j)] = V('cnt', i, j)
        for i in range(1, NS + 1):
            h = -OCC[i - 1]
            for j in range(1, min(i, Kh) + 1):
                c = cnt[(i, j)]
                if j == 1:
                    emit([-h, c], 'K')
                elif (i - 1, j - 1) in cnt:
                    emit([-h, -cnt[(i - 1, j - 1)], c], 'K')
                if (i - 1, j) in cnt:
                    emit([-cnt[(i - 1, j)], c], 'K')
            # overflow: h_i and at least Kh holes among the first i-1
            if Kh == 0:
                emit([-h], 'K')
            elif (i - 1, Kh) in cnt:
                emit([-h, -cnt[(i - 1, Kh)]], 'K')
        self.body.write(''.join(self.buf))
        self.buf = []
        self.body.close()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('CA', type=int)
    ap.add_argument('CB', type=int)
    ap.add_argument('G', type=int)
    ap.add_argument('N', type=int)
    ap.add_argument('out')
    ap.add_argument('--nosig', action='store_true')
    ap.add_argument('--nowit', action='store_true')
    ap.add_argument('--nochains', action='store_true')
    ap.add_argument('--nocorner', action='store_true')
    ap.add_argument('--names', action='store_true', help='also write out+.names.pkl')
    a = ap.parse_args()
    body = a.out + '.body'
    B = Builder(a.CA, a.CB, a.G, a.N, body, sig=not a.nosig, wit=not a.nowit, chains=not a.nochains,
                corner=not a.nocorner)
    B.build()
    with open(a.out, 'w') as f:
        f.write(f'p cnf {B.nv} {B.nc}\n')
        with open(body) as g:
            while True:
                chunk = g.read(1 << 24)
                if not chunk:
                    break
                f.write(chunk)
    os.remove(body)
    if a.names:
        with open(a.out + '.names.pkl', 'wb') as f:
            pickle.dump({'names': B.names, 'CA': a.CA, 'CB': a.CB, 'G': a.G, 'N': a.N}, f)
    print(json.dumps({'vars': B.nv, 'clauses': B.nc, 'states': B.NS, 'triples': B.ntriples,
                      'quads': B.n4, 'polys': B.polys, 'families': B.fam}))


if __name__ == '__main__':
    main()
