#!/usr/bin/env python3
"""Write the kernel proof of `V2L.leavesOf_cover` in parts (V2L/Cover/PartK.lean, V2L/Cover.lean).

  gen_cover.py ASM_DIR [--threshold T] [--parts P]

`decide +kernel` on `coverCheck (leavesOf s)` runs out of memory for large leaf lists. For a
case with more than T leaves, the proof follows the recursion of `Mir.coverAux` (split on the
first literal of the first cube, as `coverAux` does) until the restricted list has at most T
cubes or contains the empty cube; each such subtree is one `decide +kernel` theorem about
`coverAux n (restrictPath path (leavesOf s))`, and `coverAux_path` joins two subtrees. Cases
with at most T leaves are one `decide +kernel` theorem. The Python recursion only chooses the
proof shape; every fact is checked by the kernel."""
import json, os, sys
sys.setrecursionlimit(1000000)
asm = sys.argv[1]
T = int(sys.argv[sys.argv.index("--threshold") + 1]) if "--threshold" in sys.argv else 150
P = int(sys.argv[sys.argv.index("--parts") + 1]) if "--parts" in sys.argv else 8
st = json.load(open(os.path.join(asm, "status.json")))

def restrict(z, cubes):
    return [[l for l in c if l != z] for c in cubes if -z not in c]
def lst(xs): return "[" + ", ".join(map(str, xs)) + "]"

def case_thms(i, spec, cubes):
    """Lean declarations proving `coverCheck (leavesOf spec) = true` as `V2L.Cover.c<i>`."""
    out, cnt = [], [0]
    S = "(%s, %s)" % (lst(spec[0]), lst(spec[1]))
    if len(cubes) <= T:
        out.append("set_option maxHeartbeats 0 in\ntheorem c%d : coverCheck (leavesOf %s) = true := by\n  decide +kernel\n" % (i, S))
        return out, 1
    N = sum(len(c) for c in cubes) + 1
    def node(path, cs, n):
        k = cnt[0]; cnt[0] += 1
        name = "c%d_%d" % (i, k)
        stmt = "coverAux %d (restrictPath %s (leavesOf %s)) = true" % (n, lst(path), S)
        if len(cs) <= T or any(len(c) == 0 for c in cs):
            out.append("set_option maxHeartbeats 0 in\ntheorem %s : %s := by\n  decide +kernel\n" % (name, stmt))
            return name
        z = cs[0][0]
        assert z != 0 and n >= 1
        a = node(path + [z], restrict(z, cs), n - 1)
        b = node(path + [-z], restrict(-z, cs), n - 1)
        out.append("set_option maxHeartbeats 0 in\ntheorem %s : %s :=\n  coverAux_path (z := %d) (by decide +kernel) (by decide) %s %s\n" % (name, stmt, z, a, b))
        return name
    root = node([], cubes, N)
    out.append("set_option maxHeartbeats 0 in\ntheorem c%d : coverCheck (leavesOf %s) = true :=\n  coverCheck_of_coverAux (n := %d) (by decide +kernel) %s\n" % (i, S, N, root))
    return out, cnt[0]

HDR = """import V2L.Leaves
import V2L.CoverSplit

/-! Generated by `scripts/gen_cover.py` (threshold %d); do not edit by hand. -/

namespace V2L.Cover

open Mir V2L

"""
parts = [[] for _ in range(P)]; load = [0] * P; stats = []
rows = st["rows"]
order = sorted(range(len(rows)), key=lambda i: -rows[i]["leaves"])
for i in order:
    r = rows[i]
    cubes = [list(map(int, l.split()[1:-1])) for l in open(os.path.join(asm, "leaves", r["case"] + ".icnf")) if l.startswith("a")]
    thms, n = case_thms(i, (r["U"], r["L"]), cubes)
    j = min(range(P), key=lambda j: load[j])
    parts[j].append((i, thms)); load[j] += len(cubes) + 50
    stats.append((r["case"], len(cubes), n))
os.makedirs("V2L/Cover", exist_ok=True)
for j in range(P):
    with open("V2L/Cover/Part%d.lean" % j, "w") as f:
        f.write(HDR % T)
        for i, thms in sorted(parts[j]):
            f.write("".join(t + "\n" for t in thms))
        f.write("end V2L.Cover\n")
# The assembly: every case of `caseSpecs`, in order.
body = "".join("  List.forall_mem_cons.2 ⟨Cover.c%d,\n" % i for i in range(len(rows)))
with open("V2L/Cover.lean", "w") as f:
    f.write("".join("import V2L.Cover.Part%d\n" % j for j in range(P)))
    f.write("""import V2L.Facts

/-! Generated by `scripts/gen_cover.py`; do not edit by hand. -/

namespace V2L

open Mir

set_option maxRecDepth 100000 in
theorem leavesOf_cover_specs : ∀ s ∈ caseSpecs, coverCheck (leavesOf s) = true :=
%s  fun _ h => absurd h List.not_mem_nil%s

theorem leavesOf_cover_split : ∀ p ∈ caseTable, coverCheck (leavesOf p.1) = true :=
  fun p hp => leavesOf_cover_specs p.1 (List.of_mem_zip hp).1

end V2L
""" % (body, "⟩" * len(rows)))
json.dump({"threshold": T, "parts": P, "cases": [{"case": c, "leaves": n, "theorems": k} for c, n, k in stats]},
          open(os.path.join(asm, "cover_proof.json"), "w"), indent=1)
print("cases", len(stats), "theorems", sum(k for _, _, k in stats), "parts", P)
